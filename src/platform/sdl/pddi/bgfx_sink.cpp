// State words
static const uint64_t kPrimToBgfx[5] = {0, BGFX_STATE_PT_TRISTRIP, BGFX_STATE_PT_LINES, BGFX_STATE_PT_LINESTRIP,
                                        BGFX_STATE_PT_POINTS};
static const uint64_t kDepthTest[8] = {BGFX_STATE_DEPTH_TEST_NEVER, BGFX_STATE_DEPTH_TEST_ALWAYS,
                                       BGFX_STATE_DEPTH_TEST_LESS, BGFX_STATE_DEPTH_TEST_LEQUAL,
                                       BGFX_STATE_DEPTH_TEST_GREATER, BGFX_STATE_DEPTH_TEST_GEQUAL,
                                       BGFX_STATE_DEPTH_TEST_EQUAL, BGFX_STATE_DEPTH_TEST_NOTEQUAL};
static const uint32_t kStencilTest[8] = {BGFX_STENCIL_TEST_NEVER, BGFX_STENCIL_TEST_ALWAYS, BGFX_STENCIL_TEST_LESS,
                                         BGFX_STENCIL_TEST_LEQUAL, BGFX_STENCIL_TEST_GREATER,
                                         BGFX_STENCIL_TEST_GEQUAL, BGFX_STENCIL_TEST_EQUAL,
                                         BGFX_STENCIL_TEST_NOTEQUAL};
static const uint32_t kOpFailS[6] = {BGFX_STENCIL_OP_FAIL_S_KEEP, BGFX_STENCIL_OP_FAIL_S_ZERO,
                                     BGFX_STENCIL_OP_FAIL_S_REPLACE, BGFX_STENCIL_OP_FAIL_S_INCR,
                                     BGFX_STENCIL_OP_FAIL_S_DECR, BGFX_STENCIL_OP_FAIL_S_INVERT};
static const uint32_t kOpFailZ[6] = {BGFX_STENCIL_OP_FAIL_Z_KEEP, BGFX_STENCIL_OP_FAIL_Z_ZERO,
                                     BGFX_STENCIL_OP_FAIL_Z_REPLACE, BGFX_STENCIL_OP_FAIL_Z_INCR,
                                     BGFX_STENCIL_OP_FAIL_Z_DECR, BGFX_STENCIL_OP_FAIL_Z_INVERT};
static const uint32_t kOpPassZ[6] = {BGFX_STENCIL_OP_PASS_Z_KEEP, BGFX_STENCIL_OP_PASS_Z_ZERO,
                                     BGFX_STENCIL_OP_PASS_Z_REPLACE, BGFX_STENCIL_OP_PASS_Z_INCR,
                                     BGFX_STENCIL_OP_PASS_Z_DECR, BGFX_STENCIL_OP_PASS_Z_INVERT};
static const uint64_t kBlendFactor[11] = {
    BGFX_STATE_BLEND_ZERO, BGFX_STATE_BLEND_ONE, BGFX_STATE_BLEND_SRC_COLOR, BGFX_STATE_BLEND_INV_SRC_COLOR,
    BGFX_STATE_BLEND_SRC_ALPHA, BGFX_STATE_BLEND_INV_SRC_ALPHA, BGFX_STATE_BLEND_DST_ALPHA,
    BGFX_STATE_BLEND_INV_DST_ALPHA, BGFX_STATE_BLEND_DST_COLOR, BGFX_STATE_BLEND_INV_DST_COLOR,
    BGFX_STATE_BLEND_SRC_ALPHA_SAT};
static const uint64_t kBlendEquation[5] = {BGFX_STATE_BLEND_EQUATION_ADD, BGFX_STATE_BLEND_EQUATION_SUB,
                                           BGFX_STATE_BLEND_EQUATION_REVSUB, BGFX_STATE_BLEND_EQUATION_MIN,
                                           BGFX_STATE_BLEND_EQUATION_MAX};

static uint64_t stateWord(const SinkRenderState& s, uint32_t* stencil)
{
    uint64_t st = kPrimToBgfx[s.prim];
    if (s.writeMask & 1) st |= BGFX_STATE_WRITE_R;
    if (s.writeMask & 2) st |= BGFX_STATE_WRITE_G;
    if (s.writeMask & 4) st |= BGFX_STATE_WRITE_B;
    if (s.writeMask & 8) st |= BGFX_STATE_WRITE_A;
    if (s.depthTest) {
        st |= kDepthTest[s.depthFunc & 7];
        if (s.depthWrite)
            st |= BGFX_STATE_WRITE_Z;
    }
    if (s.cull == 1)
        st |= BGFX_STATE_CULL_CCW;
    else if (s.cull == 2)
        st |= BGFX_STATE_CULL_CW;
    if (s.blend)
        st |= BGFX_STATE_BLEND_FUNC(kBlendFactor[s.srcBlend], kBlendFactor[s.dstBlend]) |
              BGFX_STATE_BLEND_EQUATION(kBlendEquation[s.blendOp]);
    *stencil = BGFX_STENCIL_NONE;
    if (s.stencil) {
        *stencil = kStencilTest[s.stencilFunc & 7] | BGFX_STENCIL_FUNC_REF(s.stencilRef) |
                   BGFX_STENCIL_FUNC_RMASK(s.stencilReadMask) | kOpFailS[s.stencilOp[0] % 6] |
                   kOpFailZ[s.stencilOp[1] % 6] | kOpPassZ[s.stencilOp[2] % 6];
    }
    return st;
}

static uint32_t samplerFlags(const SinkStage& s)
{
    uint32_t flags = 0;
    switch (s.address) {
    case kAddressMirror: flags |= BGFX_SAMPLER_U_MIRROR | BGFX_SAMPLER_V_MIRROR; break;
    case kAddressClamp: flags |= BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP; break;
    case kAddressBorder: flags |= BGFX_SAMPLER_U_BORDER | BGFX_SAMPLER_V_BORDER; break;
    default: break;
    }
    if (s.minPoint)
        flags |= BGFX_SAMPLER_MIN_POINT;
    if (s.magPoint)
        flags |= BGFX_SAMPLER_MAG_POINT;
    if (s.mipPoint)
        flags |= BGFX_SAMPLER_MIP_POINT;
    return flags;
}

