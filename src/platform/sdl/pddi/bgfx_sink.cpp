// Shaders and programs
// The vertex programs' shaders, by the front end's program index (bgfx_draw.cpp kPrograms: the same order)
struct ProgramShaders {
    const char* vs;             // our shader (shaders/vp/)
    const char* fs;             // the stage shader with exactly its outputs as inputs (bgfx pairs no others)
};
static const ProgramShaders kProgramShaders[kVertexProgramCount] = {
    {"vs_vp_ff", "fs_vp_stage"},
    {"vs_vp_skin", "fs_vp_stage"},
    {"vs_vp_skin_onebone", "fs_vp_stage"},
    {"vs_vp_refract", "fs_vp_stage5"},
    {"vs_vp_skin_refract", "fs_vp_stage5"},
    {"vs_vp_simple_proximity", "fs_vp_stage3"},
    {"vs_vp_ff2s", "fs_vp_stage2s"},
};

static const char* rendererProfile()
{
    switch (bgfx::getRendererType()) {
    case bgfx::RendererType::Direct3D11:
    case bgfx::RendererType::Direct3D12: return "dxbc";
    case bgfx::RendererType::Vulkan: return "spirv";
    case bgfx::RendererType::Metal: return "metal";
    case bgfx::RendererType::OpenGL: return "glsl";
    case bgfx::RendererType::OpenGLES: return "essl";
    default: return "";
    }
}

static bgfx::ShaderHandle loadShader(const char* name)
{
#if HULK_PDDI_HOST || HULK_PDDI_EMBED_SHADERS
    const char* prof = rendererProfile();
    for (const PddiEmbeddedShader* s = g_pddi_shaders; s->name; s++)
        if (!strcmp(s->name, name) && !strcmp(s->profile, prof))
            return bgfx::createShader(bgfx::makeRef(s->data, s->size));
    logf("pddi: no %s build of shader %s: its draws are skipped\n", prof, name);
#endif
    return BGFX_INVALID_HANDLE;
}

static bool hasShader(const char* name)
{
#if HULK_PDDI_HOST || HULK_PDDI_EMBED_SHADERS
    const char* prof = rendererProfile();
    for (const PddiEmbeddedShader* s = g_pddi_shaders; s->name; s++)
        if (!strcmp(s->name, name) && !strcmp(s->profile, prof))
            return true;
#endif
    (void)name;
    return false;
}

// a program from two embedded shaders (kNone when the renderer has no build of either, or bgfx refuses the pair)
static unsigned loadProgram(const char* vsName, const char* fsName)
{
    bgfx::ShaderHandle vs = loadShader(vsName);
    bgfx::ShaderHandle fs = loadShader(fsName);
    if (!bgfx::isValid(vs) || !bgfx::isValid(fs)) {
        if (bgfx::isValid(vs))
            bgfx::destroy(vs);
        if (bgfx::isValid(fs))
            bgfx::destroy(fs);
        return kNone;
    }
    bgfx::ProgramHandle p = bgfx::createProgram(vs, fs, true);
    if (!bgfx::isValid(p)) {
        logf("pddi: program %s + %s: bgfx refused it\n", vsName, fsName);
        return kNone;
    }
    return p.idx;
}

static uint16_t programHandle(unsigned* cache, int index)
{
    if (cache[index] == kNone) {
        bgfx::ShaderHandle vs = loadShader(kProgramShaders[index].vs);
        bgfx::ShaderHandle fs = loadShader(kProgramShaders[index].fs);
        cache[index] = kNoProgram;
        if (!bgfx::isValid(vs) || !bgfx::isValid(fs)) {
            if (bgfx::isValid(vs))
                bgfx::destroy(vs);
            if (bgfx::isValid(fs))
                bgfx::destroy(fs);
        } else {
            bgfx::ProgramHandle p = bgfx::createProgram(vs, fs, true);
            if (bgfx::isValid(p))
                cache[index] = p.idx;
            else
                logf("pddi: program %s + %s: bgfx refused it\n", kProgramShaders[index].vs, kProgramShaders[index].fs);
        }
    }
    return (uint16_t)cache[index];
}

