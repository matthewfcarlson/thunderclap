// The layouts
static const bgfx::VertexLayout& vertexLayout()
{
    static bgfx::VertexLayout s_layout;
    static bool s_made;
    if (!s_made) {
        s_layout.begin()
            .add(bgfx::Attrib::Position, 3, bgfx::AttribType::Float)
            .add(bgfx::Attrib::Normal, 3, bgfx::AttribType::Float)
            .add(bgfx::Attrib::Weight, 3, bgfx::AttribType::Float)
            .add(bgfx::Attrib::Indices, 4, bgfx::AttribType::Uint8, true)
            .add(bgfx::Attrib::Color0, 4, bgfx::AttribType::Uint8, true)
            .add(bgfx::Attrib::Color1, 4, bgfx::AttribType::Uint8, true)
            .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord1, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord2, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord3, 2, bgfx::AttribType::Float)
            .end();
        s_made = true;
    }
    return s_layout;
}

static const bgfx::VertexLayout& fxLayout()
{
    static bgfx::VertexLayout s_layout;
    static bool s_made;
    if (!s_made) {
        s_layout.begin()
            .add(bgfx::Attrib::Position, 3, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord1, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord2, 2, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord3, 2, bgfx::AttribType::Float)
            .end();
        s_made = true;
    }
    return s_layout;
}

