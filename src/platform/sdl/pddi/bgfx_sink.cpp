BgfxSink::BgfxSink()
    : m_up(false), m_uVc(kNone), m_uFrag(kNone), m_whiteTex(kNone), m_generatedDraws(0), m_genericDraws(0),
      m_fxUniformK(kNone), m_offscreen(false), m_sceneFb(kNone), m_sceneColour(kNone), m_sceneDepth(kNone),
      m_copyTex(kNone), m_targetWidth(0), m_targetHeight(0), m_presentProgram(kNone), m_uPresentTex(kNone),
      m_presentTried(false), m_quadCopy(false), m_copyFb(kNone), m_prevFb(kNone), m_prevFrame(kNone)
{
    for (int i = 0; i < 4; i++)
        m_uTex[i] = kNone;
    for (int i = 0; i < 8; i++)
        m_programs[i] = kNone;
    memset(m_programCache, 0, sizeof(m_programCache));
    memset(&m_tvb, 0, sizeof(m_tvb));
    for (int i = 0; i < 3; i++)
        m_fxUniforms[i] = kNone;
    for (int i = 0; i < 4; i++)
        m_fxSamplers[i] = kNone;
    m_fxPrograms[0] = m_fxPrograms[1] = kNone;
}

// ---- life
bool BgfxSink::init(const SinkInit& in)
{
    bgfx::Init init;
    init.callback = (bgfx::CallbackI*)in.callback;
    init.type = (bgfx::RendererType::Enum)in.renderer;
    init.platformData.type = in.nativeType ? bgfx::NativeWindowHandleType::Wayland : bgfx::NativeWindowHandleType::Default;
    init.swapChain.nwh = in.nativeWindow;         // bgfx (2026): the window is the init swap chain's
    init.swapChain.ndt = in.nativeDisplay;
    init.swapChain.width = in.width;
    init.swapChain.height = in.height;
    init.reset = BGFX_RESET_VSYNC;
    if (!bgfx::init(init)) {
        logf("pddi: bgfx::init failed\n");
        return false;
    }
    m_up = true;
    logf("pddi: bgfx %s, %ux%u\n", bgfx::getRendererName(bgfx::getRendererType()), in.width, in.height);
    return true;
}

void BgfxSink::shutdown()
{
    if (!m_up)
        return;
    destroyFrameTargets();
    if (m_presentProgram != kNone)
        bgfx::destroy(bgfx::ProgramHandle{(uint16_t)m_presentProgram});
    if (m_uPresentTex != kNone)
        bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_uPresentTex});
    m_presentProgram = m_uPresentTex = kNone;
    bgfx::shutdown();
    m_up = false;
}

SinkCaps BgfxSink::caps() const
{
    SinkCaps c;
    memset(&c, 0, sizeof(c));
    const bgfx::Caps* caps = bgfx::getCaps();
    c.homogeneousDepth = caps && caps->homogeneousDepth;
    c.originBottomLeft = caps && caps->originBottomLeft;
    c.copyTakesPass = m_quadCopy;
    c.lastPass = 250;
    return c;
}

void BgfxSink::resizeBackBuffer(uint32_t width, uint32_t height)
{
    bgfx::SwapChain sc;
    sc.width = width;
    sc.height = height;
    bgfx::reset(BGFX_RESET_VSYNC, &sc);
}

// ---- the scene target, the copy texture, the present pass (G4; see bgfx_pddi.h)
void BgfxSink::destroyFrameTargets()
{
    if (m_sceneFb != kNone)
        bgfx::destroy(bgfx::FrameBufferHandle{(uint16_t)m_sceneFb});     // destroys its textures too
    destroyCopyTarget(&m_copyTex, &m_copyFb);
    destroyCopyTarget(&m_prevFrame, &m_prevFb);
    m_sceneFb = m_sceneColour = m_sceneDepth = kNone;
    m_targetWidth = m_targetHeight = 0;
}

// A texture the scene target is copied into: a blit destination, or (quad copies) a render target with a frame
// buffer of its own
unsigned BgfxSink::makeCopyTarget(unsigned w, unsigned h, unsigned* fb)
{
    *fb = kNone;
    const uint64_t clamp = BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP;
    bgfx::TextureHandle t = bgfx::createTexture2D((uint16_t)w, (uint16_t)h, false, 1, bgfx::TextureFormat::BGRA8,
                                                  (m_quadCopy ? BGFX_TEXTURE_RT : BGFX_TEXTURE_BLIT_DST) | clamp);
    if (!bgfx::isValid(t))
        return kNone;
    if (m_quadCopy) {
        bgfx::FrameBufferHandle f = bgfx::createFrameBuffer(1, &t, true);
        if (!bgfx::isValid(f)) {
            bgfx::destroy(t);
            return kNone;
        }
        *fb = f.idx;
    }
    return t.idx;
}

void BgfxSink::destroyCopyTarget(unsigned* tex, unsigned* fb)
{
    if (*fb != kNone)
        bgfx::destroy(bgfx::FrameBufferHandle{(uint16_t)*fb});          // and its texture
    else if (*tex != kNone)
        bgfx::destroy(bgfx::TextureHandle{(uint16_t)*tex});
    *tex = *fb = kNone;
}

SinkTarget BgfxSink::createCopyTarget(uint32_t width, uint32_t height)
{
    SinkTarget t;
    unsigned fb;
    t.texture = makeCopyTarget(width, height, &fb);
    t.frameBuffer = fb;
    return t;
}

void BgfxSink::destroyCopyTarget(SinkTarget* t)
{
    unsigned tex = t->texture, fb = t->frameBuffer;
    destroyCopyTarget(&tex, &fb);
    t->texture = tex;
    t->frameBuffer = fb;
}

// the framebuffer effects' targets: a colour target (clamped), its frame buffer owning it
SinkTarget BgfxSink::createRenderTarget(uint32_t w, uint32_t h)
{
    bgfx::TextureHandle t = bgfx::createTexture2D((uint16_t)(w ? w : 1), (uint16_t)(h ? h : 1), false, 1,
                                                  bgfx::TextureFormat::BGRA8,
                                                  BGFX_TEXTURE_RT | BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP);
    bgfx::FrameBufferHandle fb = bgfx::createFrameBuffer(1, &t, true);
    SinkTarget r;
    r.texture = t.idx;
    r.frameBuffer = fb.idx;
    return r;
}

void BgfxSink::destroyRenderTarget(SinkTarget* t)
{
    if (t->frameBuffer != kNone)
        bgfx::destroy(bgfx::FrameBufferHandle{(uint16_t)t->frameBuffer});
    t->texture = t->frameBuffer = kNone;
}

bool BgfxSink::frameTargets(uint32_t width, uint32_t height)
{
    if (!m_presentTried) {
        m_presentTried = true;
        const char* direct = getenv("HULK_GFX_DIRECT");        // 1: no scene target (the G3 path: no copies)
        if (direct && *direct == '1') {
            logf("pddi: HULK_GFX_DIRECT: drawing to the back buffer (no frame-buffer copies or effects)\n");
            return m_offscreen = false;
        }
        m_presentProgram = loadProgram("vs_pddi_present", "fs_pddi_present");
        if (m_presentProgram != kNone)
            m_uPresentTex = bgfx::createUniform("s_pddiPresent", bgfx::UniformType::Sampler).idx;
        else
            logf("pddi: no present program for this renderer: drawing to the back buffer (no frame-buffer copies)\n");
        const char* qc = getenv("HULK_GFX_QUAD_COPY");
        m_quadCopy = qc && *qc ? *qc == '1' : bgfx::getRendererType() == bgfx::RendererType::OpenGL;
        if (m_quadCopy)
            logf("pddi: render-target copies by quad (no blits)\n");
    }
    if (m_presentProgram == kNone)
        return m_offscreen = false;
    if (m_sceneFb != kNone && m_targetWidth == width && m_targetHeight == height)
        return m_offscreen = true;
    destroyFrameTargets();
    const uint64_t rt = BGFX_TEXTURE_RT | BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP | BGFX_SAMPLER_POINT;
    bgfx::TextureHandle colour = bgfx::createTexture2D((uint16_t)width, (uint16_t)height, false, 1,
                                                       bgfx::TextureFormat::BGRA8, rt);
    // depth + stencil: D24S8 where the renderer can render to it, else 32-bit float depth + stencil (MoltenVK and
    // Apple GPUs have no D24S8)
    const bgfx::Caps* caps = bgfx::getCaps();
    bgfx::TextureFormat::Enum depthFormat = bgfx::TextureFormat::D24S8;
    if (caps && !(caps->formats[bgfx::TextureFormat::D24S8] & BGFX_CAPS_FORMAT_TEXTURE_FRAMEBUFFER))
        depthFormat = bgfx::TextureFormat::D32FS8;
    bgfx::TextureHandle depth = bgfx::createTexture2D((uint16_t)width, (uint16_t)height, false, 1, depthFormat,
                                                      BGFX_TEXTURE_RT_WRITE_ONLY);
    bgfx::TextureHandle both[2] = {colour, depth};
    bgfx::FrameBufferHandle fb = bgfx::createFrameBuffer(2, both, true);
    if (!bgfx::isValid(fb)) {
        logf("pddi: scene target %ux%u (depth format %d): bgfx refused it: drawing to the back buffer\n", width,
             height, (int)depthFormat);
        bgfx::destroy(colour);
        bgfx::destroy(depth);
        return m_offscreen = false;
    }
    m_sceneFb = fb.idx;
    m_sceneColour = colour.idx;
    m_sceneDepth = depth.idx;
    // the copy (the game's display+0x498: the back buffer's size and format); a blit destination, sampled
    // (this bgfx has no blit capability bit: every renderer we build blits; WebGL2, G5, gets a quad copy if not)
    m_copyTex = makeCopyTarget(width, height, &m_copyFb);
    m_targetWidth = width;
    m_targetHeight = height;
    logf("pddi: scene target %ux%u (depth format %s)%s\n", width, height,
         depthFormat == bgfx::TextureFormat::D24S8 ? "D24S8" : "D32FS8", m_copyTex != kNone ? " + frame-buffer copy" : "");
    return m_offscreen = true;
}

// The previous frame for the framebuffer effects' overlay: made on first use (the frame it is first asked for has
// nothing in it yet: black, as a fresh Xbox front buffer would hold whatever was last shown); kept up to date by the
// present while it is asked for (the front end checks sceneTarget() first)
uint32_t BgfxSink::frontBuffer()
{
    if (m_prevFrame == kNone)
        m_prevFrame = makeCopyTarget(m_targetWidth, m_targetHeight, &m_prevFb);
    return m_prevFrame;
}

void BgfxSink::fullQuad(uint16_t view, unsigned srcTex, uint32_t sampler, float x0, float y0, float x1, float y1)
{
    struct V { float x, y, z, u, v; };
    static bgfx::VertexLayout s_layout;
    static bool s_made;
    if (!s_made) {
        s_layout.begin()
            .add(bgfx::Attrib::Position, 3, bgfx::AttribType::Float)
            .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
            .end();
        s_made = true;
    }
    if (bgfx::getAvailTransientVertexBuffer(4, s_layout) < 4)
        return;
    bgfx::TransientVertexBuffer tvb;
    bgfx::allocTransientVertexBuffer(&tvb, 4, s_layout);
    const bgfx::Caps* caps = bgfx::getCaps();
    bool flip = caps && caps->originBottomLeft;
    float vt = flip ? 1.0f : 0.0f, vb = flip ? 0.0f : 1.0f;
    V q[4] = {{x0, y0, 0, 0, vt}, {x1, y0, 0, 1, vt}, {x0, y1, 0, 0, vb}, {x1, y1, 0, 1, vb}};
    memcpy(tvb.data, q, sizeof(q));
    bgfx::setVertexBuffer(0, &tvb);
    bgfx::setTexture(0, bgfx::UniformHandle{(uint16_t)m_uPresentTex}, bgfx::TextureHandle{(uint16_t)srcTex},
                     sampler | BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP);
    bgfx::setState(BGFX_STATE_WRITE_RGB | BGFX_STATE_WRITE_A | BGFX_STATE_PT_TRISTRIP);
    bgfx::submit(view, bgfx::ProgramHandle{(uint16_t)m_presentProgram});
}

// A quad copy (renderers that can't blit): `srcTex` drawn 1:1 into the frame buffer `dstFb` in `view`
void BgfxSink::copyQuad(uint16_t view, unsigned srcTex, unsigned dstFb, unsigned w, unsigned h)
{
    bgfx::setViewFrameBuffer(view, bgfx::FrameBufferHandle{(uint16_t)dstFb});
    bgfx::setViewRect(view, 0, 0, (uint16_t)w, (uint16_t)h);
    bgfx::setViewClear(view, BGFX_CLEAR_NONE);
    bgfx::setViewMode(view, bgfx::ViewMode::Sequential);
    fullQuad(view, srcTex, BGFX_SAMPLER_POINT, -1.0f, 1.0f, 1.0f, -1.0f);
}

// Before bgfx::frame: the scene target onto the back buffer, a quad in the last view: 1:1 (point sampled) when the
// window has the frame's size, else scaled into the present rectangle with black bars around it (G5).
void BgfxSink::present(const SinkPresent& p)
{
    if (!m_up || !m_offscreen || m_sceneFb == kNone)
        return;
    bgfx::ViewId view = (bgfx::ViewId)kPresentView;
    if (m_prevFrame != kNone && p.keepFrontBuffer) {             // the front buffer of the next frame (a view's
        if (m_quadCopy) {                                        // blits run before its draws: the frame as drawn)
            copyQuad((uint16_t)(kPresentView - 1), m_sceneColour, m_prevFb, m_targetWidth, m_targetHeight);
        } else {
            bgfx::TextureRegion dst, srcRegion;
            dst.init(bgfx::TextureHandle{(uint16_t)m_prevFrame});
            srcRegion.init(bgfx::TextureHandle{(uint16_t)m_sceneColour});
            bgfx::blit(view, dst, srcRegion);
        }
    }
    unsigned ww = p.windowWidth ? p.windowWidth : 1, wh = p.windowHeight ? p.windowHeight : 1;
    bgfx::setViewFrameBuffer(view, BGFX_INVALID_HANDLE);
    bgfx::setViewRect(view, 0, 0, (uint16_t)ww, (uint16_t)wh);
    bgfx::setViewClear(view, p.bars ? BGFX_CLEAR_COLOR : BGFX_CLEAR_NONE, 0x000000ff);
    bgfx::setViewMode(view, bgfx::ViewMode::Sequential);
    float x0 = 2.0f * (float)p.x / (float)ww - 1.0f, x1 = 2.0f * (float)(p.x + p.w) / (float)ww - 1.0f;
    float y0 = 1.0f - 2.0f * (float)p.y / (float)wh, y1 = 1.0f - 2.0f * (float)(p.y + p.h) / (float)wh;
    fullQuad(view, m_sceneColour, p.point ? BGFX_SAMPLER_POINT : 0, x0, y0, x1, y1);
}

// ---- textures: exactly the levels the game supplies (m_mips extra ones): hasMips alone makes the full chain down
// to 1x1, and the levels nothing uploads sample as black, so far surfaces went dark (sky1). Direct3D clamps to the
// last level.
uint32_t BgfxSink::createTexture(const SinkTextureDesc& d)
{
    static const bgfx::TextureFormat::Enum kFormat[4] = {bgfx::TextureFormat::BGRA8, bgfx::TextureFormat::BC1,
                                                         bgfx::TextureFormat::BC2, bgfx::TextureFormat::BC3};
    bgfx::TextureHandle h = bgfx::createTexture2D((uint16_t)d.width, (uint16_t)d.height, d.mips > 0, 1,
                                                  kFormat[d.format & 3],
                                                  d.mips > 0 ? BGFX_TEXTURE_MIP_COUNT(d.mips + 1) : BGFX_TEXTURE_NONE);
    return h.idx;
}

bool BgfxSink::updateTexture(uint32_t texture, uint32_t level, uint32_t w, uint32_t h, const void* data,
                             uint32_t pitch, uint32_t size)
{
    const bgfx::Memory* mem = bgfx::copy(data, size);
    if (!mem)
        return false;
    bgfx::updateTexture2D(bgfx::TextureHandle{(uint16_t)texture}, 0, (uint8_t)level, 0, 0, (uint16_t)w, (uint16_t)h,
                          mem, (uint16_t)pitch);
    return true;
}

void BgfxSink::destroyTexture(uint32_t texture)
{
    if (texture != kNone)
        bgfx::destroy(bgfx::TextureHandle{(uint16_t)texture});
}

// ---- prim buffers: a static bgfx buffer the first time, a dynamic one once the buffer is written again (animated
// geometry). Ids: the bgfx handle, | kDynamic for a dynamic buffer.
uint32_t BgfxSink::updateVertexBuffer(uint32_t vb, const SinkVertexData& d)
{
    const bgfx::Memory* mem = bgfx::copy(d.vertices, (uint32_t)(sizeof(SinkVertex) * d.count));
    bool dynamic = vb != kNone && (vb & kDynamic);
    if (vb != kNone && !dynamic) {
        bgfx::destroy(bgfx::VertexBufferHandle{(uint16_t)vb});
        vb = kNone;
        dynamic = true;
    }
    if (dynamic) {
        if (vb == kNone)
            vb = bgfx::createDynamicVertexBuffer(d.count, vertexLayout()).idx | kDynamic;
        bgfx::update(bgfx::DynamicVertexBufferHandle{(uint16_t)vb}, 0, mem);
        return vb;
    }
    return bgfx::createVertexBuffer(mem, vertexLayout()).idx;
}

uint32_t BgfxSink::updateIndexBuffer(uint32_t ib, const uint16_t* indices, uint32_t count, uint32_t)
{
    const bgfx::Memory* mem = bgfx::copy(indices, 2 * count);
    bool dynamic = ib != kNone && (ib & kDynamic);
    if (ib != kNone && !dynamic) {
        bgfx::destroy(bgfx::IndexBufferHandle{(uint16_t)ib});
        ib = kNone;
        dynamic = true;
    }
    if (dynamic) {
        if (ib == kNone)
            ib = bgfx::createDynamicIndexBuffer(count).idx | kDynamic;
        bgfx::update(bgfx::DynamicIndexBufferHandle{(uint16_t)ib}, 0, mem);
        return ib;
    }
    return bgfx::createIndexBuffer(mem).idx;
}

void BgfxSink::destroyBuffers(uint32_t vb, uint32_t ib)
{
    if (vb != kNone) {
        if (vb & kDynamic)
            bgfx::destroy(bgfx::DynamicVertexBufferHandle{(uint16_t)vb});
        else
            bgfx::destroy(bgfx::VertexBufferHandle{(uint16_t)vb});
    }
    if (ib != kNone) {
        if (ib & kDynamic)
            bgfx::destroy(bgfx::DynamicIndexBufferHandle{(uint16_t)ib});
        else
            bgfx::destroy(bgfx::IndexBufferHandle{(uint16_t)ib});
    }
}

SinkVertex* BgfxSink::allocTransient(uint32_t n, uint32_t* token)
{
    if (bgfx::getAvailTransientVertexBuffer(n, vertexLayout()) < n) {
        logf("pddi: transient vertex buffer full: %d vertices dropped\n", (int)n);
        return 0;
    }
    bgfx::allocTransientVertexBuffer(&m_tvb, n, vertexLayout());
    *token = 0;
    return (SinkVertex*)m_tvb.data;
}

// ---- passes (bgfx views; sequential: draws in submission order)
void BgfxSink::setPass(const SinkPass& p)
{
    bgfx::ViewId v = (bgfx::ViewId)p.id;
    bgfx::FrameBufferHandle fb = BGFX_INVALID_HANDLE;
    if (p.target == kSinkTargetScene) {
        if (m_offscreen)
            fb.idx = (uint16_t)m_sceneFb;
    } else {
        fb.idx = (uint16_t)p.target;
    }
    bgfx::setViewFrameBuffer(v, fb);
    bgfx::setViewMode(v, bgfx::ViewMode::Sequential);
    bgfx::setViewRect(v, p.x, p.y, p.w, p.h);
    bgfx::setViewClear(v, p.clearFlags, p.clearRgba, p.clearDepth, (uint8_t)p.clearStencil);
    bgfx::touch(v);
}

// The frame so far into `dst`: a blit at the start of the pass (a view runs its blits before its clear and draws), or
// with quad copies a draw into dst's frame buffer in that pass
void BgfxSink::copyFrame(uint16_t pass, SinkTarget dst)
{
    if (!m_quadCopy) {
        bgfx::TextureRegion d, s;
        d.init(bgfx::TextureHandle{(uint16_t)dst.texture});
        s.init(bgfx::TextureHandle{(uint16_t)m_sceneColour});
        bgfx::blit((bgfx::ViewId)pass, d, s);
        return;
    }
    copyQuad(pass, m_sceneColour, dst.frameBuffer, m_targetWidth, m_targetHeight);
}

// ---- draws
bool BgfxSink::drawResources()
{
    if (m_uVc == kNone) {
        m_uVc = bgfx::createUniform("u_vc", bgfx::UniformType::Vec4, 96).idx;
        m_uFrag = bgfx::createUniform("u_pddiFrag", bgfx::UniformType::Vec4, 16).idx;
        static const char* const kSamplers[4] = {"s_pddiTex0", "s_pddiTex1", "s_pddiTex2", "s_pddiTex3"};
        for (int i = 0; i < 4; i++)
            m_uTex[i] = bgfx::createUniform(kSamplers[i], bgfx::UniformType::Sampler).idx;
        static const uint32_t white = 0xffffffffu;
        m_whiteTex = bgfx::createTexture2D(1, 1, false, 1, bgfx::TextureFormat::BGRA8, 0,
                                           bgfx::copy(&white, 4)).idx;
    }
    return true;
}

bool BgfxSink::hasVertexProgram(uint32_t vp)
{
    if (vp >= kVertexProgramCount)
        return false;
    uint16_t h = programHandle(m_programs, (int)vp);
    return h != kNoProgram && h != kNone;
}

// The program for a vertex program and a combiner key: the generated fragment program of the key
// (fs_cmb_<hash>, shaders/vp/combiners.txt) for the vertex programs with all seven outputs, else the generic
// combiner of the program's output set (the stages as uniforms). Cached per (vertex program, key hash).
uint16_t BgfxSink::combinerProgram(int vp, const char* key, uint32_t hash, bool forceGeneric, bool* generic)
{
    if (forceGeneric) {
        *generic = true;
        return programHandle(m_programs, vp);
    }
    if (!hash)
        hash = 1;
    unsigned slot = (hash + (unsigned)vp * 0x9e3779b1u) & (kProgramSlots - 1);
    for (int probe = 0; probe < kProgramSlots; probe++, slot = (slot + 1) & (kProgramSlots - 1)) {
        ProgramSlot& e = m_programCache[slot];
        if (e.hash == hash && e.vp == (uint16_t)vp) {
            *generic = e.generic;
            return e.generic ? programHandle(m_programs, vp) : e.program;
        }
        if (e.hash)
            continue;
        e.hash = hash;
        e.vp = (uint16_t)vp;
        e.generic = true;
        e.program = kNone;
        char name[24] = "fs_cmb_";
        static const char kHex[] = "0123456789abcdef";
        for (int i = 0; i < 8; i++)
            name[7 + i] = kHex[(hash >> (28 - 4 * i)) & 15];
        name[15] = 0;
        if (!strcmp(kProgramShaders[vp].fs, "fs_vp_stage") && hasShader(name)) {
            bgfx::ShaderHandle vs = loadShader(kProgramShaders[vp].vs);
            bgfx::ShaderHandle fs = loadShader(name);
            if (bgfx::isValid(vs) && bgfx::isValid(fs)) {
                bgfx::ProgramHandle ph = bgfx::createProgram(vs, fs, true);
                if (bgfx::isValid(ph)) {
                    e.program = ph.idx;
                    e.generic = false;
                } else {
                    logf("pddi: program %s + %s: bgfx refused it (generic combiner instead)\n",
                         kProgramShaders[vp].vs, name);
                }
            } else {
                if (bgfx::isValid(vs))
                    bgfx::destroy(vs);
                if (bgfx::isValid(fs))
                    bgfx::destroy(fs);
            }
        } else if (!strcmp(kProgramShaders[vp].fs, "fs_vp_stage")) {
            static int s_logged;
            if (s_logged++ < 32)
                logf("pddi: combiner %s (%s) has no generated program: the generic combiner draws it "
                     "(tools/native_gfx.py combiners)\n", key, name);
        }
        *generic = e.generic;
        return e.generic ? programHandle(m_programs, vp) : e.program;
    }
    *generic = true;
    return programHandle(m_programs, vp);
}

bool BgfxSink::preparePipeline(DrawPacket& p)
{
    bool generic;
    uint16_t prog = combinerProgram((int)p.vertexProgram, p.combinerKey, p.combinerHash, p.forceGeneric != 0, &generic);
    if (prog == kNoProgram || prog == kNone)
        return false;
    if (generic)
        m_genericDraws++;
    else
        m_generatedDraws++;
    p.pipeline = prog;
    p.generic = generic ? 1 : 0;
    return true;
}

void BgfxSink::submitDraw(const DrawPacket& p)
{
    bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_uVc}, p.vertexConstants, (uint16_t)p.vertexConstantCount);
    // the stage textures (an empty stage samples white), with the stage's addressing and filtering
    for (int i = 0; i < 4; i++) {
        const SinkStage& s = p.stage[i];
        uint16_t th = s.texture != kNone ? (uint16_t)s.texture : (uint16_t)m_whiteTex;
        bgfx::setTexture((uint8_t)i, bgfx::UniformHandle{(uint16_t)m_uTex[i]}, bgfx::TextureHandle{th},
                         samplerFlags(s));
    }
    bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_uFrag}, p.frag, 16);
    uint32_t stencil;
    uint64_t st = stateWord(p.state, &stencil);
    bgfx::setState(st);
    bgfx::setStencil(stencil);
    if (p.transient != kNone) {
        bgfx::setVertexBuffer(0, &m_tvb);
    } else {
        if (p.vertexBuffer & kDynamic)
            bgfx::setVertexBuffer(0, bgfx::DynamicVertexBufferHandle{(uint16_t)p.vertexBuffer}, 0, p.vertexCount);
        else
            bgfx::setVertexBuffer(0, bgfx::VertexBufferHandle{(uint16_t)p.vertexBuffer}, 0, p.vertexCount);
        if (p.indexBuffer != kNone) {
            if (p.indexBuffer & kDynamic)
                bgfx::setIndexBuffer(bgfx::DynamicIndexBufferHandle{(uint16_t)p.indexBuffer}, 0, p.count);
            else
                bgfx::setIndexBuffer(bgfx::IndexBufferHandle{(uint16_t)p.indexBuffer}, 0, p.count);
        }
    }
    if (p.query != kNone)                     // inside a visibility test: the draw is the query
        bgfx::submit((bgfx::ViewId)p.pass, bgfx::ProgramHandle{(uint16_t)p.pipeline},
                     bgfx::OcclusionQueryHandle{(uint16_t)p.query});
    else
        bgfx::submit((bgfx::ViewId)p.pass, bgfx::ProgramHandle{(uint16_t)p.pipeline});
}

void BgfxSink::combinerStats(int* generated, int* generic, int* draws)
{
    *generated = *generic = 0;
    for (int i = 0; i < kProgramSlots; i++)
        if (m_programCache[i].hash)
            ++*(m_programCache[i].generic ? generic : generated);
    draws[0] = (int)m_generatedDraws;
    draws[1] = (int)m_genericDraws;
}

// ---- the full-screen passes
bool BgfxSink::fxResources()
{
    if (m_fxUniforms[0] == kNone) {
        m_fxUniforms[0] = bgfx::createUniform("u_fxC", bgfx::UniformType::Vec4, 8).idx;
        m_fxUniforms[1] = bgfx::createUniform("u_fxProg", bgfx::UniformType::Vec4).idx;
        m_fxUniforms[2] = bgfx::createUniform("u_fxTarget", bgfx::UniformType::Vec4).idx;
        static const char* const kS[4] = {"s_fx0", "s_fx1", "s_fx2", "s_fx3"};
        for (int i = 0; i < 4; i++)
            m_fxSamplers[i] = bgfx::createUniform(kS[i], bgfx::UniformType::Sampler).idx;
        m_fxUniformK = bgfx::createUniform("u_fxK", bgfx::UniformType::Vec4).idx;
        m_fxPrograms[0] = loadProgram("vs_fx", "fs_fx_filter");
        m_fxPrograms[1] = loadProgram("vs_fx", "fs_fx_blur");
        if (m_fxPrograms[0] == kNone || m_fxPrograms[1] == kNone)
            logf("pddi: framebuffer effects: no pass programs for this renderer: the passes are skipped\n");
    }
    return m_fxPrograms[0] != kNone && m_fxPrograms[1] != kNone;
}

// One quad of a pass. Renderers with the origin at the bottom left sample targets upside down: v flipped.
void BgfxSink::fxDraw(const FxPacket& p)
{
    if (bgfx::getAvailTransientVertexBuffer(4, fxLayout()) < 4)
        return;
    bgfx::TransientVertexBuffer tvb;
    bgfx::allocTransientVertexBuffer(&tvb, 4, fxLayout());
    const bgfx::Caps* caps = bgfx::getCaps();
    bool flip = caps && caps->originBottomLeft;
    float* v = (float*)tvb.data;
    for (int i = 0; i < 4; i++, v += 11) {
        bool right = (i & 1) != 0, bottom = (i & 2) != 0;
        v[0] = right ? p.x1 : p.x0;
        v[1] = bottom ? p.y1 : p.y0;
        v[2] = 0.0f;
        for (int s = 0; s < 4; s++) {
            v[3 + 2 * s] = right ? p.uv[s][2] : p.uv[s][0];
            float tv = bottom ? p.uv[s][3] : p.uv[s][1];
            v[4 + 2 * s] = flip ? 1.0f - tv : tv;
        }
    }
    float target[4] = {2.0f / (float)(p.targetWidth ? p.targetWidth : 1),
                       2.0f / (float)(p.targetHeight ? p.targetHeight : 1), 0.0f, 0.0f};
    bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_fxUniforms[2]}, target);
    bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_fxUniforms[0]}, p.consts, 8);
    bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_fxUniforms[1]}, p.prog);
    uint16_t program = (uint16_t)m_fxPrograms[p.program == kFxFilter ? 0 : 1];
    if (program == m_fxPrograms[0])
        bgfx::setUniform(bgfx::UniformHandle{(uint16_t)m_fxUniformK}, p.prog + 4);
    for (uint32_t i = 0; i < p.textures && i < 4; i++)
        bgfx::setTexture((uint8_t)i, bgfx::UniformHandle{(uint16_t)m_fxSamplers[i]},
                         bgfx::TextureHandle{(uint16_t)p.texture[i]}, BGFX_SAMPLER_U_CLAMP | BGFX_SAMPLER_V_CLAMP);
    bgfx::setVertexBuffer(0, &tvb);
    uint64_t state = 0;
    if (p.state & kFxWriteRgb)
        state |= BGFX_STATE_WRITE_RGB;
    if (p.state & kFxWriteAlpha)
        state |= BGFX_STATE_WRITE_A;
    if (p.state & kFxBlendAdd)
        state |= BGFX_STATE_BLEND_FUNC(BGFX_STATE_BLEND_ONE, BGFX_STATE_BLEND_ONE);
    bgfx::setState(state | BGFX_STATE_PT_TRISTRIP);
    bgfx::submit((bgfx::ViewId)p.pass, bgfx::ProgramHandle{program});
}

// ---- occlusion queries
uint32_t BgfxSink::createQuery()
{
    bgfx::OcclusionQueryHandle h = bgfx::createOcclusionQuery();
    return bgfx::isValid(h) ? h.idx : kNone;
}

uint32_t BgfxSink::queryResult(uint32_t query, int32_t* pixels)
{
    bgfx::OcclusionQueryResult::Enum r = bgfx::getResult(bgfx::OcclusionQueryHandle{(uint16_t)query}, pixels);
    if (r == bgfx::OcclusionQueryResult::Visible)
        return kQueryVisible;
    if (r == bgfx::OcclusionQueryResult::Invisible)
        return kQueryInvisible;
    return kQueryPending;
}

// ---- the context's resources, at its destruction
void BgfxSink::contextDestroyed()
{
    for (int i = 0; i < 8; i++)
        if (m_programs[i] != kNone && m_programs[i] != kNoProgram)
            bgfx::destroy(bgfx::ProgramHandle{(uint16_t)m_programs[i]});
    for (int i = 0; i < kProgramSlots; i++)
        if (m_programCache[i].hash && !m_programCache[i].generic && m_programCache[i].program != kNone &&
            m_programCache[i].program != kNoProgram)
            bgfx::destroy(bgfx::ProgramHandle{m_programCache[i].program});
    if (m_uVc != kNone) {
        bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_uVc});
        bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_uFrag});
        for (int i = 0; i < 4; i++)
            bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_uTex[i]});
        bgfx::destroy(bgfx::TextureHandle{(uint16_t)m_whiteTex});
    }
    if (m_fxUniforms[0] != kNone) {
        for (int i = 0; i < 3; i++)
            bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_fxUniforms[i]});
        bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_fxUniformK});
        for (int i = 0; i < 4; i++)
            bgfx::destroy(bgfx::UniformHandle{(uint16_t)m_fxSamplers[i]});
        for (int i = 0; i < 2; i++)
            if (m_fxPrograms[i] != kNone)
                bgfx::destroy(bgfx::ProgramHandle{(uint16_t)m_fxPrograms[i]});
    }
    for (int i = 0; i < 8; i++)
        m_programs[i] = kNone;
    memset(m_programCache, 0, sizeof(m_programCache));
    m_uVc = m_uFrag = m_whiteTex = kNone;
    for (int i = 0; i < 4; i++)
        m_uTex[i] = m_fxSamplers[i] = kNone;
    for (int i = 0; i < 3; i++)
        m_fxUniforms[i] = kNone;
    m_fxUniformK = m_fxPrograms[0] = m_fxPrograms[1] = kNone;
}

DrawSink* bgfxSink()
{
    static BgfxSink* s_sink;              // made on first use, never destroyed (no static constructor or atexit)
    if (!s_sink)
        s_sink = new BgfxSink();
    return s_sink;
}

