#!/usr/bin/env python3
"""The XDK shim's tables bound by name, on a linked image (tools/native_bind.py XdkTable; docs/native-android.md
section 15).

  build/venv/bin/python tests/native_host/xdk_bind_test.py --target mac            # arm64 macOS: link and run
  build/venv/bin/python tests/native_host/xdk_bind_test.py --target linux-x64      # lld link, checked from the image
  build/venv/bin/python tests/native_host/xdk_bind_test.py --target android-arm64  # (NDK) lld link, from the image
  # --no-bind: the control (the link without native_bind): must FAIL, which shows the test sees a wrong binding
  # --map BINDINGS.json: also check the rule on the names a real tree spells (a Wine build's binding map, below)

A stand-in game TU (generated from src/platform/sdl/xdk/imports.h and library.h) names every row the ways the tree
does: `FUN_<addr>` as a C name and inside an MS name (`?FUN_0020c14b@fn_bindtest@@...`), `thunk_FUN_<addr>`, the
import's own name as a C name and as an MS free function in a namespace (`?ConvertThreadToFiber@XAPILIB@@...`), and
each library data row by `DAT_<addr>` at its start, one word in and its last word (C and MS names). It goes through
the tree's pipeline (the MS-ABI front end, the target's retarget, its backend), native_bind binds the object, and it
links with the shim in its stand-in configuration (the ELF images' configuration; the macOS image adds the SDL3
backends, which define the same hulk_xdk_* names) and a checker. Every entry must be the address of the row's
definition: `hulk_xdk_<name>` / `hulk_lib_<name>`, or the data row's symbol plus the offset. On macOS the checker
runs; on the ELF targets the slots are read from the image's dynamic relocations (crt_bind_test.elf_slots).

Names that must NOT bind (plan level): a member function and a variable named like an import, a template, a data name
at a function row's address, and an address outside every row.

--map: every name of a Wine build's binding map (`bindings`: 32-bit name -> address) that the XDK rule binds, made
64-bit (the 32-bit MS name's `@@YG` / `@@YI` / `@@YA` free-function code and a C name's `_name@N` decoration), must be
bound by the map to that row's address; and every map name bound to a row's address is either bound by the rule
or listed (the game-source names the rule cannot know: the unb lineage's naming work). Exit 0 when all hold.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import clang_probe as cp  # noqa: E402
import native_bind as nb  # noqa: E402
import native_mac as nmac  # noqa: E402
from crt_bind_test import FRONT, elf_slots, run  # noqa: E402

HOST = ["src/platform/sdl/host/win32_posix.cpp", "src/platform/sdl/host/crt_posix.cpp",
        "src/platform/sdl/host/rtti_msabi.cpp", "src/platform/sdl/crt/softx87.cpp"]


def cases(x):
    """[(key, name, expected symbol, offset)] read off the tables here (not through XdkTable.target)."""
    out = []
    for a, (tgt, _k, n) in sorted(x.funcs.items()):
        out.append(("c", "FUN_%08x" % a, tgt, 0))
        out.append(("mangled-fn", "FUN_%08x" % a, tgt, 0))
        out.append(("mangled-fn", "thunk_FUN_%08x" % a, tgt, 0))
    first = {}
    for a, (tgt, _k, n) in sorted(x.funcs.items()):
        if n not in nb.NAME_RULE_EXCEPT:
            first.setdefault(n, tgt)
    for n, tgt in sorted(first.items()):
        out.append(("c", n, tgt, 0))
        out.append(("ns-fn", n, tgt, 0))
    for a, s, size in x.data:
        for off in sorted({0, 4, size - 4} if size > 4 else {0}):
            out.append(("c-data", "DAT_%08x" % (a + off), s, off))
            out.append(("mangled-data", "DAT_%08x" % (a + off), s, off))
    return out


NEGATIVE = sorted(nb.NAME_RULE_EXCEPT) + ["?Sleep@Obj@@QEAAXH@Z", "?XInputGetState@@3HA", "?CreateFiber@?$Box@H@@YAXXZ",
            "?DAT_0020c14b@fn_bindtest@@3HA", "?DAT_0039db04@fn_bindtest@@3PEBXEB", "FUN_00100000", "DAT_00100000", "XInputGetStateX"]


def prefix(key):
    return {"mangled-fn": "fn_bindtest::", "mangled-data": "fn_bindtest::", "ns-fn": "XAPILIB::"}.get(key, "")


def game_tu(cs):
    L = ["// generated by tests/native_host/xdk_bind_test.py", 'extern "C" {']
    seen = set()
    for key, n, _t, _o in cs:
        if (key, n) in seen or key not in ("c", "c-data"):
            continue
        seen.add((key, n))
        L.append("void %s();" % n if key == "c" else "extern char %s[];" % n)
    L.append("}")
    for ns, keys in (("fn_bindtest", ("mangled-fn", "mangled-data")), ("XAPILIB", ("ns-fn",))):
        L.append("namespace %s {" % ns)
        for key, n, _t, _o in cs:
            if key in keys and (key, n) not in seen:
                seen.add((key, n))
                L.append("int %s(void*, int, const char*);" % n if key != "mangled-data" else "extern int %s;" % n)
        L.append("}")
    refs = ["(void*)&%s%s" % (prefix(k), n) for k, n, _t, _o in cs]
    L.append('extern "C" void* const hulk_bind_refs[] = {\n    ' + ",\n    ".join(refs) + "\n};")
    L.append('extern "C" const unsigned hulk_bind_count = %d;' % len(cs))
    return "\n".join(L) + "\n"


def checker_cpp(cs, orig=()):
    syms = sorted({t for _k, _n, t, _o in cs})
    L = ["// generated by tests/native_host/xdk_bind_test.py", "#include <stdio.h>", "#include <stdlib.h>",
         'extern "C" {', "extern void* const hulk_bind_refs[];", "extern const unsigned hulk_bind_count;"]
    L += ["extern char %s;" % s for s in syms]
    L += ['void hulk_native_log(const char* line) { (void)line; }',
          'void hulk_native_missing(const char* name) { fprintf(stderr, "missing %s\\n", name); exit(3); }']
    L += ["unsigned long long %s(void) { return 0; }" % o for o in orig]
    L += ["}"]
    L.append("struct Want { const char* name; const char* target; unsigned off; const char* at; };")
    L.append("static const Want W[] = {")
    for k, n, t, o in cs:
        L.append('    {"%s%s", "%s", %du, &%s + %d},' % (prefix(k), n, t, o, t, o))
    L.append("};")
    L.append(r'''
int main() {
    unsigned n = sizeof(W) / sizeof(W[0]), bad = 0;
    if (n != hulk_bind_count) { printf("table size %u, game side %u\n", n, hulk_bind_count); return 2; }
    for (unsigned i = 0; i < n; i++)
        if (hulk_bind_refs[i] != (const void*)W[i].at) {
            bad++;
            printf("FAIL %-48s -> %p, want %s+%u %p\n", W[i].name, hulk_bind_refs[i], W[i].target, W[i].off, W[i].at);
        }
    printf("%u names, %u bound right, %u wrong\n", n, n - bad, bad);
    return bad ? 1 : 0;
}''')
    return "\n".join(L) + "\n"


def map_check(path, x):
    """The rule on a real tree's names (a Wine build's binding map: its names are the 32-bit spellings)."""
    b = json.load(open(path))["bindings"]
    by_target = {}
    for a, (tgt, _k, _n) in x.funcs.items():
        by_target[tgt] = a
    for da, ds, _n in x.data:
        by_target[ds] = da
    wrong, bound, unnamed = [], 0, []
    for s, v in sorted(b.items()):
        a = int(v["addr"], 16)
        s64 = re.sub(r"@@Y[GIA]", "@@YA", s) if s.startswith("?") else re.sub(r"^_(\w+?)(?:@\d+)?$", r"\1", s)
        tgt, _how = x.target(s64)
        row = x.funcs.get(a)
        if tgt:
            base, off = x.aliases.get(tgt, (tgt, 0))
            at = by_target.get(base)
            bound += 1
            if at is None or at + off != a:
                wrong.append("%s: the rule binds %s (%s), the map 0x%08x" % (
                    s, tgt, "0x%08x" % (at + off) if at is not None else "?", a))
        elif row:
            unnamed.append((row[2], s))
    return bound, wrong, unnamed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", default="mac", choices=["mac", "linux-x64", "android-arm64"])
    ap.add_argument("--out", help="work directory (default build/a2s2/xdk-bind-<target>)")
    ap.add_argument("--no-bind", action="store_true", help="the control: link without native_bind (must fail)")
    ap.add_argument("--map", help="a Wine build's bindings.json: check the rule on the names it binds")
    a = ap.parse_args()
    out = a.out or os.path.join(ROOT, "build/a2s2/xdk-bind-%s%s" % (a.target, "-nobind" if a.no_bind else ""))
    os.makedirs(out, exist_ok=True)
    t = nb.Table()
    x = t.xdk
    rc = 0
    bad_neg = [s for s in NEGATIVE if t.target(s)[0]]
    if bad_neg:
        print("FAIL names that must not bind are bound: %s" % ", ".join("%s -> %s" % (s, t.target(s)[0])
                                                                         for s in bad_neg))
        rc = 1
    if a.map:
        bound, wrong, unnamed = map_check(a.map, nb.XdkTable())   # (its own aliases: not the link's)
        print("map %s: %d names the rule binds, %d bound elsewhere by the map; %d map names of import rows the rule "
              "does not bind (game-source names):" % (os.path.relpath(a.map, ROOT), bound, len(wrong), len(unnamed)))
        for w in wrong:
            print("  FAIL " + w)
        for n, s in sorted(unnamed):
            print("  unnamed %-40s %s" % (n, s))
        rc = rc or (1 if wrong else 0)
    cs = cases(x)
    with open(os.path.join(out, "game.cpp"), "w") as f:
        f.write(game_tu(cs))
    game_ll, game_t, game_o = (os.path.join(out, n) for n in ("game.ll", "game.t.ll", "game.o"))
    if a.target == "mac":
        fmt = "macho"
        run([cp.tool("clang++"), "--target=aarch64-pc-windows-msvc"] + FRONT + [os.path.join(out, "game.cpp"), "-o",
                                                                                  game_ll], "front end")
        open(game_t, "w", errors="surrogateescape").write(nmac.retarget(open(game_ll, errors="surrogateescape").read()))
        run([cp.tool("clang")] + nmac.BACK + [game_t, "-o", game_o], "backend")
        game_syms = nmac.nm_macho([game_o])
    else:
        import native_elf as ne
        tc = ne.Toolchain(a.target)
        fmt = "elf"
        run(tc.cxx + ["--target=" + ne.TARGETS[a.target]["front"]] + FRONT + [os.path.join(out, "game.cpp"), "-o",
                                                                              game_ll], "front end")
        open(game_t, "w", errors="surrogateescape").write(
            ne.retarget_elf(open(game_ll, errors="surrogateescape").read(), tc))
        run(tc.cc + ne.flags(a.target)[1] + [game_t, "-o", game_o], "backend")
        game_syms = ne.nm_elf([game_o], tc.nm)
    undef = set().union(*(u for _d, u in game_syms.values())) - set().union(*(d for d, _u in game_syms.values()))
    binding = nb.plan(undef, t)
    unbound = sorted(n for n in undef if n not in binding)
    if unbound:
        print("FAIL native_bind.plan does not bind %d names: %s" % (len(unbound), ", ".join(unbound[:20])))
        rc = 1
    # the shim (stand-ins) with the aliases this binding made, and the host layer it calls
    if a.target == "mac":
        shim, _lf, errs, cfg = nb.macos_shim_objects(os.path.join(out, "shim"), x.aliases, sdl=False)
        host, errs2 = nb.macos_host_objects(os.path.join(out, "host"), HOST)
        host_syms = nmac.nm_macho(shim + host)
    else:
        shim, _lf, errs, _cfg = ne.build_shim(tc, os.path.join(out, "shim"), x.aliases, sdl=False)   # (stand-ins)
        host, errs2 = [], {}
        hd = os.path.join(out, "host")
        os.makedirs(hd, exist_ok=True)
        for src in HOST:
            o = os.path.join(hd, os.path.basename(src) + ".o")
            r = subprocess.run(tc.cxx + tc.host_flags() + ["-I" + os.path.join(ROOT, "src/platform/sdl"), "-c",
                                                           os.path.join(ROOT, src), "-o", o], capture_output=True, text=True)
            (errs2.__setitem__(src, r.stderr[-1500:]) if r.returncode else host.append(o))
        host_syms = ne.nm_elf(shim + host, tc.nm)
    if errs or errs2:
        sys.exit("shim / host layer failed: %s" % json.dumps(dict(errs, **errs2), indent=1)[:4000])
    # the shim's calls into the game by address (timing.cpp's FUN_00267f40, ...): null functions in the checker
    host_def = set().union(*(d for d, _u in host_syms.values()))
    orig = sorted({u for _d, us in host_syms.values() for u in us if nb.ORIG.match(u)} - host_def)
    with open(os.path.join(out, "check.cpp"), "w") as f:
        f.write(checker_cpp(cs, orig))
    if a.no_bind:
        objs, bst = [game_o], {}
    else:
        objs, bst = nb.apply([game_o], binding, game_syms, os.path.join(out, "bound"), fmt)
    bound_syms = nmac.nm_macho(objs) if fmt == "macho" else ne.nm_elf(objs, tc.nm)
    sysdef = nb.macos_system_names() if a.target == "mac" else None
    st, problems = nb.check(binding, bound_syms, host_syms, (), sysdef, t)
    print("native_bind: %s; apply %s; library data aliases %d" % (json.dumps(st), json.dumps(bst), len(x.aliases)))
    for p in problems[:40]:
        print("  check: " + p)
    image = os.path.join(out, "xdk_bind")
    if a.no_bind:   # the names nobody defines: stubs (16 zero bytes each), as the link before the XDK table
        hd = set().union(*(d for d, _u in host_syms.values()))
        sp = os.path.join(out, "stubs.s")
        with open(sp, "w") as f:
            for n in sorted(undef - hd):
                q = nb.spell(n, fmt)
                f.write('\t.data\n\t.globl "%s"\n"%s":\n\t.space 16\n' % (q, q))
        so = sp + ".o"
        run((["xcrun", "clang", "-arch", "arm64"] if fmt == "macho" else tc.cc + ["--target=" + tc.triple, "-fPIC"])
            + ["-c", sp, "-o", so], "stubs")
        objs = objs + [so]
    if a.target == "mac":
        run(["xcrun", "clang++", "-arch", "arm64", "-std=c++17", "-O1", "-w", "-mmacosx-version-min=" + nmac.MACOS_MIN,
             os.path.join(out, "check.cpp")] + objs + shim + host + ["-o", image], "link")
        r = subprocess.run([image], capture_output=True, text=True)
        print((r.stdout + r.stderr)[-4000:])
        rc = rc or r.returncode
    else:
        chk = os.path.join(out, "check.o")
        run(tc.cxx + tc.host_flags() + ["-w", "-c", os.path.join(out, "check.cpp"), "-o", chk], "checker")
        cmd = tc.cxx + tc.host_flags() + ["-pie", "-Wl,--build-id=none", chk] + objs + shim + host + ["-o", image]
        cmd += tc.link_flags + ["-ldl", "-lm"] + (["-lpthread"] if a.target == "linux-x64" else [])
        run(cmd, "link")
        slots, names_at, _defined = elf_slots(image, tc.nm, cp.tool("llvm-readelf"), len(cs))
        addr = {}
        for v, ns in names_at.items():
            for n in ns:
                addr.setdefault(n, v)
        bad = 0
        for (k, n, tgt, off), (how, v) in zip(cs, slots):
            if not (how == "rel" and tgt in addr and v == addr[tgt] + off):
                bad += 1
                print("FAIL %-48s -> %s 0x%x, want %s+%d" % (prefix(k) + n, how, v if isinstance(v, int) else 0, tgt, off))
        print("%d names, %d bound right, %d wrong (read from %s's relocations)" % (len(cs), len(cs) - bad, bad,
                                                                                  os.path.basename(image)))
        rc = rc or (1 if bad else 0)
    if problems:
        rc = rc or 1
    if a.no_bind:
        print("control (--no-bind): %s" % ("FAILS as it must" if rc else "PASSES: the test cannot see a wrong binding"))
        return 0 if rc else 1
    print("xdk_bind_test %s: %s" % (a.target, "ok" if rc == 0 else "FAILED"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
