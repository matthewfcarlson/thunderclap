#!/usr/bin/env python3
"""The native CRT table bound by name, on a linked image (tools/native_bind.py; docs/native-android.md section 14).

  build/venv/bin/python tests/native_host/crt_bind_test.py --target mac            # arm64 macOS: link and run
  build/venv/bin/python tests/native_host/crt_bind_test.py --target linux-x64      # lld link, checked from the image
  build/venv/bin/python tests/native_host/crt_bind_test.py --target android-arm64  # (NDK) lld link, from the image
  # --no-bind: the control (the link without native_bind): must FAIL, which shows the test sees a wrong binding

A stand-in game TU (generated from src/platform/sdl/crt/native_crt_table.h) declares every name the table binds --
each row's tree names, the plain form of `_` names the table binds through that prefix, `FUN_<addr>` / `DAT_<addr>`
for the rows with an XBE address, and the same addresses inside MS-mangled names (`?FUN_00344e74@fn_bindtest@@...`,
`?DAT_004d9968@fn_bindtest@@3HA`) -- and takes the address of each into a table. It goes through the tree's pipeline
(the MS-ABI front end for the target's Windows triple, the target's retarget, its backend), native_bind binds the
object, and it links with the host glue the images link (crt_posix, rtti_msabi, softx87) and a checker.

Every entry must be the address of the row's definition: a glue / math / abi / data row's `hulk_ncrt_*` symbol in the
host glue, a libc row's function in the system C library (dlsym on the library's own handle, so a stub or glue
function of the same name in the image cannot pass). On macOS the checker runs; on the ELF targets (no Linux machine,
no emulator needed) the table's slots are read from the image's dynamic relocations: a RELATIVE slot must land on the
glue symbol, a symbol slot must name the libc function and the image must not define it. native_bind.check() runs on
the link's inputs as well. Exit 0 when every row binds right.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import clang_probe as cp  # noqa: E402
import native_bind as nb  # noqa: E402
import native_mac as nmac  # noqa: E402

# the tree's front-end flags (native_mac.FRONT without the forced compat/native.h and its warnings)
FRONT = ["-fms-extensions", "-fms-compatibility", "-fms-compatibility-version=13.10", "-std=c++14", "-O0", "-S",
         "-emit-llvm", "-fno-builtin", "-fno-strict-aliasing", "-fwrapv", "-fno-delete-null-pointer-checks", "-Xclang",
         "-fno-wchar", "-fcheck-new", "-ffp-eval-method=double", "-ffp-contract=off", "-w"]
HOST_GLUE = ["src/platform/sdl/host/crt_posix.cpp", "src/platform/sdl/host/rtti_msabi.cpp",
             "src/platform/sdl/crt/softx87.cpp"]


def cases(t):
    """[(source declaration key, symbol name, expected target)]: what the stand-in game TU references. The expected
    target is read off the rows here (first row naming it wins, as the table's comment says), not from native_bind."""
    first = {}
    for _a, k, tgt, ns in t.rows:
        if k == "na":
            continue
        for n in ns:
            first.setdefault(n, tgt)
    out = [("c", n, tg) for n, tg in sorted(first.items())]
    for n in sorted(first):   # `_name` rows bind the plain `name` as well (native_mac's rule: "_" + the name)
        if n.startswith("_") and n[1:] not in first and re.fullmatch(r"[A-Za-z]\w*", n[1:]):
            out.append(("c", n[1:], first[n]))
    for a, k, tgt, _ns in t.rows:
        if a and k != "na":
            out.append(("c", "FUN_%08x" % a, t.addrs[a]))
            out.append(("mangled-fn", "FUN_%08x" % a, t.addrs[a]))
    for a, (sym, _n) in sorted(t.data.items()):
        out.append(("c-data", "DAT_%08x" % a, sym))
        out.append(("mangled-data", "DAT_%08x" % a, sym))
    seen, uniq = set(), []
    for c in out:
        if (c[0], c[1]) not in seen:
            seen.add((c[0], c[1]))
            uniq.append(c)
    return uniq


def game_tu(cs):
    """The stand-in game TU (MS front end): declarations and `hulk_bind_refs[]`."""
    L = ["// generated by tests/native_host/crt_bind_test.py", 'extern "C" {']
    for key, n, _t in cs:
        if key == "c":
            L.append("void %s();" % n)
        elif key == "c-data":
            L.append("extern char %s[];" % n)
    L.append("}")
    L.append("namespace fn_bindtest {")
    for key, n, _t in cs:
        if key == "mangled-fn":
            L.append("int %s(void*, int, const char*);" % n)
        elif key == "mangled-data":
            L.append("extern int %s;" % n)
    L.append("}")
    refs = []
    for key, n, _t in cs:
        refs.append("(void*)&%s%s" % ("fn_bindtest::" if key.startswith("mangled") else "", n))
    L.append('extern "C" void* const hulk_bind_refs[] = {\n    ' + ",\n    ".join(refs) + "\n};")
    L.append('extern "C" const unsigned hulk_bind_count = %d;' % len(cs))
    return "\n".join(L) + "\n"


def checker_cpp(cs, t):
    """The host side's checker (macOS run): every slot against the row's definition."""
    glue = sorted({tg for _k, _n, tg in cs if t.kind.get(tg) != "libc"})
    L = ["// generated by tests/native_host/crt_bind_test.py", "#include <dlfcn.h>", "#include <stdio.h>",
         "#include <stdlib.h>", 'extern "C" {', "extern void* const hulk_bind_refs[];",
         "extern const unsigned hulk_bind_count;"]
    L += ["extern char %s;" % g for g in glue]
    L += ['void hulk_native_missing(const char* name) { fprintf(stderr, "missing %s\\n", name); exit(3); }', "}"]
    L.append("extern void* const hulk_libc_refs[];  // libc_refs.c: the host side's own references, by the same link")
    L.append("struct Want { const char* name; const char* target; const char* kind; const void* glue; };")
    L.append("static const Want W[] = {")
    for key, n, tg in cs:
        k = t.kind.get(tg, "?")
        L.append('    {"%s%s", "%s", "%s", %s},' % ("fn_bindtest::" if key.startswith("mangled") else "", n, tg, k,
                                                   "0" if k == "libc" else "&" + tg))
    L.append("};")
    L.append(r'''
// A libc row: the host side's own reference to the function (the same link resolves it) and an address inside a
// system library, never inside this image (so a stub or glue function of the libc name cannot pass). Glue / math /
// abi / data rows: the hulk_ncrt_* definition itself.
int main() {
    Dl_info self;
    dladdr((const void*)&main, &self);
    unsigned n = sizeof(W) / sizeof(W[0]), bad = 0;
    if (n != hulk_bind_count) { printf("table size %u, game side %u\n", n, hulk_bind_count); return 2; }
    for (unsigned i = 0; i < n; i++) {
        const void* got = hulk_bind_refs[i];
        Dl_info di;
        int found = got && dladdr(got, &di);
        const char* at = found && di.dli_sname ? di.dli_sname : "?";
        const char* lib = found && di.dli_fname ? di.dli_fname : "?";
        const void* want = W[i].glue ? W[i].glue : hulk_libc_refs[i];
        int in_image = found && di.dli_fbase == self.dli_fbase;
        if (!want || got != want || (!W[i].glue && in_image)) {
            bad++;
            printf("FAIL %-40s -> %p (%s in %s), want %s %s %p\n", W[i].name, got, at, lib, W[i].kind, W[i].target, want);
        }
    }
    printf("%u names, %u bound right, %u wrong\n", n, n - bad, bad);
    return bad ? 1 : 0;
}''')
    return "\n".join(L) + "\n"


def libc_refs_c(cs, t):
    """The host side's references to each libc row's function (C, no headers: plain `extern char name;`)."""
    libc = sorted({tg for _k, _n, tg in cs if t.kind.get(tg) == "libc"})
    L = ["/* generated by tests/native_host/crt_bind_test.py */"] + ["extern char %s;" % g for g in libc]
    L.append("void* const hulk_libc_refs[] = {\n    " + ",\n    ".join(
        "&" + tg if t.kind.get(tg) == "libc" else "0" for _k, _n, tg in cs) + "\n};")
    return "\n".join(L) + "\n"


def run(cmd, what):
    r = subprocess.run(cmd, capture_output=True, text=True, errors="replace")
    if r.returncode:
        sys.exit("%s failed (rc %d):\n%s\n%s" % (what, r.returncode, " ".join(cmd)[:600], (r.stdout + r.stderr)[-3000:]))
    return r


def elf_slots(image, nm_tool, readelf, n):
    """The table's slots in a linked ELF image: [('rel', address) | ('sym', name)]; and the image's defined names."""
    syms = run([nm_tool, "--defined-only", image], "llvm-nm").stdout
    addr_of, names_at = None, {}
    for line in syms.splitlines():
        p = line.split(None, 2)
        if len(p) == 3:
            names_at.setdefault(int(p[0], 16), set()).add(p[2].replace("#", "@"))
            if p[2] == "hulk_bind_refs":
                addr_of = int(p[0], 16)
    defined = {s for v in names_at.values() for s in v}
    rel = run([readelf, "-r", "--wide", image], "llvm-readelf -r").stdout
    slots = {}
    for line in rel.splitlines():
        p = line.split()
        if len(p) >= 4 and re.fullmatch(r"[0-9a-f]{16}", p[0]):
            off = int(p[0], 16)
            if "RELATIVE" in p[2]:
                slots[off] = ("rel", int(p[-1], 16))
            elif p[2].endswith("_64") or p[2].endswith("ABS64") or "GLOB_DAT" in p[2]:
                slots[off] = ("sym", re.sub(r"@.*$", "", p[4]) if len(p) > 4 else "?")
    # RELR (Android's packed relative relocations: `.relr.dyn` lists only offsets) keeps the address in the slot
    def slot_word(va):
        import struct
        b = open(image, "rb").read()
        phoff, phentsize, phnum = struct.unpack_from("<Q", b, 0x20)[0], *struct.unpack_from("<HH", b, 0x36)
        for i in range(phnum):
            ptype, _fl, off, vaddr, _pa, filesz = struct.unpack_from("<IIQQQQ", b, phoff + i * phentsize)
            if ptype == 1 and vaddr <= va < vaddr + filesz:
                return struct.unpack_from("<Q", b, off + va - vaddr)[0]
        return 0
    relr = "relr" in rel.lower()
    return [slots.get(addr_of + 8 * i) or (("rel", slot_word(addr_of + 8 * i)) if relr else ("none", 0))
            for i in range(n)], names_at, defined


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--target", default="mac", choices=["mac", "linux-x64", "android-arm64"])
    ap.add_argument("--out", help="work directory (default build/a2s1/crt-bind-<target>)")
    ap.add_argument("--no-bind", action="store_true", help="the control: link without native_bind (must fail)")
    a = ap.parse_args()
    out = a.out or os.path.join(ROOT, "build/a2s1/crt-bind-%s%s" % (a.target, "-nobind" if a.no_bind else ""))
    os.makedirs(out, exist_ok=True)
    t = nb.Table()
    cs = cases(t)
    with open(os.path.join(out, "game.cpp"), "w") as f:
        f.write(game_tu(cs))
    with open(os.path.join(out, "check.cpp"), "w") as f:
        f.write(checker_cpp(cs, t))
    with open(os.path.join(out, "libc_refs.c"), "w") as f:
        f.write(libc_refs_c(cs, t))
    game_ll, game_t, game_o = (os.path.join(out, n) for n in ("game.ll", "game.t.ll", "game.o"))
    if a.target == "mac":
        fe, fmt = cp.tool("clang++"), "macho"
        run([fe, "--target=aarch64-pc-windows-msvc"] + FRONT + [os.path.join(out, "game.cpp"), "-o", game_ll], "front end")
        open(game_t, "w", errors="surrogateescape").write(nmac.retarget(open(game_ll, errors="surrogateescape").read()))
        run([cp.tool("clang")] + nmac.BACK + [game_t, "-o", game_o], "backend")
        game_syms = nmac.nm_macho([game_o])
        host, errs = nb.macos_host_objects(os.path.join(out, "host"), HOST_GLUE)
        host_syms = nmac.nm_macho(host)
    else:
        import native_elf as ne
        tc = ne.Toolchain(a.target)
        fe, fmt = tc.cxx, "elf"
        run(fe + ["--target=" + ne.TARGETS[a.target]["front"]] + FRONT + [os.path.join(out, "game.cpp"), "-o", game_ll],
            "front end")
        open(game_t, "w", errors="surrogateescape").write(
            ne.retarget_elf(open(game_ll, errors="surrogateescape").read(), tc))
        run(tc.cc + ne.flags(a.target)[1] + [game_t, "-o", game_o], "backend")
        game_syms = ne.nm_elf([game_o], tc.nm)
        host, errs = [], {}
        hd = os.path.join(out, "host")
        os.makedirs(hd, exist_ok=True)
        for src in HOST_GLUE:
            o = os.path.join(hd, os.path.basename(src) + ".o")
            r = subprocess.run(tc.cxx + tc.host_flags() + ["-I" + os.path.join(ROOT, "src/platform/sdl"), "-c",
                                                           os.path.join(ROOT, src), "-o", o], capture_output=True, text=True)
            (errs.__setitem__(src, r.stderr[-1500:]) if r.returncode else host.append(o))
        host_syms = ne.nm_elf(host, tc.nm)
    if errs:
        sys.exit("host glue failed: %s" % json.dumps(errs, indent=1))
    undef = set().union(*(u for _d, u in game_syms.values())) - set().union(*(d for d, _u in game_syms.values()))
    binding = nb.plan(undef, t)
    want_names = {(n if not k.startswith("mangled") else None) for k, n, _t in cs} - {None}
    missing = sorted(n for n in want_names if n not in binding)
    if missing:
        sys.exit("native_bind.plan does not bind: %s" % ", ".join(missing))
    if a.no_bind:
        objs, bst = [game_o], {}
    else:
        objs, bst = nb.apply([game_o], binding, game_syms, os.path.join(out, "bound"), fmt)
    bound_syms = (nmac.nm_macho(objs) if fmt == "macho" else ne.nm_elf(objs, tc.nm))
    sysdef = nb.macos_system_names() if a.target == "mac" else None
    st, problems = nb.check(binding, bound_syms, host_syms, (), sysdef, t)
    print("native_bind: %s; apply %s" % (json.dumps(st), json.dumps(bst)))
    for p in problems[:40]:
        print("  check: " + p)
    image = os.path.join(out, "crt_bind")
    if a.no_bind:   # the link before native_bind: names neither the host glue nor the system defines are stubs
        hd = set().union(*(d for d, _u in host_syms.values()))
        sd = sysdef if sysdef is not None else (
            ne.defined_syms(tc.nm, tc.system_libs()[0], dynamic=True) | ne.defined_syms(tc.nm, tc.system_libs()[1]))
        stubs = sorted(n for n in undef if n not in hd and n not in sd)
        sp = os.path.join(out, "stubs.s")
        with open(sp, "w") as f:
            for n in stubs:
                q = nb.spell(n, fmt)
                f.write('\t.data\n\t.globl "%s"\n"%s":\n\t.space 16\n' % (q, q))
        so = sp + ".o"
        run((["xcrun", "clang", "-arch", "arm64"] if fmt == "macho" else tc.cc + ["--target=" + tc.triple, "-fPIC"])
            + ["-c", sp, "-o", so], "stubs")
        objs = objs + [so]
        print("control: %d names stubbed, the rest left to the C library" % len(stubs))
    if a.target == "mac":
        lr = os.path.join(out, "libc_refs.o")
        run(["xcrun", "clang", "-arch", "arm64", "-O1", "-fno-builtin", "-w", "-mmacosx-version-min=" + nmac.MACOS_MIN,
             "-c", os.path.join(out, "libc_refs.c"), "-o", lr], "libc_refs")
        run(["xcrun", "clang++", "-arch", "arm64", "-std=c++17", "-O1", "-fno-builtin", "-mmacosx-version-min=" + nmac.MACOS_MIN,
             os.path.join(out, "check.cpp"), lr] + objs + host + ["-o", image], "link")
        r = subprocess.run([image], capture_output=True, text=True)
        print(r.stdout + r.stderr[-2000:])
        rc = r.returncode
    else:
        chk = os.path.join(out, "check.o")
        run(tc.cxx + tc.host_flags() + ["-fno-builtin", "-c", os.path.join(out, "check.cpp"), "-o", chk], "checker")
        lr = os.path.join(out, "libc_refs.o")
        run(tc.cc + [f for f in tc.host_flags() if f != "-std=c++17"] + ["-fno-builtin", "-w", "-c",
                                                                        os.path.join(out, "libc_refs.c"), "-o", lr], "libc_refs")
        cmd = tc.cxx + tc.host_flags() + ["-pie", "-Wl,--build-id=none", chk, lr] + objs + host + ["-o", image] + tc.link_flags
        cmd += ["-ldl", "-lm"] + (["-lpthread"] if a.target == "linux-x64" else [])
        run(cmd, "link")
        nm_tool, readelf = tc.nm, cp.tool("llvm-readelf")
        slots, names_at, defined = elf_slots(image, nm_tool, readelf, len(cs))
        bad = 0
        for (key, n, tg), (how, v) in zip(cs, slots):
            k = t.kind.get(tg)
            name = ("fn_bindtest::" if key.startswith("mangled") else "") + n
            if k == "libc":
                ok = how == "sym" and v == tg and tg not in defined
            else:
                ok = how == "rel" and tg in names_at.get(v, set())
            if not ok:
                bad += 1
                print("FAIL %-40s -> %s %s, want %s %s" % (name, how, v if how != "rel" else
                                                          "0x%x %s" % (v, sorted(names_at.get(v, []))[:3]), k, tg))
        print("%d names, %d bound right, %d wrong (read from %s's relocations)" % (len(cs), len(cs) - bad, bad,
                                                                                  os.path.basename(image)))
        rc = 1 if bad else 0
    if problems:
        rc = rc or 1
    if a.no_bind:
        print("control (--no-bind): %s" % ("FAILS as it must" if rc else "PASSES: the test cannot see a wrong binding"))
        return 0 if rc else 1
    print("crt_bind_test %s: %s" % (a.target, "ok" if rc == 0 else "FAILED"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
