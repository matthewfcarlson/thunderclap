#!/bin/sh
# The x86-64 Linux image (tools/native_elf.py link --target linux-x64 --ld: hulk-linux) in a local Linux VM on an
# Apple Silicon Mac (docs/native-linux.md). Lima, vz backend: an arm64 Debian 12 guest that runs x86-64 ELF binaries
# through Rosetta for Linux (binfmt_misc), with Debian's amd64 glibc / libstdc++ (multiarch). Headless; nothing is
# forwarded off the Mac. The guest sees two read-only virtiofs mounts and nothing else from the host:
#   $SHARE -> /mnt/hulk/bin    the image to run (this script copies it there)
#   $DATA  -> /mnt/hulk/data   the player's extracted disc (default isos/extracted, with default.xbe)
# Results come back with `limactl cp`; the run's save / tdata / udata live in the guest's /tmp and are deleted after.
#
#   sh tests/linux/vm_run.sh setup              # once: create and start the VM (downloads Debian's arm64 cloud image)
#   sh tests/linux/vm_run.sh start|stop|status|shell
#   sh tests/linux/vm_run.sh delete             # removes the VM and its disk (~/.lima/$VM)
#   sh tests/linux/vm_run.sh host-tests [DIR]   # tests/linux/host_link.sh's executables, checked by host_run.sh
#   sh tests/linux/vm_run.sh run IMAGE OUT_DIR [continue]   # start-up run, as tests/android/libmain_run.sh
#   sh tests/linux/vm_run.sh gdb IMAGE CMDS.gdb [continue]  # the same start-up under gdb (batch, CMDS.gdb's commands)
#
# gdb: Rosetta's own debug server (ROSETTA_DEBUGSERVER_PORT) crashes in this guest, so the image runs under
# qemu-x86_64's gdb stub instead (qemu-user: slower, exact enough for breakpoints and memory; the load base is then
# 0x4000000000, not Rosetta's 0x555555554000) with gdb-multiarch attached. Software watchpoints only
# (`set can-use-hw-watchpoints 0`), and they single-step: watch late, from a breakpoint.
#
# run: stops at the first missing name (exit 3), a crash (exit 4), the end of main, HANG seconds without progress
# (default 90) or TIMEOUT seconds (default 300). `continue` is the survey mode (HULK_NATIVE_MISSING=continue: every
# missing name logged once and answered with 0; a list of stops, never a result). REC=<.hrp> replays a recording with
# checkpoints (HULK_CKPT), for when the start-up reaches the game loop. FFMPEG=<dir> (x86-64 libav*.so built for the
# sysroot) is copied next to the image and put on LD_LIBRARY_PATH. Writes OUT_DIR/{trace.txt,stdout.txt,result.txt}.
# Environment: VM (instance name, default hulk-linux); for setup SHARE (default build/linux-vm/share), DATA, CPUS
# (4), MEMORY (8GiB), DISK (20GiB). The mounts are fixed when the VM is created (the other commands read SHARE from
# the VM's configuration): change SHARE / DATA with delete + setup.
set -u
cmd=${1:-}
[ $# -gt 0 ] && shift
VM=${VM:-hulk-linux}
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
SHARE=${SHARE:-$ROOT/build/linux-vm/share}
DATA=${DATA:-$ROOT/isos/extracted}
command -v limactl > /dev/null || { echo "no limactl: brew install lima" >&2; exit 2; }
g() { limactl shell --workdir / "$VM" "$@"; }
# an existing VM's share is the directory it mounts at /mnt/hulk/bin (fixed when it was created)
if [ "$cmd" != setup ]; then
    m=$(limactl list "$VM" --format '{{range .Config.Mounts}}{{.MountPoint}}={{.Location}}{{"\n"}}{{end}}' 2>/dev/null |
        sed -n 's|^/mnt/hulk/bin=||p')
    [ -n "$m" ] && SHARE=$m
fi

case "$cmd" in
setup)
    [ "$(uname -s)/$(uname -m)" = Darwin/arm64 ] || { echo "setup: an Apple Silicon Mac (vz + Rosetta)" >&2; exit 2; }
    [ -x /Library/Apple/usr/libexec/oah/RosettaLinux/rosetta ] ||
        { echo "Rosetta is not installed: softwareupdate --install-rosetta --agree-to-license" >&2; exit 2; }
    [ -f "$DATA/default.xbe" ] || { echo "no extracted disc at $DATA (default.xbe)" >&2; exit 2; }
    mkdir -p "$SHARE"
    SHARE=$(cd "$SHARE" && pwd); DATA=$(cd "$DATA" && pwd)
    y=$(mktemp -t hulk-lima).yaml
    cat > "$y" <<EOF
# generated by tests/linux/vm_run.sh setup
base:
- template:_images/debian-12
vmType: vz
arch: aarch64
cpus: ${CPUS:-4}
memory: ${MEMORY:-8GiB}
disk: ${DISK:-20GiB}
mountType: virtiofs
mounts:
- location: "$SHARE"
  mountPoint: /mnt/hulk/bin
  writable: false
- location: "$DATA"
  mountPoint: /mnt/hulk/data
  writable: false
vmOpts:
  vz:
    rosetta:
      enabled: true
      binfmt: true
containerd:
  system: false
  user: false
ssh:
  loadDotSSHPubKeys: false
  forwardAgent: false
  forwardX11: false
# nothing from the guest is forwarded to the host
portForwards:
- guestIP: "0.0.0.0"
  guestPortRange: [1, 65535]
  proto: any
  ignore: true
- guestIP: "127.0.0.1"
  guestPortRange: [1, 65535]
  proto: any
  ignore: true
provision:
- mode: system
  script: |
    #!/bin/sh
    set -eux
    # x86-64 user space for Rosetta: the loader, glibc, libstdc++ / libgcc (Debian multiarch)
    if ! dpkg --print-foreign-architectures | grep -q amd64; then dpkg --add-architecture amd64; fi
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -q
    apt-get install -y -q --no-install-recommends libc6:amd64 libstdc++6:amd64 libgcc-s1:amd64 file binutils
    # debugging (vm_run.sh gdb): qemu-user's gdb stub and a gdb that reads x86-64
    apt-get install -y -q --no-install-recommends qemu-user gdb-multiarch
probes:
- script: |
    #!/bin/sh
    test -e /lib64/ld-linux-x86-64.so.2
  hint: the provision script installs the amd64 loader
EOF
    limactl start --name="$VM" --tty=false "$y" || exit 1
    rm -f "$y"
    g sh -c 'uname -m; cat /proc/sys/fs/binfmt_misc/rosetta 2>/dev/null | head -2; ls /lib64/ld-linux-x86-64.so.2'
    ;;
start) limactl start --tty=false "$VM" ;;
stop) limactl stop "$VM" ;;
delete) limactl delete --force "$VM" ;;
status) limactl list "$VM"; du -sh "${LIMA_HOME:-$HOME/.lima}/$VM" 2>/dev/null ;;
shell) limactl shell "$VM" "$@" ;;
host-tests)   # the host layer's tests (tests/linux/host_link.sh [DIR], default build/elf1/linux-host) in the VM
    hb=${1:-$ROOT/build/elf1/linux-host}
    mkdir -p "$SHARE/host" || exit 1
    for b in crt_test crt_test_libm host_test entry_test rtti_test; do cp "$hb/$b" "$SHARE/host/" || exit 1; done
    cp "$ROOT/tests/linux/host_run.sh" "$SHARE/host/" || exit 1
    g sh /mnt/hulk/bin/host/host_run.sh /mnt/hulk/bin/host
    ;;
run|gdb)
    if [ "$cmd" = gdb ]; then img=$1; gdbf=$2; mode=${3:-}; out=${OUT:-$(dirname "$gdbf")}; else img=$1; out=$2; mode=${3:-}; fi
    [ -f "$img" ] || { echo "no image $img" >&2; exit 2; }
    mkdir -p "$out" "$SHARE"
    limactl list --format '{{.Status}}' "$VM" 2>/dev/null | grep -q Running || { echo "VM $VM not running: sh $0 start" >&2; exit 2; }
    g test -f /mnt/hulk/data/default.xbe || { echo "no extracted disc at /mnt/hulk/data in the VM" >&2; exit 2; }
    cp "$img" "$SHARE/hulk-linux" || exit 1
    LIB=/mnt/hulk/bin
    if [ -n "${FFMPEG:-}" ]; then mkdir -p "$SHARE/lib" && cp -P "$FFMPEG"/lib/lib*.so* "$SHARE/lib/" && LIB=/mnt/hulk/bin/lib; fi
    X=
    [ "$mode" = continue ] && X="HULK_NATIVE_MISSING=continue"
    if [ -n "${REC:-}" ]; then
        cp "$REC" "$SHARE/rec.hrp" || exit 1
        X="$X HULK_INPUT_SOURCE=replay:/mnt/hulk/bin/rec.hrp HULK_CKPT=1 HULK_CKPT_ALL=1 HULK_CKPT_REGIONS=0 HULK_AUDIO_CLOCK=frame"
    fi
    D=/tmp/hulk-run
    g sh -c "rm -rf $D && mkdir -p $D/save $D/tdata $D/udata" || exit 1
    E="LD_LIBRARY_PATH=$LIB HULK_TRACE_FILE=$D/trace.txt HULK_DATA_DIR=/mnt/hulk/data HULK_SAVE_DIR=$D/save \
HULK_TDATA_DIR=$D/tdata HULK_UDATA_DIR=$D/udata SDL_AUDIO_DRIVER=dummy SDL_VIDEO_DRIVER=dummy"
    T0=$(date +%s)
    if [ "$cmd" = gdb ]; then
        cp "$gdbf" "$SHARE/cmds.gdb" || exit 1
        g sh -c "cd $D && (env $E HULK_HANG=0 $X qemu-x86_64 -g 12345 /mnt/hulk/bin/hulk-linux > $D/stdout.txt 2>&1 &) && sleep 2 &&
timeout ${TIMEOUT:-600} gdb-multiarch -q -batch -ex 'set architecture i386:x86-64' -ex 'file /mnt/hulk/bin/hulk-linux' \
-ex 'target remote 127.0.0.1:12345' -x /mnt/hulk/bin/cmds.gdb 2>&1 | grep -v '^warning'; pkill -f 'qemu-x86_64 -g 12345'" | tee "$out/gdb.txt"
        rc=gdb
        rm -f "$SHARE/cmds.gdb"
    else
        rc=$(g sh -c "cd $D && env $E HULK_HANG=${HANG:-90} $X timeout ${TIMEOUT:-300} /mnt/hulk/bin/hulk-linux > $D/stdout.txt 2>&1; echo \$?")
    fi
    T1=$(date +%s)
    limactl cp "$VM:$D/trace.txt" "$out/trace.txt" > /dev/null 2>&1
    limactl cp "$VM:$D/stdout.txt" "$out/stdout.txt" > /dev/null 2>&1
    g rm -rf $D
    rm -f "$SHARE/rec.hrp"
    {
        echo "exit $rc wall $((T1 - T0)) s"
        grep -E "^(missing|crash|end|hang|first)" "$out/trace.txt" 2>/dev/null | head -12
        grep -E "^init [0-9]+" "$out/trace.txt" 2>/dev/null | tail -1
        echo "initializers run: $(grep -c '^init ' "$out/trace.txt" 2>/dev/null), skipped: $(grep -c '^skip ' "$out/trace.txt" 2>/dev/null)"
    } > "$out/result.txt"
    cat "$out/result.txt"
    ;;
*) sed -n '2,/^set -u/p' "$0" | sed '$d'; exit 2 ;;
esac
