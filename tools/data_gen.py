def tu_path(obj, layer):
    return os.path.join(OUT_SRC, layer, re.sub(r"\.cpp$", ".data.cpp", obj))


def generate(model, only=None):
    """Write every data TU. Returns [(tu path, [items])]."""
    inv_items = model.items
    # aligned words the inventory takes as pointers (re-derived the inventory's way)
    inv = di.Inventory()
    inv.collect_starts([], {}, {})
    ptr_words = set(inv.data_ptrs)
    by_obj = collections.defaultdict(list)
    for it in inv_items:
        if model.emitted(it) and (only is None or it["object"] == only):
            by_obj[(it["object"], it["layer"])].append(it)
    out = []
    for (obj, layer), items in sorted(by_obj.items()):
        w = TUWriter(model, items)
        w.ptr_words = ptr_words
        p = tu_path(obj, layer)
        w.write(p)
        out.append((p, items, w))
    return out


def pointer_layout(model):
    """{item addr: set of byte offsets of its pointer words} as generate() emits them (the XBE's initialized
    pointers and config/data-ptrs.json's run-time ones): for tools/data_ptrs.py lint."""
    inv = di.Inventory()
    inv.collect_starts([], {}, {})
    w = TUWriter(model, [])
    w.ptr_words = set(inv.data_ptrs)
    out = {}
    for it in model.items:
        if not model.emitted(it) or it["kind"] in ("string", "wstring"):
            continue
        offs = set()
        b = model.raw(it)
        if it["section"] != ".bss" and it["addr"] % 4 == 0:
            for i in range(0, it["size"] - 3, 4):
                v = struct.unpack_from("<I", b, i)[0]
                if v and it["addr"] + i in w.ptr_words and model.target(v) is not None:
                    offs.add(i)
        for o in w.evidence_ptrs(it):
            if it["section"] == ".bss" or struct.unpack_from("<I", b, o)[0] == 0 or o in offs:
                offs.add(o)
        if offs:
            out[it["addr"]] = offs
    return out


def record_items(model):
    """{item addr: record stride} of the items generate() emits as record arrays (for tools/data_ptrs.py lint)."""
    inv = di.Inventory()
    inv.collect_starts([], {}, {})
    w = TUWriter(model, [])
    w.ptr_words = set(inv.data_ptrs)
    out = {}
    for key, e in w.ev.items():
        if not e.get("records"):
            continue
        it = model.item_at(int(key, 16))
        if it is None or not model.emitted(it):
            continue
        w.local = {it["cname"]}
        if w.record_item(it) is not None:
            out[it["addr"]] = e["records"][0]["stride"]
    return out


def write_decls(model, tus):
    """include/decls/data/<layer>/<dir>.h: declarations only (names, types, sizes)."""
    by_hdr = collections.defaultdict(list)
    for p, items, w in tus:
        decl = dict(w.decls)
        for it in items:
            if it["cname"] in decl:
                d = os.path.dirname(it["object"]) or "root"
                by_hdr[(it["layer"], d)].append((it, decl[it["cname"]]))
    written = []
    for (layer, d), rows in sorted(by_hdr.items()):
        path = os.path.join(DECLS, layer, d + ".h")
        guard = "HULK_DECLS_DATA_" + re.sub(r"\W", "_", "%s_%s" % (layer, d)).upper() + "_H"
        lines = [HEADER, "// Data items owned by %s/%s objects (docs/data.md). Each is declared under its address name, the" % (
                     layer, d), "// symbol every source uses; the inventory name follows when it says more. Sources include this",
                 "// header instead of declaring the names (tools/migrate_data.py).",
                 "#ifndef " + guard, "#define " + guard, ""] + DATA_PRELUDE
        structs = set()
        for it, decl in rows:
            m = re.match(r"(?:const )?(Data(?:Layout|Rec)_[0-9a-f]{8})\b", decl)
            if m:
                structs.add(m.group(1))
        for s in sorted(structs):
            lines.append("struct %s;  // packed layout (bytes and pointers), defined in the data TU" % s)
        cur = None
        for it, decl in sorted(rows, key=lambda r: (r[0]["object"], r[0]["addr"])):
            if it["object"] != cur:
                cur = it["object"]
                lines += ["", "// %s" % cur]
            note = "  // " + it["name"] if it["name"] != it["cname"] else ""
            lines.append('extern "C" %s;%s' % (decl, note))
        lines += ["", "#endif", ""]
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("\n".join(lines))
        written.append(path)
    return written


