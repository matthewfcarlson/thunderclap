class Model:
    def __init__(self):
        self.xbe = Xbe(di.XBE_PATH)
        self.objects = di.load_objects()
        inv = di.load_inventory(objects=self.objects)
        self.items = [it for it in inv["items"] if it["section"] in (".rdata", ".data", ".bss")]
        self.items.sort(key=lambda it: it["addr"])
        self.addrs = [it["addr"] for it in self.items]
        self.funcs = di.load_functions()
        self.fstarts = sorted(self.funcs)
        for it in self.items:
            it["cname"] = cname(it)
        self.by_cname = {it["cname"]: it for it in self.items}

    def item_at(self, a):
        import bisect
        j = bisect.bisect_right(self.addrs, a) - 1
        if j >= 0 and a < self.addrs[j] + self.items[j]["size"] + self.items[j]["pad"]:
            return self.items[j]
        return None

    def func_at(self, a):
        import bisect
        j = bisect.bisect_right(self.fstarts, a) - 1
        if j >= 0 and a < self.fstarts[j] + max(1, self.funcs[self.fstarts[j]][0]):
            return self.fstarts[j]
        return None

    def raw(self, it):
        o = self.xbe.offset(it["addr"])
        if o is None:
            return bytes(it["size"])
        return self.xbe.data[o:o + it["size"]]

    def emitted(self, it):
        return it["kind"] not in SKIP_KINDS and not it["opaque"] and it.get("object") and \
            it["layer"] in ("game", "engine", "platform/xbox")

    def target(self, v):
        """C name and offset of what a pointer value points at, as ('data'|'func', name, offset)."""
        t = self.item_at(v)
        if t is not None:
            return "data", t["cname"], v - t["addr"]
        f = self.func_at(v)
        if f is not None:
            return "func", "FUN_%08x" % f, v - f
        return None


def cname(it):
    """The C symbol of an item. Data items are `DAT_<addr>`, the name the sources already use (docs/data.md,
    "Names in sources"): tools/equiv.py binds data symbols by that spelling (`flt_`, `tbl_`, `zero_`, ... it can't
    bind), and a source that declares `DAT_<addr>` keeps its spelling when it moves onto the shared declaration.
    The inventory name (`s_movies_0041dcac`) is the item's description, written next to the declaration.
    Compiler-generated items (vftables, RTTI) keep a name from their kind; they are not emitted."""
    if it["kind"] not in di.CODE_OWNED and it["kind"] not in ("padding", "kernel_thunks", "library_section"):
        return "DAT_%08x" % it["addr"]
    n = it["name"]
    if IDENT.match(n):
        return n
    pre = {"vtable": "vtbl", "rtti_td": "rttiTD", "rtti_col": "rttiCOL", "rtti_chd": "rttiCHD",
           "rtti_bca": "rttiBCA", "rtti_bcd": "rttiBCD"}.get(it["kind"], "d")
    return "%s_%08x" % (pre, it["addr"])


PINNED_H = os.path.join(ROOT, "include/decls/address.h")


def pinned_vars():
    """{name: (type, class)} of the variables include/decls/address.h pins (`extern World* DAT_004dd700;`). Their
    data TU definition takes that declaration (C++ linkage, the pinned type) and include/decls/data/ leaves them
    out: a source that includes both headers must see one declaration."""
    out = {}
    try:
        text = open(PINNED_H, encoding="latin1").read()
    except OSError:
        return out
    for m in re.finditer(r"^extern\s+(?:struct\s+|class\s+)?(\w+)\s*\*\s*(\w+)\s*;", text, re.M):
        out[m.group(2)] = m.group(1)
    return out


TYPED_H = os.path.join(ROOT, "include/decls/data/records.h")
TYPED_INCLUDE = "decls/data/records.h"


def typed_items():
    """{name: declaration} of the .bss items include/decls/data/records.h (hand-written) types with a record that
    several sources share (`extern "C" MemoryHeapSlot DAT_00527c60[46];`). Their data TU includes that header and
    defines them with its declaration (the 32-bit size checked against the item), and include/decls/data/ leaves
    them out: the sources include records.h."""
    out = {}
    try:
        text = open(TYPED_H, encoding="latin1").read()
    except OSError:
        return out
    # (dg1) also a plain pointer item (`extern "C" void* DAT_004e11e8;`): a word that holds a pointer at run time
    for m in re.finditer(r'^extern\s+"C"\s+(\w+(?:\s*\*)?)\s*(DAT_[0-9a-f]{8})\s*(\[\d+\])?\s*;', text, re.M):
        out[m.group(2)] = "%s %s%s" % (re.sub(r"\s+", "", m.group(1)), m.group(2), m.group(3) or "")
    return out


# (dg1) initialized (.data / .rdata) typed records. records.h's record for such an item spells its fields with the
# simple types below, so data_gen can lay the record out (the 32-bit offsets: natural alignment, 4-byte pointers) and
# write the item's initializer from the XBE's bytes. One item spans the whole record array: `--merge-records` makes
# config/data.json's item at that address cover it (the inventory had split it where code names its words).
FIELD_TYPES = {"char": ("int", 1, "char"), "signed char": ("int", 1, "char"), "unsigned char": ("int", 1, "unsigned"),
               "short": ("int", 2, "short"), "unsigned short": ("int", 2, "unsigned"), "int": ("int", 4, "int"),
               "unsigned int": ("int", 4, "unsigned"), "unsigned": ("int", 4, "unsigned"), "float": ("float", 4, "float")}


def record_fields(name, text=None):
    """[(offset, field, spelling, kind, size, count)] of records.h's `struct name` on the 32-bit builds, in
    TUWriter.rec_init's form, and its 32-bit size; None if a field is not one of the simple types (FIELD_TYPES,
    `void (*f)()` code pointers, `T*` data pointers)."""
    if text is None:
        try:
            text = open(TYPED_H, encoding="latin1").read()
        except OSError:
            return None
    m = re.search(r"^struct\s+%s\s*\{(.*?)^\};" % re.escape(name), text, re.M | re.S)
    if not m:
        return None
    fields, off, align = [], 0, 1
    for line in m.group(1).splitlines():
        line = re.sub(r"//.*", "", line).strip()
        if not line:
            continue
        f = re.fullmatch(r"void\s*\(\s*\*\s*(\w+)\s*\)\s*\(\s*(?:void)?\s*\)\s*;", line)
        if f:
            kind, size, spell, fname, count = "code", 4, "code", f.group(1), 1
        else:
            f = re.fullmatch(r"((?:const\s+)?[\w ]+?)\s*(\*?)\s*(\w+)\s*(?:\[(\d+)\])?\s*;", line)
            if not f:
                return None
            t, star, fname, count = f.group(1).strip(), f.group(2), f.group(3), int(f.group(4) or 1)
            if star:
                kind, size, spell = "pointer", 4, "pointer"
            elif t in FIELD_TYPES:
                kind, size, spell = FIELD_TYPES[t]
            else:
                return None
        off = (off + size - 1) // size * size
        fields.append((off, fname, spell, kind, size, count))
        off += size * count
        align = max(align, size)
    return fields, (off + align - 1) // align * align


def typed_data_records():
    """{item name: (record type, count, 32-bit record size, fields)} of records.h's items with an array count whose
    record data_gen can lay out (record_fields): the candidates for initialized typed records."""
    try:
        text = open(TYPED_H, encoding="latin1").read()
    except OSError:
        return {}
    out = {}
    for m in re.finditer(r'^extern\s+"C"\s+(\w+)\s+(DAT_[0-9a-f]{8})\s*\[(\d+)\]\s*;', text, re.M):
        r = record_fields(m.group(1), text)
        if r is not None:
            out[m.group(2)] = (m.group(1), int(m.group(3)), r[1], r[0])
    return out


