def verify_tu(model, path, items, obj, err):
    out = []
    if obj is None:
        for it in items:
            out.append(dict(addr=it["addr"], kind=it["kind"], status="compile_error", why=(err or "")[:200]))
        return out
    c = compare.Coff(obj)
    syms = {}
    for s in c.symbols:
        name, value, secnum, typ, cls = s
        if secnum > 0 and cls == 2:
            syms[name] = s
    # symbols per section, for sizes and section-relative relocations
    by_sec = collections.defaultdict(list)
    for name, (n, value, secnum, typ, cls) in syms.items():
        by_sec[secnum].append((value, name))
    for v in by_sec.values():
        v.sort()
    for it in items:
        r = dict(addr=it["addr"], kind=it["kind"], form=it.get("_form"))
        if it.get("_skip"):
            r.update(status="not_emitted", why=it["_skip"])
            out.append(r)
            continue
        s = syms.get("_" + it["cname"])
        if s is None and it.get("_form") == "pinned":
            s = next((x for nm, x in syms.items() if nm.startswith("?%s@@" % it["cname"])), None)
        if s is None:
            r.update(status="no_symbol")
            out.append(r)
            continue
        _, value, secnum, _, _ = s
        sname, raw, relocs = c.sections[secnum - 1]
        hdr_flags = section_flags(c, secnum)
        got_sec = ".bss" if hdr_flags & 0x80 else ".rdata" if not hdr_flags & 0x80000000 else ".data"
        r["section"] = got_sec
        size = it["size"]
        if got_sec == ".bss":
            secsize = section_size(c, secnum)
            nxt = [v for v, _ in by_sec[secnum] if v > value]
            have = (nxt[0] if nxt else secsize) - value
            ok = have >= size and not any(model.raw(it))
            r.update(status="match" if ok else "diff", why=None if ok else "bss size %d < %d" % (have, size))
            r["section_ok"] = it["section"] == ".bss"
            out.append(r)
            continue
        ours = raw[value:value + size]
        target = model.raw(it)
        if len(ours) < size:
            r.update(status="diff", why="size %d < %d" % (len(ours), size))
            out.append(r)
            continue
        masked = set()
        bad = []
        for va, si, typ in relocs:
            if not value <= va < value + size:
                continue
            masked.update(range(va - value, va - value + 4))
            tsym = c.by_index.get(si)
            add, = struct.unpack_from("<i", raw, va)
            want = struct.unpack_from("<I", target, va - value)[0] if va - value + 4 <= size else None
            got = resolve(model, c, tsym, add, by_sec)
            if typ != 6:
                bad.append("reloc type %d" % typ)
            elif got is None:
                bad.append("unresolved %s" % (tsym[0] if tsym else "?"))
            elif got != want:
                bad.append("pointer +%x -> %#x, XBE has %#x" % (va - value, got, want or 0))
        diffs = [i for i in range(size) if i not in masked and ours[i] != target[i]]
        if diffs:
            bad.append("%d bytes differ (first +%x)" % (len(diffs), diffs[0]))
        r["relocs"] = len(masked) // 4
        r["section_ok"] = got_sec == it["section"]
        r.update(status="match" if not bad else "diff", why="; ".join(bad[:3]) if bad else None)
        out.append(r)
    return out


def section_flags(c, secnum):
    d = c.data
    _, nsec, _, _, _, opthdr, _ = struct.unpack_from("<HHIIIHH", d, 0)
    o = 20 + opthdr + (secnum - 1) * 40
    return struct.unpack_from("<I", d, o + 36)[0]


def section_size(c, secnum):
    d = c.data
    _, nsec, _, _, _, opthdr, _ = struct.unpack_from("<HHIIIHH", d, 0)
    o = 20 + opthdr + (secnum - 1) * 40
    return struct.unpack_from("<I", d, o + 16)[0]


def resolve(model, c, tsym, add, by_sec):
    """XBE address a relocation (symbol + addend) stands for, through the inventory's names."""
    if tsym is None:
        return None
    name, value, secnum, typ, cls = tsym
    if cls == 3 and secnum > 0:
        # section symbol: the addend is an offset in our section -> the item defined there
        cands = [(v, n) for v, n in by_sec[secnum] if v <= add + value]
        if not cands:
            return None
        v, n = cands[-1]
        return resolve(model, c, (n, v, secnum, 0, 2), add + value - v, by_sec)
    n = name[1:] if name.startswith("_") else name
    m = re.fullmatch(r"FUN_([0-9a-f]{8})", n)
    if m:
        return int(m.group(1), 16) + add
    if addr_names.suffix_address(n) is not None:        # (clean2) `SetArc_000480a0` (tools/addr_names.py)
        return addr_names.suffix_address(n) + add
    it = model.by_cname.get(n)
    if it is None:
        return None
    return it["addr"] + add & 0xffffffff


INVENTORY = os.path.join(ROOT, "config/data.json")


def merge_records(path=INVENTORY, dry=False):
    """(dg1) Make config/data.json's item at each initialized typed record's address (typed_data_records) span the
    whole record array: the items inside the span are folded into it (their addresses become its `interior`, their
    xrefs its own), and an item that starts before the span and runs into it is cut at its start. One line per item,
    as tools/data_inventory.py writes it; the other lines are left as they are. Returns [(name, items folded)]."""
    recs = typed_data_records()
    lines = open(path).read().split("\n")
    rows = {}                               # line index -> item (items lines only)
    for i, ln in enumerate(lines):
        s = ln.strip()
        if s.startswith('{"addr":'):
            rows[i] = json.loads(s.rstrip(","))
    order = sorted(rows, key=lambda i: int(rows[i]["addr"], 16))
    done, drop = [], set()
    for name, (rname, count, size32, _) in sorted(recs.items()):
        a = int(name[4:], 16)
        span = count * size32
        head = next((i for i in order if int(rows[i]["addr"], 16) == a), None)
        if head is not None and span in (rows[head]["size"], rows[head]["size"] + rows[head].get("pad", 0)):
            continue
        # an item that runs into the span from before it: cut at the span's start (its bytes there are the record's)
        prev = [i for i in order if int(rows[i]["addr"], 16) < a]
        cut = None
        if prev:
            p = rows[prev[-1]]
            pa = int(p["addr"], 16)
            if pa + p["size"] + p.get("pad", 0) > a:
                cut = prev[-1]
        inside = [i for i in order if a < int(rows[i]["addr"], 16) < a + span]
        group = ([head] if head is not None else []) + inside
        if not group and cut is None:
            raise SystemExit("merge-records: no item at %#x" % a)
        ends = [int(rows[i]["addr"], 16) + rows[i]["size"] + rows[i].get("pad", 0) for i in group]
        if cut is not None:
            ends.append(int(rows[cut]["addr"], 16) + rows[cut]["size"] + rows[cut].get("pad", 0))
        if max(ends) != a + span:
            raise SystemExit("merge-records: %s: the items at %#x.. end at %#x, not %#x" % (name, a, max(ends), a + span))
        first = rows[group[0]] if group else rows[cut]
        for i in group + ([cut] if cut is not None else []):
            o = rows[i]
            bss = o["kind"] in ("bss", "unknown_bss")
            if o["object"] != first["object"] and not bss or o["kind"] in di.CODE_OWNED or \
                    bss != (first["kind"] in ("bss", "unknown_bss")):
                raise SystemExit("merge-records: %s: %s is %s of %s" % (name, o["addr"], o["kind"], o["object"]))
        merged = {"addr": "0x%08x" % a, "size": span}
        last = rows[group[-1]] if group else rows[cut]
        if last.get("pad"):
            merged["size"] = span - last["pad"]
            merged["pad"] = last["pad"]
        merged.update(kind="bss" if first["kind"] in ("bss", "unknown_bss") else "table", name="tbl_%08x" % a, type="%s[%d]" % (rname, count), object=first["object"])
        for k in ("layer", "owner_by"):
            if k in first:
                merged[k] = first[k]
        interior = sorted({int(x, 16) for i in group for x in rows[i].get("interior", [])
                           if a < int(x, 16) < a + span} | {int(rows[i]["addr"], 16) for i in inside})
        if interior:
            merged["interior"] = ["0x%x" % x for x in interior]
        flags = sorted({f for i in group for f in rows[i].get("flags", [])})
        if flags:
            merged["flags"] = flags
        xrefs = sorted({x for i in group for x in rows[i].get("xrefs", [])}, key=lambda x: int(x, 16))
        if xrefs:
            merged["xrefs"] = xrefs
        line = "  " + json.dumps(merged, separators=(",", ":")) + ","
        if cut is not None:
            p = rows[cut]
            pa = int(p["addr"], 16)
            p["size"] = a - pa
            p.pop("pad", None)
            m = re.fullmatch(r"(\w+)\[\d+\]", p.get("type") or "")
            if m and p["size"] % 4 == 0:
                p["type"] = "%s[%d]" % (m.group(1), p["size"] // 4)
            p["interior"] = [x for x in p.get("interior", []) if int(x, 16) < a]
            if not p["interior"]:
                p.pop("interior")
            lines[cut] = "  " + json.dumps(p, separators=(",", ":")) + ","
        if head is not None:
            lines[head] = line
            drop |= set(inside)
        else:
            lines[cut] += "\n" + line
            drop |= set(inside)
        done.append((name, len(inside)))
    if done and not dry:
        out = [ln for i, ln in enumerate(lines) if i not in drop]
        with open(path, "w") as f:
            f.write("\n".join(out))
    return done


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only", help="one object (config/splits.json file name)")
    ap.add_argument("--gen-only", action="store_true")
    ap.add_argument("--no-decls", action="store_true", help="don't write include/decls/data/")
    ap.add_argument("--merge-records", action="store_true",
                    help="make config/data.json's items of records.h's initialized typed records span their arrays")
    a = ap.parse_args(argv)
    if a.merge_records:
        for name, n in merge_records():
            print("%s: %d items folded in" % (name, n))
        return 0
    import input_guard      # (guard1) the stamp of the sources the TUs come from: Wine build jobs check it
    tok = None if a.only else input_guard.source_stamp("data")
    model = Model()
    tus = generate(model, a.only)
    print("data TUs: %d, items: %d" % (len(tus), sum(len(i) for _, i, _ in tus)), flush=True)
    if not a.only:
        # TUs of objects that no longer exist (renamed or merged in config/splits.json) would still be compiled and linked
        made = {os.path.abspath(p) for p, _, _ in tus}
        gone = [os.path.join(dp, f) for dp, _, fns in os.walk(OUT_SRC) for f in fns
                if f.endswith(".data.cpp") and os.path.abspath(os.path.join(dp, f)) not in made]
        for p in gone:
            os.unlink(p)
        if gone:
            print("removed %d data TUs of objects that no longer exist" % len(gone), flush=True)
        input_guard.put_stamp(tok, OUT_SRC)
    if not a.no_decls and not a.only:
        hs = write_decls(model, tus)
        print("headers: %d in %s" % (len(hs), os.path.relpath(DECLS, ROOT)), flush=True)
    if a.gen_only:
        return 0
    with ThreadPoolExecutor(a.jobs) as ex:
        res = list(ex.map(lambda t: compile_tu(t[0]), tus))
    checks = []
    tu_ok = 0
    for (p, items, w), (obj, err) in zip(tus, res):
        tu_ok += obj is not None
        for r in verify_tu(model, p, items, obj, err):
            r["tu"] = os.path.relpath(p, ROOT)
            checks.append(r)
    per_kind = collections.defaultdict(collections.Counter)
    why = collections.Counter()
    for r in checks:
        k = r["kind"]
        per_kind[k]["emitted"] += r["status"] != "not_emitted"
        per_kind[k]["verified"] += r["status"] == "match"
        per_kind[k][r["status"]] += 1
        per_kind[k]["section_ok"] += bool(r.get("section_ok"))
        per_kind[k]["pointer_relocs"] += r.get("relocs", 0)
        if r["status"] != "match":
            why["%s: %s" % (r["status"], re.sub(r"[0-9a-fx+#]+", "N", r.get("why") or ""))[:120]] += 1
    summary = {"tus": len(tus), "tus_compiled": tu_ok, "items": len(checks),
               "items_verified": sum(1 for r in checks if r["status"] == "match"),
               "per_kind": {k: dict(v) for k, v in sorted(per_kind.items())},
               "failure_causes": dict(why.most_common(30))}
    verified = {(r["addr"]) for r in checks if r["status"] == "match"}
    summary["bytes_verified"] = sum(it["size"] for _, items, _ in tus for it in items if it["addr"] in verified)
    summary["bytes_emitted"] = sum(it["size"] for _, items, _ in tus for it in items)
    with open(REPORT, "w") as f:
        json.dump(dict(summary, checks=checks), f, indent=1)
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())


