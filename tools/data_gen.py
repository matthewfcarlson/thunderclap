# C++ emission
def c_string(b, wide=False):
    out = []
    for c in b:
        if c == 0x5c:
            out.append("\\\\")
        elif c == 0x22:
            out.append('\\"')
        elif c == 0x3f:
            out.append("\\?")               # no trigraphs
        elif 0x20 <= c < 0x7f:
            out.append(chr(c))
        else:
            out.append("\\%03o" % c)
    return ('L"' if wide else '"') + "".join(out) + '"'


def c_float(bits, double=False):
    """A literal that MSVC parses to exactly these bits, or None (NaN, infinity, denormal)."""
    if double:
        x, = struct.unpack("<d", struct.pack("<Q", bits))
        e = (bits >> 52) & 0x7ff
        if e == 0x7ff or (e == 0 and bits & ((1 << 52) - 1)):
            return None
        s = "%.17g" % x
    else:
        x, = struct.unpack("<f", struct.pack("<I", bits))
        e = (bits >> 23) & 0xff
        if e == 0xff or (e == 0 and bits & 0x7fffff):
            return None
        s = "%.9g" % x
    if "e" not in s and "." not in s and "inf" not in s:
        s += ".0"
    return s + ("" if double else "f")


def words(b):
    return struct.unpack("<%dI" % (len(b) // 4), b)


PRIM = {"int": ("int", 4, "i"), "unsigned int": ("unsigned int", 4, "I"), "uint": ("unsigned int", 4, "I"),
        "float": ("float", 4, "f"), "double": ("double", 8, "d"), "short": ("short", 2, "h"),
        "unsigned short": ("unsigned short", 2, "H"), "char": ("char", 1, "b"), "unsigned char": ("unsigned char", 1, "B"),
        "bool": ("unsigned char", 1, "B"), "__int64": ("__int64", 8, "q"), "unsigned __int64": ("unsigned __int64", 8, "Q")}


def scalar_type(it):
    """(C type, element count) when the item's type (inventory or sources) is a primitive matching its size."""
    for t in (it.get("type"), it.get("source_type")):
        if not t:
            continue
        m = re.fullmatch(r"(?:const )?([\w ]+?)\s*(?:\[(\d*)\])?", t)
        if not m or m.group(1) not in PRIM:
            continue
        ct, sz, code = PRIM[m.group(1)]
        if it["size"] % sz:
            continue
        n = it["size"] // sz
        if n == 1 and m.group(2) is None:
            return ct, None, code
        if m.group(2) is not None:
            return ct, n, code
    return None


class TUWriter:
    def __init__(self, model, items):
        self.m = model
        self.items = items
        self.local = {it["cname"] for it in items}
        self.ext_data, self.ext_func = set(), set()
        self.structs = []
        self.decls = []          # (cname, declaration text without `extern "C"`)
        self.defs = []
        self.pins = pinned_vars()

    def ptr_expr(self, v):
        if v == 0:
            return "0"
        t = self.m.target(v)
        if t is None:
            return None
        kind, name, off = t
        if kind == "func":
            self.ext_func.add(name)
            base = "&%s" % name
        else:
            if name not in self.local:
                self.ext_data.add(name)
            base = "&%s" % name
        if off:
            return "(const void*)((const char*)%s + %d)" % (base, off)
        return "(const void*)%s" % base

    def item(self, it):
        m = self.m
        b = m.raw(it)
        n, size, sec, k = it["cname"], it["size"], it["section"], it["kind"]
        const = "const " if sec == ".rdata" else ""
        ptr_at = {}
        if sec != ".bss" and it["addr"] % 4 == 0:
            for i in range(0, size - 3, 4):
                v = struct.unpack_from("<I", b, i)[0]
                if v and it["addr"] + i in self.ptr_words and m.target(v) is not None:
                    ptr_at[i] = v
        if sec == ".bss":
            if n in self.pins and size == 4:
                return "%s* %s" % (self.pins[n], n), None, "pinned"
            st = scalar_type(it)
            if st and st[1] is None:
                return "%s %s" % (st[0], n), None, "bss"
            if st:
                return "%s %s[%d]" % (st[0], n, st[1]), None, "bss"
            return "unsigned char %s[%d]" % (n, size), None, "bss"
        if k == "string" and not ptr_at and b.endswith(b"\0"):
            return "%schar %s[%d]" % (const, n, size), c_string(b[:-1]), "string"
        if k == "wstring" and not ptr_at and size % 2 == 0:
            return "%sunsigned short %s[%d]" % (const, n, size // 2), \
                "{ %s }" % ", ".join("0x%x" % w for w in struct.unpack("<%dH" % (size // 2), b)), "wstring"
        if not ptr_at:
            if k in ("float", "float_table", "double") or (scalar_type(it) or ("",))[0] in ("float", "double"):
                dbl = k == "double" or (scalar_type(it) or ("",))[0] == "double"
                es = 8 if dbl else 4
                if size % es == 0:
                    vals = struct.unpack("<%d%s" % (size // es, "Q" if dbl else "I"), b)
                    lits = [c_float(v, dbl) for v in vals]
                    if all(lits):
                        t = "double" if dbl else "float"
                        if len(vals) == 1 and k != "float_table":
                            return "%s%s %s" % (const, t, n), lits[0], k
                        return "%s%s %s[%d]" % (const, t, n, len(vals)), "{ %s }" % ", ".join(lits), k
            st = scalar_type(it)
            if st and st[0] not in ("float", "double"):
                ct, cnt, code = st
                es = struct.calcsize("<" + code)
                vals = struct.unpack("<%d%s" % (size // es, code), b)
                lit = [("%d" % v if code in "bhiq" else "0x%x" % v) + ("LL" if code == "q" else
                       "ULL" if code == "Q" else "") for v in vals]
                if code == "i":
                    lit = ["%d" % v if v != -2147483648 else "(-2147483647 - 1)" for v in vals]
                if cnt is None:
                    return "%s%s %s" % (const, ct, n), lit[0], "typed"
                return "%s%s %s[%d]" % (const, ct, n, cnt), "{ %s }" % ", ".join(lit), "typed"
            if size % 4 == 0 and it["addr"] % 4 == 0:
                return "%sunsigned int %s[%d]" % (const, n, size // 4), \
                    "{ %s }" % ", ".join("0x%x" % w for w in words(b)), "words"
            return "%sunsigned char %s[%d]" % (const, n, size), \
                "{ %s }" % ", ".join("0x%x" % c for c in b), "bytes"
        # pointers inside
        if all(i in ptr_at or struct.unpack_from("<I", b, i)[0] == 0 for i in range(0, size, 4)) and size % 4 == 0:
            exprs = [self.ptr_expr(ptr_at[i]) if i in ptr_at else "0" for i in range(0, size, 4)]
            if all(exprs):
                if size == 4:
                    return "const void* %s%s" % (const, n), exprs[0], "pointers"
                return "const void* %s%s[%d]" % (const, n, size // 4), "{ %s }" % ", ".join(exprs), "pointers"
        # mixed: a packed struct of byte runs and pointer words
        sname = "DataLayout_%08x" % it["addr"]
        fields, inits, i, run = [], [], 0, []
        while i < size:
            if i in ptr_at:
                if run:
                    fields.append("unsigned char b%x[%d];" % (i - len(run), len(run)))
                    inits.append("{ %s }" % ", ".join("0x%x" % c for c in run))
                    run = []
                e = self.ptr_expr(ptr_at[i])
                if e is None:
                    return None, None, "unresolved pointer"
                fields.append("const void* p%x;" % i)
                inits.append(e)
                i += 4
            else:
                run.append(b[i])
                i += 1
        if run:
            fields.append("unsigned char b%x[%d];" % (size - len(run), len(run)))
            inits.append("{ %s }" % ", ".join("0x%x" % c for c in run))
        self.structs.append("struct %s { %s };" % (sname, " ".join(fields)))
        return "%s%s %s" % (const, sname, n), "{ %s }" % ", ".join(inits), "struct"

    def write(self, path):
        lines = [HEADER, "// Data of %s (%d items). Contains game data: build/ only, never commit." % (
            self.items[0]["object"], len(self.items)), ""]
        body = []
        for it in self.items:
            decl, init, form = self.item(it)
            it["_form"] = form
            if decl is None:
                it["_skip"] = form
                continue
            tag = "// %08x %s %d B%s" % (it["addr"], it["kind"], it["size"], " " + it["type"] if it.get("type") else "")
            if form == "pinned":
                # include/decls/address.h's declaration (C++ linkage, the pinned type): the sources include it
                body.append("struct %s;\n%s;  %s (include/decls/address.h)" % (decl.split("*")[0], decl, tag))
                continue
            self.decls.append((it["cname"], decl))
            if init is None:
                body.append('extern "C" { %s; }  %s' % (decl, tag))
            else:
                body.append('extern "C" %s = %s;  %s' % (decl, init, tag))
        if self.structs:
            lines.append("#pragma pack(push, 1)")
            lines += self.structs
            lines.append("#pragma pack(pop)")
            lines.append("")
        for name in sorted(self.ext_func):
            lines.append('extern "C" void %s();' % name)
        for name in sorted(self.ext_data):
            lines.append('extern "C" const char %s[];' % name)
        for name, decl in self.decls:
            if name in self.ext_data:
                continue
            lines.append('extern "C" %s;' % decl)
        lines.append("")
        lines += body
        os.makedirs(os.path.dirname(path), exist_ok=True)
        text = "\n".join(lines) + "\n"
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, "w") as f:
                f.write(text)
        return text


