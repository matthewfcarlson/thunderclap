# ---------------------------------------------------------------------------------------------
class Model:
    def __init__(self):
        self.xbe = Xbe(di.XBE_PATH)
        self.objects = di.load_objects()
        inv = di.load_inventory(objects=self.objects)
        self.items = [it for it in inv["items"] if it["section"] in (".rdata", ".data", ".bss")]
        self.items.sort(key=lambda it: it["addr"])
        self.addrs = [it["addr"] for it in self.items]
        self.funcs = di.load_functions()
        self.fstarts = sorted(self.funcs)
        for it in self.items:
            it["cname"] = cname(it)
        self.by_cname = {it["cname"]: it for it in self.items}

    def item_at(self, a):
        import bisect
        j = bisect.bisect_right(self.addrs, a) - 1
        if j >= 0 and a < self.addrs[j] + self.items[j]["size"] + self.items[j]["pad"]:
            return self.items[j]
        return None

    def func_at(self, a):
        import bisect
        j = bisect.bisect_right(self.fstarts, a) - 1
        if j >= 0 and a < self.fstarts[j] + max(1, self.funcs[self.fstarts[j]][0]):
            return self.fstarts[j]
        return None

    def raw(self, it):
        o = self.xbe.offset(it["addr"])
        if o is None:
            return bytes(it["size"])
        return self.xbe.data[o:o + it["size"]]

    def emitted(self, it):
        return it["kind"] not in SKIP_KINDS and not it["opaque"] and it.get("object") and \
            it["layer"] in ("game", "engine", "platform/xbox")

    def target(self, v):
        """C name and offset of what a pointer value points at, as ('data'|'func', name, offset)."""
        t = self.item_at(v)
        if t is not None:
            return "data", t["cname"], v - t["addr"]
        f = self.func_at(v)
        if f is not None:
            return "func", "FUN_%08x" % f, v - f
        return None


def cname(it):
    """The C symbol of an item. Data items are `DAT_<addr>`, the name the sources already use (docs/data.md,
    "Names in sources"): tools/equiv.py binds data symbols by that spelling (`flt_`, `tbl_`, `zero_`, ... it can't
    bind), and a source that declares `DAT_<addr>` keeps its spelling when it moves onto the shared declaration.
    The inventory name (`s_movies_0041dcac`) is the item's description, written next to the declaration.
    Compiler-generated items (vftables, RTTI) keep a name from their kind; they are not emitted."""
    if it["kind"] not in di.CODE_OWNED and it["kind"] not in ("padding", "kernel_thunks", "library_section"):
        return "DAT_%08x" % it["addr"]
    n = it["name"]
    if IDENT.match(n):
        return n
    pre = {"vtable": "vtbl", "rtti_td": "rttiTD", "rtti_col": "rttiCOL", "rtti_chd": "rttiCHD",
           "rtti_bca": "rttiBCA", "rtti_bcd": "rttiBCD"}.get(it["kind"], "d")
    return "%s_%08x" % (pre, it["addr"])


PINNED_H = os.path.join(ROOT, "include/decls/address.h")


def pinned_vars():
    """{name: (type, class)} of the variables include/decls/address.h pins (`extern World* DAT_004dd700;`). Their
    data TU definition takes that declaration (C++ linkage, the pinned type) and include/decls/data/ leaves them
    out: a source that includes both headers must see one declaration."""
    out = {}
    try:
        text = open(PINNED_H, encoding="latin1").read()
    except OSError:
        return out
    for m in re.finditer(r"^extern\s+(?:struct\s+|class\s+)?(\w+)\s*\*\s*(\w+)\s*;", text, re.M):
        out[m.group(2)] = m.group(1)
    return out


