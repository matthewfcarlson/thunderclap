def compile_tu(path):
    text = open(path, "rb").read()
    h = hashlib.sha1(text + repr(compare.DEFAULT_FLAGS).encode()).hexdigest()[:20]
    os.makedirs(OBJ_DIR, exist_ok=True)
    obj = os.path.join(OBJ_DIR, h + ".obj")
    err = os.path.join(OBJ_DIR, h + ".err")
    if os.path.exists(obj):
        return obj, None
    if os.path.exists(err):
        return None, open(err).read()
    with tempfile.TemporaryDirectory(dir=OBJ_DIR) as tmp:
        try:
            o = compare.compile_obj(path, compare.DEFAULT_FLAGS, tmp)
        except compare.CompileError as e:
            with open(err, "w") as f:
                f.write(str(e))
            return None, str(e)
        os.replace(o, obj)
    return obj, None


SEC_KIND = {".rdata": ".rdata", ".data": ".data", ".bss": ".bss"}


def verify_tu(model, path, items, obj, err):
    out = []
    if obj is None:
        for it in items:
            out.append(dict(addr=it["addr"], kind=it["kind"], status="compile_error", why=(err or "")[:200]))
        return out
    c = compare.Coff(obj)
    syms = {}
    for s in c.symbols:
        name, value, secnum, typ, cls = s
        if secnum > 0 and cls == 2:
            syms[name] = s
    # symbols per section, for sizes and section-relative relocations
    by_sec = collections.defaultdict(list)
    for name, (n, value, secnum, typ, cls) in syms.items():
        by_sec[secnum].append((value, name))
    for v in by_sec.values():
        v.sort()
    for it in items:
        r = dict(addr=it["addr"], kind=it["kind"], form=it.get("_form"))
        if it.get("_skip"):
            r.update(status="not_emitted", why=it["_skip"])
            out.append(r)
            continue
        s = syms.get("_" + it["cname"])
        if s is None and it.get("_form") == "pinned":
            s = next((x for nm, x in syms.items() if nm.startswith("?%s@@" % it["cname"])), None)
        if s is None:
            r.update(status="no_symbol")
            out.append(r)
            continue
        _, value, secnum, _, _ = s
        sname, raw, relocs = c.sections[secnum - 1]
        hdr_flags = section_flags(c, secnum)
        got_sec = ".bss" if hdr_flags & 0x80 else ".rdata" if not hdr_flags & 0x80000000 else ".data"
        r["section"] = got_sec
        size = it["size"]
        if got_sec == ".bss":
            secsize = section_size(c, secnum)
            nxt = [v for v, _ in by_sec[secnum] if v > value]
            have = (nxt[0] if nxt else secsize) - value
            ok = have >= size and not any(model.raw(it))
            r.update(status="match" if ok else "diff", why=None if ok else "bss size %d < %d" % (have, size))
            r["section_ok"] = it["section"] == ".bss"
            out.append(r)
            continue
        ours = raw[value:value + size]
        target = model.raw(it)
        if len(ours) < size:
            r.update(status="diff", why="size %d < %d" % (len(ours), size))
            out.append(r)
            continue
        masked = set()
        bad = []
        for va, si, typ in relocs:
            if not value <= va < value + size:
                continue
            masked.update(range(va - value, va - value + 4))
            tsym = c.by_index.get(si)
            add, = struct.unpack_from("<i", raw, va)
            want = struct.unpack_from("<I", target, va - value)[0] if va - value + 4 <= size else None
            got = resolve(model, c, tsym, add, by_sec)
            if typ != 6:
                bad.append("reloc type %d" % typ)
            elif got is None:
                bad.append("unresolved %s" % (tsym[0] if tsym else "?"))
            elif got != want:
                bad.append("pointer +%x -> %#x, XBE has %#x" % (va - value, got, want or 0))
        diffs = [i for i in range(size) if i not in masked and ours[i] != target[i]]
        if diffs:
            bad.append("%d bytes differ (first +%x)" % (len(diffs), diffs[0]))
        r["relocs"] = len(masked) // 4
        r["section_ok"] = got_sec == it["section"]
        r.update(status="match" if not bad else "diff", why="; ".join(bad[:3]) if bad else None)
        out.append(r)
    return out


def section_flags(c, secnum):
    d = c.data
    _, nsec, _, _, _, opthdr, _ = struct.unpack_from("<HHIIIHH", d, 0)
    o = 20 + opthdr + (secnum - 1) * 40
    return struct.unpack_from("<I", d, o + 36)[0]


def section_size(c, secnum):
    d = c.data
    _, nsec, _, _, _, opthdr, _ = struct.unpack_from("<HHIIIHH", d, 0)
    o = 20 + opthdr + (secnum - 1) * 40
    return struct.unpack_from("<I", d, o + 16)[0]


def resolve(model, c, tsym, add, by_sec):
    """XBE address a relocation (symbol + addend) stands for, through the inventory's names."""
    if tsym is None:
        return None
    name, value, secnum, typ, cls = tsym
    if cls == 3 and secnum > 0:
        # section symbol: the addend is an offset in our section -> the item defined there
        cands = [(v, n) for v, n in by_sec[secnum] if v <= add + value]
        if not cands:
            return None
        v, n = cands[-1]
        return resolve(model, c, (n, v, secnum, 0, 2), add + value - v, by_sec)
    n = name[1:] if name.startswith("_") else name
    m = re.fullmatch(r"FUN_([0-9a-f]{8})", n)
    if m:
        return int(m.group(1), 16) + add
    it = model.by_cname.get(n)
    if it is None:
        return None
    return it["addr"] + add & 0xffffffff


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--only", help="one object (config/splits.json file name)")
    ap.add_argument("--gen-only", action="store_true")
    ap.add_argument("--no-decls", action="store_true", help="don't write include/decls/data/")
    a = ap.parse_args(argv)
    model = Model()
    tus = generate(model, a.only)
    print("data TUs: %d, items: %d" % (len(tus), sum(len(i) for _, i, _ in tus)), flush=True)
    if not a.no_decls and not a.only:
        hs = write_decls(model, tus)
        print("headers: %d in %s" % (len(hs), os.path.relpath(DECLS, ROOT)), flush=True)
    if a.gen_only:
        return 0
    with ThreadPoolExecutor(a.jobs) as ex:
        res = list(ex.map(lambda t: compile_tu(t[0]), tus))
    checks = []
    tu_ok = 0
    for (p, items, w), (obj, err) in zip(tus, res):
        tu_ok += obj is not None
        for r in verify_tu(model, p, items, obj, err):
            r["tu"] = os.path.relpath(p, ROOT)
            checks.append(r)
    per_kind = collections.defaultdict(collections.Counter)
    why = collections.Counter()
    for r in checks:
        k = r["kind"]
        per_kind[k]["emitted"] += r["status"] != "not_emitted"
        per_kind[k]["verified"] += r["status"] == "match"
        per_kind[k][r["status"]] += 1
        per_kind[k]["section_ok"] += bool(r.get("section_ok"))
        per_kind[k]["pointer_relocs"] += r.get("relocs", 0)
        if r["status"] != "match":
            why["%s: %s" % (r["status"], re.sub(r"[0-9a-fx+#]+", "N", r.get("why") or ""))[:120]] += 1
    summary = {"tus": len(tus), "tus_compiled": tu_ok, "items": len(checks),
               "items_verified": sum(1 for r in checks if r["status"] == "match"),
               "per_kind": {k: dict(v) for k, v in sorted(per_kind.items())},
               "failure_causes": dict(why.most_common(30))}
    verified = {(r["addr"]) for r in checks if r["status"] == "match"}
    summary["bytes_verified"] = sum(it["size"] for _, items, _ in tus for it in items if it["addr"] in verified)
    summary["bytes_emitted"] = sum(it["size"] for _, items, _ in tus for it in items)
    with open(REPORT, "w") as f:
        json.dump(dict(summary, checks=checks), f, indent=1)
    print(json.dumps(summary, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())


