def load_ptr_evidence():
    try:
        return json.load(open(EVIDENCE_PTRS)).get("items", {})
    except (OSError, ValueError):
        return {}


class TUWriter:
    def __init__(self, model, items):
        self.m = model
        self.items = items
        self.local = {it["cname"] for it in items}
        self.ext_data, self.ext_func = set(), set()
        self.structs = []
        self.decls = []          # (cname, declaration text without `extern "C"`)
        self.defs = []
        self.pins = pinned_vars()
        self.ev = load_ptr_evidence()
        self.rec_structs, self.rec_checks = [], []

    def ptr_expr(self, v, ctype="const void*"):
        """Initializer of a pointer word holding XBE address v, as C type ctype (0 -> "0")."""
        if v == 0:
            return "0"
        t = self.m.target(v)
        if t is None:
            return None
        kind, name, off = t
        if kind == "func":
            self.ext_func.add(name)
        elif name not in self.local:
            self.ext_data.add(name)
        if off:
            return "(%s)((const char*)&%s + %d)" % (ctype, name, off)
        return "(%s)&%s" % (ctype, name)

    def category(self, v):
        """What a pointer value points at: "string", "code", "vftable" or "data" (None: unresolved)."""
        t = self.m.target(v)
        if t is None:
            return None
        if t[0] == "func":
            return "code"
        k = self.m.by_cname[t[1]]["kind"] if t[1] in self.m.by_cname else ""
        return {"string": "string", "vtable": "vftable"}.get(k, "data")

    def item(self, it):
        r = self.record_item(it)
        if r is not None:
            return r
        return self.item_plain(it)

    def item_plain(self, it):
        m = self.m
        b = m.raw(it)
        n, size, sec, k = it["cname"], it["size"], it["section"], it["kind"]
        const = "const " if sec == ".rdata" else ""
        ptr_at = {}
        if sec != ".bss" and it["addr"] % 4 == 0:
            for i in range(0, size - 3, 4):
                v = struct.unpack_from("<I", b, i)[0]
                if v and it["addr"] + i in self.ptr_words and m.target(v) is not None:
                    ptr_at[i] = v
        # words that hold a pointer at run time (config/data-ptrs.json, from the sources): zero in the XBE
        run_ptrs = {o for o in self.evidence_ptrs(it) if o not in ptr_at and
                    (sec == ".bss" or struct.unpack_from("<I", b, o)[0] == 0)}
        if sec == ".bss":
            if n in self.pins and size == 4:
                return "%s* %s" % (self.pins[n], n), None, "pinned"
            if run_ptrs:
                return self.pointer_item(it, b, {}, run_ptrs, "", bss=True)
            st = scalar_type(it)
            if st and st[1] is None:
                return "%s %s" % (st[0], n), None, "bss"
            if st:
                return "%s %s[%d]" % (st[0], n, st[1]), None, "bss"
            return "unsigned char %s[%d]" % (n, size), None, "bss"
        if k == "string" and not ptr_at and b.endswith(b"\0"):
            return "%schar %s[%d]" % (const, n, size), c_string(b[:-1]), "string"
        if k == "wstring" and not ptr_at and size % 2 == 0:
            return "%sunsigned short %s[%d]" % (const, n, size // 2), \
                "{ %s }" % ", ".join("0x%x" % w for w in struct.unpack("<%dH" % (size // 2), b)), "wstring"
        if ptr_at or run_ptrs:
            return self.pointer_item(it, b, ptr_at, run_ptrs, const)
        if not ptr_at:
            if k in ("float", "float_table", "double") or (scalar_type(it) or ("",))[0] in ("float", "double"):
                dbl = k == "double" or (scalar_type(it) or ("",))[0] == "double"
                es = 8 if dbl else 4
                if size % es == 0:
                    vals = struct.unpack("<%d%s" % (size // es, "Q" if dbl else "I"), b)
                    lits = [c_float(v, dbl) for v in vals]
                    if all(lits):
                        t = "double" if dbl else "float"
                        if len(vals) == 1 and k != "float_table":
                            return "%s%s %s" % (const, t, n), lits[0], k
                        return "%s%s %s[%d]" % (const, t, n, len(vals)), "{ %s }" % ", ".join(lits), k
            st = scalar_type(it)
            if st and st[0] not in ("float", "double"):
                ct, cnt, code = st
                es = struct.calcsize("<" + code)
                vals = struct.unpack("<%d%s" % (size // es, code), b)
                lit = [("%d" % v if code in "bhiq" else "0x%x" % v) + ("LL" if code == "q" else
                       "ULL" if code == "Q" else "") for v in vals]
                if code == "i":
                    lit = ["%d" % v if v != -2147483648 else "(-2147483647 - 1)" for v in vals]
                if cnt is None:
                    return "%s%s %s" % (const, ct, n), lit[0], "typed"
                return "%s%s %s[%d]" % (const, ct, n, cnt), "{ %s }" % ", ".join(lit), "typed"
            if size % 4 == 0 and it["addr"] % 4 == 0:
                return "%sunsigned int %s[%d]" % (const, n, size // 4), \
                    "{ %s }" % ", ".join("0x%x" % w for w in words(b)), "words"
            return "%sunsigned char %s[%d]" % (const, n, size), \
                "{ %s }" % ", ".join("0x%x" % c for c in b), "bytes"
        raise AssertionError("unreachable")

    # ---- record-typed items (config/data-ptrs.json "records": the record type sources cast the item to) ----
    def record_item(self, it):
        """An item the sources address as an array of one record type (`((Entry*)&DAT_x)[i].fn`): emitted as that
        record's array (a prefix of the record for a partial last element), naturally aligned on every target, so
        the record's 64-bit layout is the sources' own (their casts index it correctly) while the 32-bit layout is
        the XBE's (checked by a size assertion). None: no usable record view."""
        e = self.ev.get("0x%08x" % it["addr"])
        views = [v for v in (e or {}).get("records", ()) if "fields" in v]
        if not views or len(views) != len((e or {}).get("records", ())) or len(views) != 1:
            return None
        v = views[0]
        if int(v["base"], 16) != 0 or v["stride"] > it["size"] or it["addr"] % 4:
            return None
        size, stride, n = it["size"], v["stride"], it["cname"]
        snap = (set(self.ext_data), set(self.ext_func))
        full, rem = divmod(size, stride)
        tail = []
        if rem:
            for f in v["fields"]:
                if f[0] + f[4] * f[5] <= rem:
                    tail.append(f)
            used = max((f[0] + f[4] * f[5] for f in tail), default=0)
            if used != rem:
                return None
        b = self.m.raw(it)
        bss = it["section"] == ".bss"
        const = "const " if it["section"] == ".rdata" else ""
        ptr_at = {}
        if not bss:
            for i in range(0, size - 3, 4):
                w = struct.unpack_from("<I", b, i)[0]
                if w and it["addr"] + i in self.ptr_words and self.m.target(w) is not None:
                    ptr_at[i] = w
        rname = "DataRec_%08x" % it["addr"]
        defs = []
        try:
            self.rec_type(rname, v["fields"], defs)
        except KeyError:
            return None
        # 32-bit: the record and the item have the XBE's sizes
        checks = ["typedef char hulk_size_%s[sizeof(%s) == %d ? 1 : -1];" % (rname, rname, stride)]
        init = None
        if not bss:
            elems = []
            for k in range(full):
                x = self.rec_init(v["fields"], b, k * stride, ptr_at)
                if x is None:
                    self.ext_data, self.ext_func = snap
                    return None
                elems.append(x)
            init_tail = self.rec_init(tail, b, full * stride, ptr_at) if tail else None
            if tail and init_tail is None:
                self.ext_data, self.ext_func = snap
                return None
        saved = (list(self.structs), set(self.ext_data), set(self.ext_func))
        plain = self.item_plain(dict(it))[0] or ""
        self.structs, self.ext_data, self.ext_func = saved
        was_array = plain.rstrip().endswith("]")
        if not tail and full == 1 and not was_array:
            decl = "%s%s %s" % (const, rname, n)
            init = None if bss else elems[0]
        elif not tail and was_array:
            decl = "%s%s %s[%d]" % (const, rname, n, full)
            init = None if bss else "{ %s }" % ", ".join(elems)
        elif not tail:
            # a scalar item (its name is the object, not an address) keeps being one: a wrapper of the array
            lname = "DataLayout_%08x" % it["addr"]
            defs.append("struct %s { %s r[%d]; };" % (lname, rname, full))
            checks.append("typedef char hulk_size_%s[sizeof(%s) == %d ? 1 : -1];" % (lname, lname, size))
            decl = "%s%s %s" % (const, lname, n)
            init = None if bss else "{ { %s } }" % ", ".join(elems)
        else:
            lname = "DataLayout_%08x" % it["addr"]
            tname = "DataRec_%08x_tail" % it["addr"]
            self.rec_type(tname, tail, defs)
            defs.append("struct %s { %s r[%d]; %s t; };" % (lname, rname, full, tname))
            checks.append("typedef char hulk_size_%s[sizeof(%s) == %d ? 1 : -1];" % (lname, lname, size))
            decl = "%s%s %s%s" % (const, lname, n, "[1]" if was_array else "")
            if not bss:
                body = "{ { %s }, %s }" % (", ".join(elems), init_tail)
                init = "{ %s }" % body if was_array else body
        self.rec_structs += defs
        self.rec_checks += checks
        return decl, init, "record"

    def rec_type(self, name, fields, defs):
        members = []
        for f in fields:
            off, fname, spell, kind, esize, count = f[:6]
            if kind == "record":
                sub = "%s_%s" % (name, fname)
                self.rec_type(sub, f[6], defs)
                t = sub
            elif kind == "code":
                t = "hulk_code_ptr"
            elif kind == "pointer":
                t = "void*"
            elif kind == "float":
                t = "double" if esize == 8 else "float"
            else:
                uns = "unsigned" in spell or spell in ("bool", "_Bool")
                t = {1: "unsigned char" if uns else "signed char", 2: "unsigned short" if uns else "short",
                     4: "unsigned int" if uns else "int", 8: "unsigned __int64" if uns else "__int64"}[esize]
            members.append("%s %s%s;" % (t, re.sub(r"\W", "_", fname) or "f%x" % off, "[%d]" % count if count > 1 else ""))
        defs.append("struct %s { %s };" % (name, " ".join(members)))
        return name

    def rec_init(self, fields, b, base, ptr_at):
        """Initializer of one record (fields) whose bytes start at b[base]; None if a pointer field holds a value
        that is not a pointer the inventory knows."""
        parts = []
        for f in fields:
            off, fname, spell, kind, esize, count = f[:6]
            vals = []
            for j in range(count):
                o = base + off + j * esize
                if kind == "record":
                    x = self.rec_init(f[6], b, o, ptr_at)
                elif kind in ("code", "pointer"):
                    w = struct.unpack_from("<I", b, o)[0]
                    if o in ptr_at:
                        x = self.ptr_expr(ptr_at[o], "hulk_code_ptr" if kind == "code" else "void*")
                    elif w == 0:
                        x = "0"
                    else:
                        return None
                elif kind == "float":
                    raw = struct.unpack_from("<Q" if esize == 8 else "<I", b, o)[0]
                    x = c_float(raw, esize == 8)
                else:
                    if o in ptr_at:
                        return None
                    uns = "unsigned" in spell or spell in ("bool", "_Bool")
                    code = {1: "B", 2: "H", 4: "I", 8: "Q"}[esize]
                    w = struct.unpack_from("<" + (code if uns else code.lower()), b, o)[0]
                    x = ("%d" % w if not uns else "0x%x" % w) + ("LL" if esize == 8 and not uns else "ULL" if esize == 8 else "")
                    if not uns and esize == 4 and w == -2147483648:
                        x = "(-2147483647 - 1)"
                if x is None:
                    return None
                vals.append(x)
            parts.append(vals[0] if count == 1 else "{ %s }" % ", ".join(vals))
        return "{ %s }" % ", ".join(parts)

    def evidence_ptrs(self, it):
        """Byte offsets (4-aligned words) of the item that the sources use as pointers (config/data-ptrs.json)."""
        e = self.ev.get("0x%08x" % it["addr"])
        if not e or it["addr"] % 4:
            return set()
        out = {int(o, 16) for o in e.get("pointers", ())}
        for o in e.get("table_from", ()):
            o = int(o, 16)
            out |= set(range(o - o % 4, it["size"] - 3, 4))
        return {o for o in out if 0 <= o and o + 4 <= it["size"] and o % 4 == 0}

    def pointer_item(self, it, b, ptr_at, run_ptrs, const, bss=False):
        """An item with pointer words: real pointer types (4 bytes on the 32-bit builds, 8 on 64-bit). Every word
        a pointer (or zero between pointers): a pointer or an array of pointers, typed by what the words point at
        (`const char*` strings, hulk_code_ptr code, hulk_vftable_ptr vftables, `const void*` other data, `void*` for a
        pointer only set at run time). Otherwise a struct with the pointers as pointer members and the rest as
        unsigned int words and bytes, packed on the 32-bit builds (the XBE's layout) and naturally aligned on 64-bit
        (HULK_DATA_PACKED)."""
        n, size = it["cname"], it["size"]
        # keep what the item's name means in an expression: an array (its address) stays an array, a scalar (its
        # value) a scalar, as the 32-bit form without run-time pointer evidence had it, so a source's
        # `(int)DAT_x` / `DAT_x == 0` means the same (or no longer compiles) instead of changing silently
        st = scalar_type(it)
        if bss:
            scalar = bool(st) and st[1] is None
        elif ptr_at:
            scalar = size == 4 or self.old_struct(it, b, ptr_at)
        else:
            scalar = bool(st) and st[1] is None and st[0] not in ("float", "double")
        cats = {i: self.category(v) for i, v in ptr_at.items()}
        if None in cats.values():
            return None, None, "unresolved pointer"
        pws = set(ptr_at) | set(run_ptrs)
        words_all = size % 4 == 0 and it["addr"] % 4 == 0 and all(
            i in pws or (not bss and struct.unpack_from("<I", b, i)[0] == 0) for i in range(0, size, 4))
        if words_all:
            kinds = set(cats.values())
            ct = PTR_TYPE[kinds.pop()] if len(kinds) == 1 and not run_ptrs else ("void*" if not ptr_at else "const void*")
            if bss:
                ct = "void*"
            exprs = [self.ptr_expr(ptr_at[i], ct) if i in ptr_at else "0" for i in range(0, size, 4)]
            cq = " const" if const else ""
            form = "pointers" if ptr_at else "runtime pointers"
            if size == 4 and scalar:
                return "%s%s %s" % (ct, cq, n), None if bss else exprs[0], form
            return "%s%s %s[%d]" % (ct, cq, n, size // 4), None if bss else "{ %s }" % ", ".join(exprs), form
        sname = "DataLayout_%08x" % it["addr"]
        fields, inits, i, run = [], [], 0, []

        def flush(end):
            # a run of non-pointer bytes: whole aligned words as unsigned int, the rest as bytes
            start = end - len(run)
            j = start
            while j < end:
                if (it["addr"] + j) % 4 == 0 and end - j >= 4:
                    k = j
                    while k + 4 <= end:
                        k += 4
                    ws = words(bytes(b[j:k]))
                    if len(ws) == 1:
                        fields.append("unsigned int w%x;" % j)
                        inits.append("0x%x" % ws[0] if not bss else None)
                    else:
                        fields.append("unsigned int w%x[%d];" % (j, len(ws)))
                        inits.append("{ %s }" % ", ".join("0x%x" % w for w in ws) if not bss else None)
                    j = k
                else:
                    k = j
                    while k < end and not ((it["addr"] + k) % 4 == 0 and end - k >= 4):
                        k += 1
                    fields.append("unsigned char b%x[%d];" % (j, k - j))
                    inits.append("{ %s }" % ", ".join("0x%x" % c for c in b[j:k]) if not bss else None)
                    j = k
            del run[:]
        while i < size:
            if i in pws:
                if run:
                    flush(i)
                if i in ptr_at:
                    ct = PTR_TYPE[cats[i]]
                    fields.append("%s p%x;" % (ct, i))
                    inits.append(self.ptr_expr(ptr_at[i], ct))
                else:
                    fields.append("void* p%x;" % i)
                    inits.append("0")
                i += 4
            else:
                run.append(b[i])
                i += 1
        if run:
            flush(size)
        self.structs.append("struct %s { %s };" % (sname, " ".join(fields)))
        dim = "" if scalar else "[1]"
        if bss:
            return "%s %s%s" % (sname, n, dim), None, "struct"
        init = "{ %s }" % ", ".join(inits)
        return "%s%s %s%s" % (const, sname, n, dim), init if scalar else "{ %s }" % init, "struct"

    def old_struct(self, it, b, ptr_at):
        """Did the 32-bit form without run-time pointers make this a (scalar) struct: pointers mixed with other
        bytes, not a pointer array?"""
        size = it["size"]
        return not (size % 4 == 0 and all(i in ptr_at or struct.unpack_from("<I", b, i)[0] == 0
                                          for i in range(0, size, 4)))

    def write(self, path):
        lines = [HEADER, "// Data of %s (%d items). Contains game data: build/ only, never commit." % (
            self.items[0]["object"], len(self.items)), ""]
        body = []
        for it in self.items:
            decl, init, form = self.item(it)
            it["_form"] = form
            if decl is None:
                it["_skip"] = form
                continue
            tag = "// %08x %s %d B%s" % (it["addr"], it["kind"], it["size"], " " + it["type"] if it.get("type") else "")
            if form == "pinned":
                # include/decls/address.h's declaration (C linkage, the pinned type): the sources include it
                body.append('struct %s;\nextern "C" { %s; }  %s (include/decls/address.h)' % (decl.split("*")[0], decl, tag))
                continue
            self.decls.append((it["cname"], decl))
            if init is None:
                body.append('extern "C" { %s; }  %s' % (decl, tag))
            else:
                body.append('extern "C" %s = %s;  %s' % (decl, init, tag))
        lines += DATA_PRELUDE
        if self.rec_structs:
            # record types: natural alignment on every target (the sources' own record layouts)
            lines += self.rec_structs
            lines += ["#if HULK_DATA_PACKED"] + self.rec_checks + ["#endif", ""]
        if self.structs:
            lines += ["#if HULK_DATA_PACKED", "#pragma pack(push, 1)", "#endif"]
            lines += self.structs
            lines += ["#if HULK_DATA_PACKED", "#pragma pack(pop)", "#endif"]
            lines.append("")
        for name in sorted(self.ext_func):
            lines.append('extern "C" void %s();' % name)
        for name in sorted(self.ext_data):
            lines.append('extern "C" const char %s[];' % name)
        for name, decl in self.decls:
            if name in self.ext_data:
                continue
            lines.append('extern "C" %s;' % decl)
        lines.append("")
        lines += body
        os.makedirs(os.path.dirname(path), exist_ok=True)
        text = "\n".join(lines) + "\n"
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, "w") as f:
                f.write(text)
        return text


