"""Data as source: per-object data TUs from config/data.json, compiled with MSVC 7.1 and byte-checked (docs/data.md).

  build/venv/bin/python tools/data_gen.py                 # generate + compile + verify -> build/data/report.json
  build/venv/bin/python tools/data_gen.py --gen-only      # just write the TUs and the include/decls/data/ headers
  build/venv/bin/python tools/data_gen.py --only global/CAction.cpp   # one object
  build/venv/bin/python tools/data_gen.py --jobs 4        # compiler processes (default 4; the box is shared)

Output:
  build/data/src/<layer>/<dir>/<File>.data.cpp   one data TU per owning object (contains the game's bytes: untracked)
  include/decls/data/<layer>/<dir>.h             extern "C" declarations of every emitted item (names/types only)
  build/data/report.json                         per-item verification and per-kind totals

What is emitted: every item of a game/engine/platform object except the kinds the compiler generates from class
definitions (vtables, RTTI structures: checked by tools/gen_headers.py --probe) and alignment padding. Library
data (XDK/CRT, Bink) stays opaque.

Verification, per item: the symbol is defined in the object, in the item's section kind (.rdata for const, .data
for initialized, .bss), and its bytes equal the XBE's; every relocation inside it must resolve, through the
inventory's names, to the address the XBE word holds (target item or function + addend). Pointer bytes are not
compared raw.
"""
