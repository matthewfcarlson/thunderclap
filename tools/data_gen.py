def compile_tu(path):
    text = open(path, "rb").read()
    h = hashlib.sha1(text + repr(compare.DEFAULT_FLAGS).encode()).hexdigest()[:20]
    os.makedirs(OBJ_DIR, exist_ok=True)
    obj = os.path.join(OBJ_DIR, h + ".obj")
    err = os.path.join(OBJ_DIR, h + ".err")
    if os.path.exists(obj):
        return obj, None
    if os.path.exists(err):
        return None, open(err).read()
    with tempfile.TemporaryDirectory(dir=OBJ_DIR) as tmp:
        try:
            o = compare.compile_obj(path, compare.DEFAULT_FLAGS, tmp)
        except compare.CompileError as e:
            with open(err, "w") as f:
                f.write(str(e))
            return None, str(e)
        os.replace(o, obj)
    return obj, None


