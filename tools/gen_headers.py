# Model

class Cls:
    def __init__(self, rec):
        self.rec = rec
        self.mangled = rec["mangled"]
        self.name = rec["name"]
        self.keyword = {"V": "class", "U": "struct", "T": "union"}[self.mangled[3]]
        self.parts = split_top(self.name, "::")
        self.short, self.targs = split_template(self.parts[-1])
        self.vtables = {}
        self.vtaddr = {}
        for v in rec["vtables"]:
            if v["slots"] and v["offset"] not in self.vtables:
                self.vtables[v["offset"]] = v["slots"]
                self.vtaddr[v["offset"]] = v["address"]
        self.has_layout = rec["attributes"] is not None
        self.bases = []      # direct: (Cls, mdisp, virtual)
        self.all_bases = []  # flattened RTTI list: (Cls, mdisp, pdisp, vdisp, attributes)
        self.unit = None

    @property
    def scope_mangled(self):
        return self.mangled[4:]


class Unit:
    """A thing emitted once: a plain class, or a template family."""

    def __init__(self, uid, members, template):
        self.uid = uid
        self.members = members        # [Cls]
        self.template = template
        c0 = members[0]
        self.parts = split_top(uid, "::")
        self.short = self.parts[-1]
        self.keyword = c0.keyword
        self.ns = []            # namespace path
        self.outer = None       # enclosing Unit (nested class)
        self.header = None
        self.params = None      # template parameter list
        self.nested = []        # nested units / extra forward-declared names
        self.fields = {}        # offset -> ctype (merged across a family)


class Gen:
    def __init__(self, evidence=None):
        rt = json.load(open(RTTI_PATH))
        self.classes = [Cls(r) for r in rt["classes"]]
        self.by_mangled = {c.mangled: c for c in self.classes}
        self.by_name = {c.name: c for c in self.classes}
        self.by_csv = {csv_name(c.name): c for c in self.classes}
        self.code = Code()
        self.report = collections.defaultdict(list)
        self.evidence = evidence or {}
        for c in self.classes:
            bl = c.rec["bases"]
            c.all_bases = [(self.by_mangled[b["name"]], b["mdisp"], b["pdisp"], b["vdisp"], b["attributes"]) for b in bl]
            i = 0
            while i < len(bl):
                b = bl[i]
                c.bases.append((self.by_mangled[b["name"]], b["mdisp"], b["pdisp"] != -1))
                i += b["contained"] + 1
        self.repair_vtables()
        self.build_units()
        self.classify_scopes()

    def repair_vtables(self):
        """rtti.py ends a vftable at the next COL or non-code pointer, so a vftable followed by a
        code-looking pointer is over-counted. A derived class's vftable is never shorter than its
        base's, so a base longer than every derived class gets truncated."""
        derived_len = collections.defaultdict(list)
        for c in self.classes:
            for off, slots in c.vtables.items():
                for b, m, _ in c.bases:
                    if (off - m) in b.vtables:
                        derived_len[(b.mangled, off - m)].append(len(slots))
                        break
        for (bm, off), lens in derived_len.items():
            b = self.by_mangled[bm]
            if max(lens) < len(b.vtables[off]):
                self.report["vtable_repaired"].append("%s vftable +0x%x: %d slots -> %d (every derived class has <= %d)"
                                                      % (b.name, off, len(b.vtables[off]), max(lens), max(lens)))
                b.vtables[off] = b.vtables[off][:max(lens)]

    # -- units and scopes -------------------------------------------------------------------
    def build_units(self):
        groups = collections.OrderedDict()
        for c in self.classes:
            uid = "::".join(c.parts[:-1] + [c.short])
            groups.setdefault((uid, c.targs is not None), []).append(c)
        self.units = collections.OrderedDict()
        for (uid, is_t), members in groups.items():
            if (uid, not is_t) in groups and is_t:
                self.report["unexpressible"].append("%s is both a template and a plain class" % uid)
            u = Unit(uid, members, is_t)
            if is_t:
                n = len(members[0].targs)
                if any(len(m.targs) != n for m in members):
                    self.report["unexpressible"].append("%s: instantiations with different arity" % uid)
                kinds = []
                for k in range(n):
                    nt = [is_nontype(m.targs[k]) for m in members if k < len(m.targs)]
                    kinds.append(all(nt))
                u.params = ["int N%d" % k if nt else "class T%d" % k for k, nt in enumerate(kinds)]
            for m in members:
                m.unit = u
            self.units[uid if not is_t else uid + "<>"] = u
        self.unit_by_uid = {}
        for u in self.units.values():
            self.unit_by_uid.setdefault(u.uid, u)

    def classify_scopes(self):
        """Decide namespace vs enclosing class for every qualifier; assign headers."""
        plain = {u.uid: u for u in self.units.values() if not u.template}
        self.extra_fwd = {}  # qualified name -> (keyword, outer unit or None, ns)
        for u in self.units.values():
            self._place(u.parts, u, plain)
        for u in self.units.values():
            o = u
            while o.outer is not None:
                o = o.outer
            u.ns = o.ns
        # Types only named in template arguments: forward declarations.
        for c in self.classes:
            for a in (c.targs or []):
                for kw, qn in elaborated_types(a):
                    self._extra(kw, qn, plain)

    def _place(self, parts, u, plain):
        ns, outer = [], None
        for j in range(len(parts) - 1):
            prefix = "::".join(parts[:j + 1])
            if prefix in plain:
                outer = plain[prefix]
                ns = None
            elif outer is not None:
                self.report["unexpressible"].append(
                    "%s: qualifier %s nests inside class %s but has no RTTI" % ("::".join(parts), prefix, outer.uid))
                u.skip = True
            else:
                ns.append(parts[j])
        if outer is not None:
            u.outer = outer
            outer.nested.append(u)
            u.ns = outer.ns
            u.header = outer.header if outer.header else None
        else:
            u.ns = ns
        top = parts[0] if (len(parts) > 1 and parts[0] not in plain) else "global"
        u.header = top
        # nested classes go with their outermost class
        o = u
        while o.outer is not None:
            o = o.outer
        u.header = o.parts[0] if (len(o.parts) > 1) else "global"

    def _extra(self, kw, qn, plain):
        if qn in plain or qn in self.extra_fwd:
            return
        base, targs = split_template(split_top(qn, "::")[-1])
        if targs is not None:
            # template instantiation used as an argument: its family must exist
            uid = "::".join(split_top(qn, "::")[:-1] + [base])
            if uid + "<>" not in self.units:
                self.report["unexpressible"].append("template argument %s names an unknown template" % qn)
            for a in targs:
                for kw2, qn2 in elaborated_types(a):
                    self._extra(kw2, qn2, plain)
            return
        parts = split_top(qn, "::")
        ns, outer = [], None
        for j in range(len(parts) - 1):
            prefix = "::".join(parts[:j + 1])
            if prefix in plain:
                outer = plain[prefix]
            elif outer is not None:
                self.report["unexpressible"].append("%s: nested in non-RTTI class %s" % (qn, prefix))
                return
            else:
                ns.append(parts[j])
        if outer is not None:
            outer.nested.append(("fwd", kw, parts[-1]))
        hdr = ns[0] if ns else "global"
        if outer is not None:
            hdr = outer.header
        self.extra_fwd[qn] = (kw, outer, ns, hdr)

    # -- slots ------------------------------------------------------------------------------
    def vt_base(self, c, off):
        """(base Cls, mdisp) whose vtable becomes c's vtable at off, or None (new family)."""
        for b, m, virt in c.bases:
            if (off - m) in b.vtables and not virt:
                return b, m
        return None

    def resolve(self, c, off, i):
        """Slot key (unit uid, slot index) of the class that introduced slot i of c's vtable at off."""
        memo = self._resolve_memo
        k = (c.mangled, off, i)
        if k in memo:
            return memo[k]
        vb = self.vt_base(c, off)
        if vb and i < len(vb[0].vtables[off - vb[1]]):
            r = self.resolve(vb[0], off - vb[1], i)
        else:
            r = (c.unit.uid, i)
        memo[k] = r
        return r

    def analyse_slots(self):
        self._resolve_memo = {}
        self.slot_impls = collections.defaultdict(list)   # key -> [addresses]
        self.slot_pos = {}                                # key -> introducing (Cls, off)
        for c in self.classes:
            c.decl = collections.OrderedDict()   # key -> pure?
            c.new = []                           # keys introduced, in slot order
            c.vt_info = {}                       # off -> [(key, implementer Cls or 'pure')]
            for off in sorted(c.vtables):
                slots = c.vtables[off]
                vb = self.vt_base(c, off)
                bslots = vb[0].vtables[off - vb[1]] if vb else []
                if vb is None and off != 0:
                    self.report["unexpressible"].append(
                        "%s: vftable at +0x%x matches no base vftable" % (c.name, off))
                if vb and len(slots) < len(bslots):
                    self.report["anomaly"].append("%s: vftable +0x%x has %d slots, base %s has %d"
                                                  % (c.name, off, len(slots), vb[0].name, len(bslots)))
                info = []
                for i, a in enumerate(slots):
                    key = self.resolve(c, off, i)
                    self.slot_impls[key].append(a)
                    if i < len(bslots):
                        if a != bslots[i]:
                            c.decl[key] = (a == PURECALL)
                            info.append((key, "pure" if a == PURECALL else c))
                        else:
                            info.append((key, None))  # inherited: filled from base below
                    else:
                        if off != 0:
                            self.report["unexpressible"].append(
                                "%s: secondary vftable +0x%x longer than its base's" % (c.name, off))
                            continue
                        c.new.append(key)
                        c.decl[key] = (a == PURECALL)
                        info.append((key, "pure" if a == PURECALL else c))
                        self.slot_pos.setdefault(key, (c, i))
                c.vt_info[off] = info
        # destructor detection per slot key
        self.dtor = {}
        for key, impls in self.slot_impls.items():
            real = [a for a in set(impls) if a != PURECALL]
            if not real:
                continue
            n = sum(self.code.is_scalar_dtor(a) for a in real)
            if n and n * 2 > len(real):
                self.dtor[key] = True
        # at most one destructor per primary chain
        for c in self.classes:
            ks = [k for k, _ in c.vt_info.get(0, []) if k in self.dtor]
            if len(ks) > 1:
                self.report["anomaly"].append("%s: several destructor-like slots %s; keeping slot %d"
                                              % (c.name, ks, ks[0][1]))
                for k in ks[1:]:
                    self.dtor.pop(k, None)
        # A destructor is implicitly redeclared by every class, so declare it everywhere it appears
        # (pure where the class's own vftable has _purecall in that slot).
        for c in self.classes:
            for off, info in c.vt_info.items():
                for i, (key, impl) in enumerate(info):
                    if key in self.dtor and impl is None:
                        pure = c.vtables[off][i] == PURECALL
                        c.decl[key] = pure
                        info[i] = (key, "pure" if pure else c)
        # arity per key from ret N
        self.arity = {}
        for key, impls in self.slot_impls.items():
            cnt = collections.Counter()
            for a in set(impls):
                if a == PURECALL:
                    continue
                r = self.code.ret_bytes(a)
                if r is not None:
                    cnt[r] += 1
            if cnt:
                r, n = cnt.most_common(1)[0]
                self.arity[key] = r // 4
                if len(cnt) > 1:
                    self.report["arity_conflicts"].append("%s slot %d: ret %s" % (key[0], key[1], dict(cnt)))
        self.names = {}

    def name_of(self, key):
        if key in self.dtor:
            return "~"
        return self.names.get(key, "vfunc_%d" % key[1])

    def fix_collisions(self):
        """With multiple inheritance, one declaration vfunc_N in a class overrides every inherited
        vfunc_N with the same parameters, and hides those with other parameters. Where the vtables
        say otherwise (one overridden and one inherited, different signatures, or different final
        functions), rename the less-used slot family to vfunc_N_<Introducer>."""
        for _ in range(50):
            changed = False
            for c in self.classes:
                if len(c.vtables) < 2:
                    continue
                byname = collections.defaultdict(list)
                for off, info in c.vt_info.items():
                    for i, (key, impl) in enumerate(info):
                        byname[self.name_of(key)].append((key, impl is not None, self.code.final(c.vtables[off][i])))
                for nm, pos in byname.items():
                    keys = {k for k, _, _ in pos}
                    if nm == "~" or len(keys) < 2:
                        continue
                    ok = len({o for _, o, _ in pos}) == 1 and len({tuple(self.signature(k)[1]) for k in keys}) == 1
                    if ok and pos[0][1]:
                        ok = len({a for _, _, a in pos}) == 1
                    if ok:
                        continue
                    victim = min(keys, key=lambda k: (len(self.slot_impls[k]), k))
                    new = "vfunc_%d_%s" % (victim[1], re.sub(r"\W", "_", split_top(victim[0], "::")[-1]))
                    self.report["renamed"].append("%s slot %d -> %s (collides in %s)" % (victim[0], victim[1], new, c.name))
                    self.names[victim] = new
                    changed = True
                    break
            if not changed:
                return
        self.report["unexpressible"].append("slot-name collision fixing did not converge")

    # -- signatures and fields ---------------------------------------------------------------
    def load_sigs_fields(self):
        self.sigs = {}
        self.sig_src = {}
        ev = self.evidence
        for fname, sig in list(ev.get("sigs", {}).items()) + list(CURATED_SIGS.items()):
            m = re.match(r"(.*)::vfunc_(\d+)$", fname)
            c = self.by_csv.get(m.group(1)) if m else None
            if c is None or 0 not in c.vtables or int(m.group(2)) >= len(c.vtables[0]):
                self.report["evidence_dropped"].append("signature for %s: no such slot" % fname)
                continue
            key = self.resolve(c, 0, int(m.group(2)))
            if key in self.dtor:
                continue
            ret, params = sig[0], list(sig[1])
            want = self.arity.get(key)
            if want is not None and len(params) != want and fname not in CURATED_SIGS:
                self.report["evidence_dropped"].append(
                    "signature for %s: %d params but slot cleans %d" % (fname, len(params), want))
                continue
            self.sigs[key] = (ret, params)
            self.sig_src[key] = fname
        for uname, fl in list(ev.get("fields", {}).items()) + list(CURATED_FIELDS.items()):
            c = self.by_csv.get(uname) or self.by_name.get(uname)
            u = c.unit if c else self.unit_by_uid.get(uname)
            if u is None:
                self.report["evidence_dropped"].append("fields for unknown class %s" % uname)
                continue
            for off, t in fl.items():
                off = int(off, 0) if isinstance(off, str) else off
                u.fields[off] = t

    def signature(self, key):
        if key in self.sigs:
            return self.sigs[key]
        n = self.arity.get(key, 0)
        return ("void", ["int"] * n)

    # -- sizes --------------------------------------------------------------------------------
    def compute_sizes(self):
        """Exact base sizes proven by the next base's offset in some class (4-byte alignment)."""
        self.min_size = {}
        for c in self.classes:
            bl = sorted(c.bases, key=lambda b: b[1])
            for (b, m), (b2, m2) in zip([(x[0], x[1]) for x in bl], [(x[0], x[1]) for x in bl[1:]]):
                if m2 > m:
                    u = b.unit
                    prev = self.min_size.get(u.uid)
                    if prev is not None and prev != m2 - m:
                        self.report["size_conflicts"].append(
                            "%s: size %#x (from %s) vs %#x" % (u.uid, m2 - m, c.name, prev))
                    self.min_size[u.uid] = max(prev or 0, m2 - m)
        self._size = {}

    def own_start(self, c):
        end = 0
        for b, m, _ in c.bases:
            end = max(end, m + self.size(b))
        if not c.bases and c.vtables:
            end = 4
        return end

    def size(self, c):
        if c.mangled in self._size:
            return self._size[c.mangled]
        cur = self.own_start(c)
        for off in sorted(c.unit.fields):
            if off >= cur:
                cur = off + type_size(c.unit.fields[off])
        cur = max(cur, self.min_size.get(c.unit.uid, 0))
        if cur % 4 and cur > 1:
            cur += 4 - cur % 4
        self._size[c.mangled] = cur
        return cur

    # -- emission -----------------------------------------------------------------------------
    def cpp_name(self, c):
        """Fully qualified C++ spelling of an RTTI class."""
        if c.targs is None:
            return "::" + c.name
        q = split_top(c.name, "::")
        return "::" + "::".join(q[:-1] + [c.short]) + "< " + ", ".join(render_type(a) for a in c.targs) + " >"

    def base_text(self, c, subst=None):
        """Base specifiers. With subst (an instantiation's args), express bases via T0..Tn."""
        out = []
        for b, m, virt in c.bases:
            t = self.cpp_name(b)
            if subst is not None:
                t = self.subst_base(b, subst)
            out.append(("virtual " if virt else "") + "public " + t)
        return out

    def subst_base(self, b, targs):
        """Spell base b in terms of the parameters of an instantiation with arguments targs."""
        def param(a, pos):
            cand = [k for k, x in enumerate(targs) if x == a]
            if not cand:
                return None
            k = pos if pos in cand else cand[0]
            return "N%d" % k if is_nontype(a) else "T%d" % k
        whole = param("%s %s" % (b.keyword, b.name), -1)
        if whole:
            return whole
        if b.targs is None:
            return self.cpp_name(b)
        q = split_top(b.name, "::")
        args = [param(a, k) or render_type(a) for k, a in enumerate(b.targs)]
        return "::" + "::".join(q[:-1] + [b.short]) + "< " + ", ".join(args) + " >"

    def member_lines(self, c, cls_short, unit, concrete=None):
        lines = []
        dtor_done = False
        seen = {}
        for key, pure in c.decl.items():
            nm = self.name_of(key)
            if nm != "~" and nm in seen:
                if self.signature(seen[nm]) != self.signature(key):
                    self.report["unexpressible"].append(
                        "%s: one override %s for slots with different signatures" % (c.name, nm))
                continue
            seen[nm] = key
            tail = " = 0;" if pure else ";"
            where = "slot %d" % key[1] if key in c.new else "overrides %s slot %d" % (key[0], key[1])
            if nm == "~":
                if dtor_done:
                    continue
                dtor_done = True
                lines.append("    virtual ~%s()%s // %s" % (cls_short, tail, where))
                continue
            ret, params = self.signature(key)
            lines.append("    virtual %s %s(%s)%s // %s" % (ret, nm, ", ".join(params), tail, where))
        # fields
        flines = []
        cur = self.own_start(c)
        for off in sorted(unit.fields):
            t = unit.fields[off]
            if off < cur:
                if off not in getattr(unit, "_skipped", set()):
                    self.report["fields_in_base"].append("%s +0x%x %s (inside bases, which end at 0x%x)"
                                                         % (unit.uid, off, t, cur))
                    unit.__dict__.setdefault("_skipped", set()).add(off)
                continue
            if off > cur:
                flines.append("    char _pad_%02x[0x%x];" % (cur, off - cur))
            fl = decl_field(t, "f_%02x" % off)
            if concrete is not None:
                fl = re.sub(r"\b[TN](\d+)\b", lambda m: render_type(concrete[int(m.group(1))]), fl)
            flines.append("    %s;" % fl)
            cur = off + type_size(t)
        tail = self.min_size.get(unit.uid)
        if tail and tail > cur:
            flines.append("    char _pad_%02x[0x%x]; // size 0x%x proven by a derived class's base offset" % (cur, tail - cur, tail))
        return lines + flines

    def shape(self, c):
        return (tuple(self.base_text(c, c.targs)), tuple(self.member_lines(c, "@", c.unit)))

    def emit_unit(self, u):
        """Lines defining unit u (at namespace scope of u.ns)."""
        lines = []
        qual = "::".join(o.short for o in self.outer_chain(u))
        qual = qual + "::" if qual else ""
        nested = self.nested_decls(u)
        if not u.template:
            c = u.members[0]
            if not c.has_layout:
                return []  # forward declaration only
            lines.append("// %s  %s" % (c.mangled, self.vt_comment(c)))
            bt = self.base_text(c)
            lines.append("%s %s%s%s {" % (u.keyword, qual, u.short, (" : " + ", ".join(bt)) if bt else ""))
            lines.append("public:")
            lines += nested
            lines += self.member_lines(c, u.short, u)
            lines.append("};")
            return lines
        # template family
        shapes = collections.OrderedDict()
        for c in u.members:
            sh = self.shape(c)
            shapes.setdefault(sh, []).append(c)
        primary_shape = max(shapes, key=lambda s: len(shapes[s]))
        u.n_specializations = sum(len(v) for s, v in shapes.items() if s != primary_shape)
        insts = shapes[primary_shape]
        c0 = insts[0]
        lines.append("// template family %s: %d instantiation(s), %d with their own specialization"
                     % (u.uid, len(u.members), u.n_specializations))
        for c in u.members:
            lines.append("//   %s  %s" % (c.name, self.vt_comment(c)))
        tparams = "template <%s>" % ", ".join(u.params)
        bt = self.base_text(c0, c0.targs)
        lines.append(tparams)
        lines.append("%s %s%s%s {" % (u.keyword, qual, u.short, (" : " + ", ".join(bt)) if bt else ""))
        lines.append("public:")
        lines += nested
        lines += self.member_lines(c0, u.short, u)
        lines.append("};")
        for sh, cs in shapes.items():
            if sh == primary_shape:
                continue
            for c in cs:
                bt = self.base_text(c)
                lines.append("template <>")
                lines.append("%s %s%s< %s >%s {" % (u.keyword, qual, u.short, ", ".join(render_type(a) for a in c.targs),
                                                     (" : " + ", ".join(bt)) if bt else ""))
                lines.append("public:")
                lines += self.member_lines(c, u.short, u, c.targs)
                lines.append("};")
        return lines

    def vt_comment(self, c):
        if not c.vtables:
            return "(no vftable)"
        return " ".join("vftable%s 0x%x (%d)" % ("" if off == 0 else "@+0x%x" % off, c.vtaddr[off], len(c.vtables[off]))
                        for off in sorted(c.vtables))

    def outer_chain(self, u):
        ch = []
        o = u.outer
        while o is not None:
            ch.append(o)
            o = o.outer
        return list(reversed(ch))

    def nested_decls(self, u):
        out = []
        for n in u.nested:
            if isinstance(n, tuple):
                out.append("    %s %s%s;" % (n[1], "HULK_SINGLE_INHERITANCE " if n[1] != "enum" else "", n[2]))
            elif n.template:
                out.append("    template <%s> %s %s;" % (", ".join(n.params), n.keyword, n.short))
            else:
                out.append("    %s %s;" % (n.keyword, n.short))
        return out

    # -- dependencies and headers -------------------------------------------------------------
    def unit_deps(self, u):
        """Units that must be defined before u, and extra forward-declared names u needs."""
        deps, fwd = set(), set()
        for c in u.members:
            for b, _, _ in c.bases:
                deps.add(b.unit)
                for a in (b.targs or []):
                    for kw, qn in elaborated_types(a):
                        self._dep_name(qn, deps, fwd)
            if u.template:
                for a in c.targs:
                    for kw, qn in elaborated_types(a):
                        self._dep_name(qn, deps, fwd)
        if u.outer is not None:
            deps.add(u.outer)
        deps.discard(u)
        return deps, fwd

    def _dep_name(self, qn, deps, fwd):
        c = self.by_name.get(qn)
        if c is not None:
            if c.unit.outer is not None:
                deps.add(c.unit.outer)
            else:
                fwd.add(("unit", c.unit.uid))
            return
        base, targs = split_template(split_top(qn, "::")[-1])
        if targs is not None:
            uid = "::".join(split_top(qn, "::")[:-1] + [base])
            u = self.units.get(uid + "<>")
            if u is not None:
                deps.add(u)
            return
        e = self.extra_fwd.get(qn)
        if e is None:
            return
        if e[1] is not None:
            deps.add(e[1])
        else:
            fwd.add(("extra", qn))

    def generate(self, out_dir=OUT_DIR, index_path=INDEX_PATH):
        self.analyse_slots()
        self.load_sigs_fields()
        self.fix_collisions()
        self.compute_sizes()
        units = [u for u in self.units.values() if not getattr(u, "skip", False)]
        headers = collections.OrderedDict()
        for u in sorted(units, key=lambda u: u.header):
            headers.setdefault(u.header, []).append(u)
        deps = {u: self.unit_deps(u) for u in units}
        # header include graph
        inc = collections.defaultdict(set)
        for u in units:
            for d in deps[u][0]:
                if d.header != u.header:
                    inc[u.header].add(d.header)
        cyc = self.find_cycle(inc)
        if cyc:
            self.report["unexpressible"].append("header include cycle: " + " -> ".join(cyc))
        os.makedirs(out_dir, exist_ok=True)
        for f in os.listdir(out_dir):
            if f.endswith(".h"):
                os.remove(os.path.join(out_dir, f))
        index = {}
        for h, us in headers.items():
            order = self.toposort(us, deps)
            text = self.emit_header(h, order, deps, sorted(inc[h]))
            with open(os.path.join(out_dir, h + ".h"), "w") as f:
                f.write(text)
            for u in us:
                for c in u.members:
                    index[c.name] = {
                        "header": h + ".h", "unit": u.uid, "template": u.template,
                        "cpp": self.cpp_name(c), "mangled": c.mangled, "abstract": self.is_abstract(c),
                        "size": self.size(c) if c.has_layout else None,
                        "vtables": {str(off): len(s) for off, s in c.vtables.items()},
                        "slots": {str(off): [[k[0], k[1], (impl if isinstance(impl, str) else impl.name if impl else None)]
                                             for k, impl in self.full_vt_info(c, off)] for off in c.vtables},
                        "bases": [[b.name, m, p, v, a] for b, m, p, v, a in c.all_bases],
                    }
        with open(os.path.join(out_dir, "_prelude.h"), "w") as f:
            f.write(BANNER + PRELUDE)
        with open(os.path.join(out_dir, "all.h"), "w") as f:
            f.write(BANNER + "#ifndef HULK_GEN_ALL_H\n#define HULK_GEN_ALL_H\n")
            for h in headers:
                f.write('#include "%s.h"\n' % h)
            f.write("#endif\n")
        if index_path:
            with open(index_path, "w") as f:
                json.dump(index, f, indent=0, sort_keys=True)
        self.index = index
        return headers

    def full_vt_info(self, c, off):
        """[(key, implementer)] with inherited slots resolved to the base's implementer."""
        out = []
        vb = self.vt_base(c, off)
        binfo = self.full_vt_info(vb[0], off - vb[1]) if vb else []
        for i, (key, impl) in enumerate(c.vt_info.get(off, [])):
            if impl is None and i < len(binfo):
                impl = binfo[i][1]
            out.append((key, impl))
        return out

    def is_abstract(self, c):
        return any(impl == "pure" for off in c.vtables for _, impl in self.full_vt_info(c, off))

    @staticmethod
    def find_cycle(g):
        color = {}

        def dfs(n, path):
            color[n] = 1
            for m in g.get(n, ()):
                if color.get(m) == 1:
                    return path + [n, m]
                if m not in color:
                    r = dfs(m, path + [n])
                    if r:
                        return r
            color[n] = 2
            return None
        for n in list(g):
            if n not in color:
                r = dfs(n, [])
                if r:
                    return r
        return None

    @staticmethod
    def toposort(us, deps):
        inset = set(us)
        done, order = set(), []

        def visit(u, stack):
            if u in done:
                return
            if u in stack:
                return
            stack.add(u)
            for d in sorted(deps[u][0], key=lambda x: x.uid):
                if d in inset:
                    visit(d, stack)
            stack.discard(u)
            done.add(u)
            order.append(u)
        for u in sorted(us, key=lambda x: x.uid):
            visit(u, set())
        return order

    def emit_header(self, h, order, deps, includes):
        guard = "HULK_GEN_%s_H" % re.sub(r"\W", "_", h).upper()
        out = [BANNER, "#ifndef %s\n#define %s\n" % (guard, guard), '#include "_prelude.h"']
        for i in includes:
            out.append('#include "%s.h"' % i)
        if includes:
            out.append("")
        # forward declarations: this header's namespace-scope units and extra names
        fwd = []
        for u in order:
            if u.outer is None:
                if u.template:
                    fwd.append((u.ns, "template <%s> %s %s;" % (", ".join(u.params), u.keyword, u.short)))
                else:
                    fwd.append((u.ns, "%s %s;" % (u.keyword, u.short)))
        need = set()
        for u in order:
            need |= deps[u][1]
        for qn, (kw, outer, ns, hdr) in sorted(self.extra_fwd.items()):
            if outer is None and (hdr == h or ("extra", qn) in need):
                if kw == "enum":
                    continue  # enums can't be forward-declared portably; template args only
                fwd.append((ns, "%s HULK_SINGLE_INHERITANCE %s;" % (kw, split_top(qn, "::")[-1])))
        for kind, uid in sorted(need):
            if kind == "unit":
                u = self.unit_by_uid[uid]
                if u.header != h and u.outer is None:
                    fwd.append((u.ns, ("template <%s> " % ", ".join(u.params) if u.template else "")
                                + "%s %s;" % (u.keyword, u.short)))
        out.append("// Forward declarations")
        out += self.in_namespaces(fwd)
        out.append("")
        # enums named in template args need a declaration to instantiate; emit as opaque enums
        enums = [(ns, "enum %s { };" % split_top(qn, "::")[-1]) for qn, (kw, outer, ns, hdr) in
                 sorted(self.extra_fwd.items()) if kw == "enum" and outer is None and hdr == h]
        if enums:
            out.append("// Enums named only in template arguments (enumerators unknown)")
            out += self.in_namespaces(enums)
            out.append("")
        body = []
        for u in order:
            ls = self.emit_unit(u)
            if ls:
                body.append((u.ns, "\n".join(ls) + "\n"))
        out += self.in_namespaces(body)
        out.append("\n#endif // %s\n" % guard)
        return "\n".join(out)

    @staticmethod
    def in_namespaces(items):
        out, cur = [], []
        for ns, text in items:
            if ns != cur:
                if cur:
                    out.append("}" * len(cur) + " // namespace " + "::".join(cur))
                if ns:
                    out.append(" ".join("namespace %s {" % n for n in ns))
                cur = ns
            out.append(text)
        if cur:
            out.append("}" * len(cur) + " // namespace " + "::".join(cur))
        return out


def type_size(t):
    if isinstance(t, (tuple, list)):
        return t[1]
    t = t.strip()
    if t.endswith("*"):
        return 4
    m = re.match(r"(.*)\[(\w+)\]$", t)
    if m:
        return type_size(m.group(1)) * int(m.group(2), 0)
    return {"char": 1, "signed char": 1, "unsigned char": 1, "bool": 1, "short": 2, "unsigned short": 2,
            "double": 8, "__int64": 8, "unsigned __int64": 8}.get(t, 4)


def decl_field(t, name):
    if isinstance(t, (tuple, list)):
        return t[0] % name
    m = re.match(r"(.*)\[(\w+)\]$", t)
    if m:
        return "%s %s[%s]" % (m.group(1), name, m.group(2))
    return "%s %s" % (t, name)


