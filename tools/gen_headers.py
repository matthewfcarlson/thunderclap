#!/usr/bin/env python3
"""Generate shared C++ class headers (include/gen/) from recovered RTTI.

Usage:
  tools/gen_headers.py                 # regenerate include/gen/ from build/rtti.json
  tools/gen_headers.py --probe [HDR..] # compile every header with cl 13.10 and check layouts
  tools/gen_headers.py --mine          # mine matches/ for field offsets / slot signatures
                                       # (writes include/gen/evidence.json, then regenerate)

Inputs: build/rtti.json (tools/rtti.py), build/functions.csv, isos/extracted/default.xbe
(slot bodies, for destructor and arity detection), include/gen/evidence.json (optional,
from --mine) and the CURATED_* tables below.

What gets emitted (see docs/headers.md):
  - one header per top-level namespace (`global.h` for the global namespace), plus all.h;
  - namespaces, forward declarations, nested classes declared inside their outer class;
  - base lists in RTTI declaration order (virtual bases flagged; none occur in this game);
  - virtual methods in vtable order: `vfunc_N` for slot N of the class that introduced the
    slot, overrides redeclared, inherited slots not redeclared, `= 0` for _purecall slots,
    `virtual ~X()` where the slot bodies look like scalar deleting destructors;
  - template families emitted once (primary template + explicit specializations for
    instantiations whose shape differs), with the instantiations listed in a comment;
  - fields only where proven: `char _pad_XX[N]` + typed members for offsets backed by
    matched code (evidence.json / CURATED_FIELDS), and tail padding where a multiple-
    inheritance base offset proves a base's size.
"""
