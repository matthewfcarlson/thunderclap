#!/usr/bin/env python3
"""List verified sources that are correct but need a readability pass before the port (docs/tech-debt.md).

A source in matches/ or equivalent/ is proven, but some were written for the checker rather than for people:
  goto     uses goto (control flow copied from the asm instead of structured)
  lift     machine-generated: a "mechanical lift" / "Generated from the original" header, or the original's stack
           frame as a raw array (`Wd L[...]`, `unsigned S[...]`)
  volatile 20 or more `volatile` declarations (forced stores and reloads to pin down x87 rounding)
Each is worth a hand rewrite during milestone 2 (shared headers), re-checked with the same tool that proved it.

  tools/tech_debt.py            # rewrites docs/tech-debt.md
  tools/tech_debt.py --check    # exits 1 if docs/tech-debt.md is out of date
"""
import csv
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs/tech-debt.md")
LIFT_HEADER = re.compile(r"mechanical lift|Generated from the original", re.I)
FRAME_ARRAY = re.compile(r"\b(?:volatile\s+)?(?:Wd|unsigned)\s+[LS]\s*\[\s*(?:0x)?[0-9a-fA-F]+\s*\]")
GOTO = re.compile(r"\bgoto\s+\w+\s*;")
VOLATILE = re.compile(r"\bvolatile\b")
VOLATILE_MIN = 20


def scan(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    gotos = len(GOTO.findall(text))
    lift = bool(LIFT_HEADER.search(text[:2000]) or FRAME_ARRAY.search(text))
    vol = len(VOLATILE.findall(text))
    flags = []
    if lift:
        flags.append("lift")
    if gotos:
        flags.append("goto")
    if vol >= VOLATILE_MIN:
        flags.append("volatile")
    return flags, gotos, vol


def render():
    sizes, names = {}, {}
    with open(os.path.join(ROOT, "docs/game-functions.csv")) as f:
        for r in csv.DictReader(f):
            sizes[r["address"]] = int(r["size"])
    fcsv = os.path.join(ROOT, "build/functions.csv")  # names, when the local Ghidra export exists
    if os.path.exists(fcsv):
        with open(fcsv) as f:
            for r in csv.DictReader(f):
                if not r["name"].startswith("FUN_"):
                    names[r["address"]] = r["name"]
    rows = []
    for d in ("matches", "equivalent"):
        for fn in sorted(os.listdir(os.path.join(ROOT, d))):
            if not fn.endswith(".cpp"):
                continue
            flags, gotos, vol = scan(os.path.join(ROOT, d, fn))
            if flags:
                a = fn[:-4]
                rows.append((d, a, sizes.get(a, 0), names.get(a, ""), flags, gotos, vol))
    rows.sort(key=lambda r: (-("lift" in r[4]), -r[2]))
    count = lambda flag: sum(1 for r in rows if flag in r[4])
    out = [
        "# Tech debt: proven sources that need a readability pass",
        "",
        "Generated by `tools/tech_debt.py`; don't edit by hand. These sources are verified (byte-matched or",
        "proven equivalent) but were shaped for the checker, not for people. Rewrite them by hand during milestone 2",
        "(shared headers) and re-check each with the tool that proved it (`compare.py` for matches/, `equiv.py` for",
        "equivalent/).",
        "",
        "| Flag | Meaning | Files |",
        "|---|---|---|",
        f"| lift | machine-generated from the asm (frame array, register variables) | {count('lift')} |",
        f"| goto | control flow copied from the asm with goto | {count('goto')} |",
        f"| volatile | {VOLATILE_MIN}+ volatile declarations pinning x87 rounding | {count('volatile')} |",
        "",
        "| Source | Size | Name | Flags | gotos | volatiles |",
        "|---|---|---|---|---|---|",
    ]
    for d, a, size, name, flags, gotos, vol in rows:
        out.append(f"| `{d}/{a}.cpp` | {size} | {name} | {', '.join(flags)} | {gotos} | {vol} |")
    return "\n".join(out) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == text else 1)
    open(OUT, "w").write(text)
    print(OUT, text.count("\n| `"), "files")


if __name__ == "__main__":
    main()
