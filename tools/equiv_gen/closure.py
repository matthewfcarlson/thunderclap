#!/usr/bin/env python3
"""Generate equivalence sources for script-binding registrations (Closure0/Function0/Function1).
usage: gen.py ADDR [ADDR...]   -> work/closure/out/ADDR.cpp"""
import re, subprocess, sys, os
ROOT = os.path.dirname(os.path.abspath(__file__))
PY = os.path.join(ROOT, '../../build/venv/bin/python')
PK = os.path.join(ROOT, '../../tools/packet.py')

def ctype(t):
    t = re.sub(r'\b(class|struct)\s+', '', t.strip())
    return t.replace(' *', '*').replace('*', '*')

def split_args(s):
    out, d, cur = [], 0, ''
    for ch in s:
        if ch == '<': d += 1
        if ch == '>': d -= 1
        if ch == ',' and d == 0: out.append(cur); cur = ''
        else: cur += ch
    out.append(cur)
    return [ctype(x) for x in out]

def decl_for(types):
    ns, cls = {}, []
    for t in types:
        base = t.replace('const ', '').replace('*', '').strip()
        if base in ('void', 'int', 'bool', 'float', 'char', 'unsigned int'): continue
        if '::' in base:
            n, c = base.rsplit('::', 1); ns.setdefault(n, set()).add(c)
        else: cls.append(base)
    s = ''
    for c in dict.fromkeys(cls): s += 'class %s { public: float FUN_dummy(); };\n' % c
    for n, cs in ns.items():
        s += 'namespace %s {\n' % n + ''.join('class %s { public: float FUN_dummy(); };\n' % c for c in sorted(cs)) + '}\n'
    return s

HEAD = '''extern "C" void* __cdecl FUN_0008d690(unsigned int size);
extern "C" char __cdecl FUN_001d04d0(const char*);
%(dats)s
inline void* operator new(unsigned int, void* p) throw() { return p; }
'''

def gen(addr):
    txt = subprocess.run([PY, PK, 'show', addr], capture_output=True, text=True).stdout
    asm = txt.split('Ghidra')[0]
    size = int(re.search(r'push (0x[0-9a-f]+)\n.*\n.*\n.*call FUN_0008d690', asm).group(1), 16) if False else None
    size = int(re.search(r'push (0x[0-9a-f]+)\s+\S+\s+mov ebx, ecx\s+\S+\s+call FUN_0008d690|push (0x[0-9a-f]+)\s+(?:\S+\s+){0,3}?call FUN_0008d690', asm.replace('\n', ' ')).group(0).split('push ')[1].split()[0], 16)
    pushes = re.findall(r'push 0x(4[0-9a-f]{5})\b', asm)
    pushes = [p for p in pushes if True]
    dats = ['DAT_00%s' % p for p in pushes]
    m = re.search(r'= (Closure0)<(.*)>::vftable', txt)
    f1 = re.search(r'= Function1<(.*)>::vftable', txt)
    f0 = re.search(r'= Function0<(.*)>::vftable', txt)
    reg = 'FUN_' + addr[2:]
    decl_dats = ''.join('extern "C" const char %s[];\n' % d for d in dict.fromkeys(dats))
    out = '// FUN_%s @ %s  (generated by work/closure/gen.py)\n' % (addr[2:], addr) + HEAD % {'dats': decl_dats}
    base = '''
class __declspec(novtable) MethodBase {
  public:
    virtual void m0();
    char pad_04[%s];
%s    MethodBase(const char* n, int k) { FUN_001d0480(n, k); }
    void FUN_001d0480(const char*, int);
};
'''
    reg_common = '''
struct Registry {
    void FUN_001d3b70(const char*, void*);
    %s;
};
'''
    if m:
        T, R = split_args(m.group(2))
        assert size == 0x24 and len(dats) == 1
        out += decl_for([T, R]) + base % ('0x14', '    char enabled;\n    char pad_19[3];\n') + '''
template <class T, class R>
class Method0 : public MethodBase {
  public:
    typedef R (T::*Fn)();
    Method0(const char* name, Fn f) : MethodBase(name, 0) {
        fn = f;
        enabled = FUN_001d04d0(%(d)s);
    }
    Fn fn;
};

template <class T, class R>
class Closure0 : public Method0<T, R> {
  public:
    Closure0(const char* name, T* o, Fn f) : Method0<T, R>(name, f), owner(o) {}
    T* owner;
};
''' % {'d': dats[0]}
        sig = 'void %s(const char* name, %s* owner, %s (%s::*fn)())' % (reg, T, R, T)
        out += reg_common % sig.replace('void ' + reg, 'void ' + reg) + '''
%s {
    void* mem = FUN_0008d690(0x24);
    Closure0<%s, %s>* c = 0;
    if (mem)
        c = new (mem) Closure0<%s, %s>(name, owner, fn);
    FUN_001d3b70(name, c);
}
''' % (sig.replace('void ' + reg, 'void Registry::' + reg), T, R, T, R)
    elif f0:
        (R,) = split_args(f0.group(1))
        assert size == 0x20 and len(dats) == 1
        out += decl_for([R]) + base % ('0x14', '    char enabled;\n    char pad_19[3];\n') + '''
template <class R>
class Function0 : public MethodBase {
  public:
    typedef R (*Fn)();
    Function0(const char* name, Fn f) : MethodBase(name, 0) {
        fn = f;
        enabled = FUN_001d04d0(%s);
    }
    Fn fn;
};
''' % dats[0]
        sig = 'void %s(const char* name, %s (*fn)())' % (reg, R)
        out += reg_common % sig + '''
%s {
    void* mem = FUN_0008d690(0x20);
    Function0<%s>* c = 0;
    if (mem)
        c = new (mem) Function0<%s>(name, fn);
    FUN_001d3b70(name, c);
}
''' % (sig.replace('void ' + reg, 'void Registry::' + reg), R, R)
    elif f1:
        R, A = split_args(f1.group(1))
        assert size == 0x20 and len(dats) == 2
        out += decl_for([R, A]) + base % ('0xc', '    char retType;\n    char pad_11[7];\n    char argType;\n    char pad_19[3];\n') + '''
template <class R, class A>
class Function1 : public MethodBase {
  public:
    typedef R (*Fn)(A);
    Function1(const char* name, Fn f) : MethodBase(name, 1) {
        fn = f;
        argType = FUN_001d04d0(%s);
        retType = FUN_001d04d0(%s);
    }
    Fn fn;
};
''' % (dats[0], dats[1])
        sig = 'void %s(const char* name, %s (*fn)(%s))' % (reg, R, A)
        out += reg_common % sig + '''
%s {
    void* mem = FUN_0008d690(0x20);
    Function1<%s, %s>* c = 0;
    if (mem)
        c = new (mem) Function1<%s, %s>(name, fn);
    FUN_001d3b70(name, c);
}
''' % (sig.replace('void ' + reg, 'void Registry::' + reg), R, A, R, A)
    else:
        raise SystemExit('unsupported shape ' + addr)
    return out

if __name__ == '__main__':
    os.makedirs(os.path.join(ROOT, 'out'), exist_ok=True)
    for a in sys.argv[1:]:
        open(os.path.join(ROOT, 'out', a + '.cpp'), 'w').write(gen(a))
