#!/usr/bin/env python3
"""Generate equivalence sources for factory-registration tables (0x00073700 and siblings).

Shape: `bool __cdecl F(Registry* r)` that calls FUN_xxx(r, "name") / FUN_xxx(r) in a long run, then
`fight::TrackFactoryCasterTemplate<T> c; r->FUN_002367c0(FUN_00236ac0("name", &c));` for each track
type, and ends with r->FUN_00236400(); return true. The statements are read in order from the
disassembly: `push STR; push esi; call X` is X(r, "str"), `push esi; call X` is X(r), a store of a
TrackFactoryCasterTemplate vftable before `call FUN_00236ac0` is the caster local.

usage: call_table.py 0xADDR [OUT]    (OUT defaults to build/farm/bench/claude-equiv/work/ADDR.cpp)
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from inlined_regs import parse_packet, packet, split_top, ROOT


def gen(addr):
    ins, strings, vft, funcs = parse_packet(packet(addr))
    body, decls0, decls1, classes = [], {}, {}, []
    pend = []          # pushed words since the last call
    movs = []          # vftable stores since the last call
    i, n = 0, len(ins)
    stmts = []
    while i < n:
        t = ins[i][1]
        if t.startswith('mov esi, dword ptr [esp'): pend = []
        m = re.match(r'push (esi|eax|ecx|edx|0x[0-9a-f]+)$', t)
        if m:
            pend.append(m.group(1))
        elif re.match(r'mov dword ptr \[esp(?: \+ (?:0x)?[0-9a-f]+)?\], (0x[0-9a-f]+)$', t):
            movs.append(int(t.rsplit(' ', 1)[1], 16))
        elif t.startswith('call '):
            c = t.split()[1]
            if c == 'FUN_00236ac0':
                assert len(movs) == 1 and 'TrackFactoryCasterTemplate' in vft[movs[0]], (hex(ins[i][0]), movs)
                name = int(pend[-1], 16)
                cls = re.match(r'fight::TrackFactoryCasterTemplate<(.*)>$', vft[movs[0]]).group(1)
                cls = re.sub(r'\b(class|struct)\s+', '', cls).strip()
                classes.append(cls)
                stmts.append(('caster', cls, strings[name]))
            elif c == 'FUN_002367c0':
                pass
            elif c == 'FUN_00236400':
                stmts.append(('done',))
            else:
                if pend[:2] == ['esi'] or pend == ['esi']:
                    assert pend == ['esi'], (hex(ins[i][0]), pend)
                    stmts.append(('call1', c))
                else:
                    assert len(pend) == 2 and pend[1] == 'esi' and int(pend[0], 16) in strings, (hex(ins[i][0]), pend, c)
                    stmts.append(('call2', c, strings[int(pend[0], 16)]))
            pend, movs = [], []
        i += 1
    ns = {}
    for c in dict.fromkeys(classes):
        parts = c.split('::')
        ns.setdefault(tuple(parts[:-1]), []).append(parts[-1])
    out = ['// FUN_%s @ %s  (generated by tools/equiv_gen/call_table.py)' % (addr[2:], addr)]
    for k, cs in ns.items():
        out.append(''.join('namespace %s { ' % p for p in k) + ' '.join('class %s;' % x for x in cs) + ''.join(' }' for _ in k))
    out += ['namespace fight { template<class T> struct TrackFactoryCasterTemplate { virtual void create(); }; }',
            'struct Registry { void FUN_002367c0(void*); void FUN_00236400(); };',
            'void* __cdecl FUN_00236ac0(const char*, void*);']
    seen = set()
    for s in stmts:
        if s[0] in ('call1', 'call2') and s[1] not in seen:
            seen.add(s[1])
            out.append('void __cdecl %s(Registry*%s);' % (s[1], ', const char*' if s[0] == 'call2' else ''))
    out.append('bool __cdecl FUN_%s(Registry* r) {' % addr[2:])
    for s in stmts:
        if s[0] == 'call1': out.append('    %s(r);' % s[1])
        elif s[0] == 'call2': out.append('    %s(r, "%s");' % (s[1], s[2]))
        elif s[0] == 'caster':
            out.append('    {\n        fight::TrackFactoryCasterTemplate<%s> caster;\n        r->FUN_002367c0(FUN_00236ac0("%s", &caster));\n    }' % (s[1], s[2]))
        elif s[0] == 'done': out.append('    r->FUN_00236400();')
    out += ['    return true;', '}']
    return '\n'.join(out) + '\n', len(stmts)


if __name__ == '__main__':
    addr = sys.argv[1]
    outp = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, '../../build/farm/bench/claude-equiv/work', addr + '.cpp')
    src, n = gen(addr)
    open(outp, 'w').write(src)
    print('%s: %d statements -> %s' % (addr, n, outp))
