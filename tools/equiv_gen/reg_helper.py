#!/usr/bin/env python3
"""Generate equivalence sources for the small `Registry::Register*(name, owner, fn)` helpers.

Each is: allocate 0x24 (or 0x20) bytes, call an out-of-line constructor on the block (args taken from
the helper's own stack arguments), optionally store a Closure vftable and the owner inline, then
registry->FUN_001d3b70(name, obj-or-0).  70-83 bytes, a few hundred of them (0x000301f0, 0x000303d0,
0x00042ad0, 0x001e35a0, ...).  The argument wiring is recovered by tracking the stack offset through
the disassembly.

usage: reg_helper.py 0xADDR... [-o DIR]     (default DIR build/farm/bench/claude-equiv/work)
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from inlined_regs import parse_packet, packet, parse_vft, ROOT


def gen(addr):
    ins, strings, vft, funcs = parse_packet(packet(addr))
    d = 0                      # bytes pushed since entry (callee-saved pushes included)
    regs = {}                  # register -> ('arg', i) | 'this' | ('ctor',) | ('eax-new',)
    regs['ecx'] = 'this'
    pend = []                  # pushed values since last call (as symbolic)
    ctor = size = None
    ctor_args = []
    vt = None
    own = None
    nargs = 0
    saved = 0
    entry_pushes = True
    ret = None
    log = []
    for off, t in ins:
        m = re.match(r'push (\w+)$', t)
        if m:
            v = m.group(1)
            if v in ('esi', 'edi', 'ebx', 'ebp') and entry_pushes:
                d += 4; continue          # callee-saved register save
            entry_pushes = False
            pend.append(regs.get(v, v)); d += 4; continue
        entry_pushes = entry_pushes and False if not t.startswith('mov') else entry_pushes
        m = re.match(r'mov (e\w\w), dword ptr \[esp \+ (0x[0-9a-f]+)\]$', t)
        if m:
            k = int(m.group(2), 16)
            regs[m.group(1)] = ('arg', (k - d) // 4)
            continue
        m = re.match(r'mov (e\w\w), (e\w\w)$', t)
        if m:
            regs[m.group(1)] = regs.get(m.group(2), m.group(2)); continue
        m = re.match(r'add esp, (0x[0-9a-f]+|\d+)$', t)
        if m:
            d -= int(m.group(1), 0); continue
        m = re.match(r'mov dword ptr \[(e\w\w)\], (0x[0-9a-f]+)$', t)
        if m and regs.get(m.group(1)) == 'obj':
            vt = int(m.group(2), 16); continue
        m = re.match(r'mov dword ptr \[(e\w\w) \+ 0x20\], (e\w\w)$', t)
        if m and regs.get(m.group(1)) == 'obj':
            own = regs[m.group(2)]; continue
        if t.startswith('call '):
            c = t.split()[1]
            if c == 'FUN_0008d690':
                size = int(pend.pop().replace('0x', '') if isinstance(pend[-1], str) else 0, 16) if False else int(str(pend.pop()), 16)
                d -= 0                      # cdecl, add esp follows
                regs['eax'] = 'obj'
            elif c == 'FUN_001d3b70':
                break
            else:
                if ctor is None:
                    ctor = c
                    ctor_args = pend[::-1]
                    regs['eax'] = 'obj'
                    d -= 4 * len(pend)
                    obj_via_ctor = True
            pend = []
    # the helper's own argument count from its `ret N`
    nret = None
    for off, t in ins:
        m = re.match(r'ret (0x[0-9a-f]+|\d+)$', t)
        if m: nret = int(m.group(1), 0) // 4
    assert ctor and size and nret, addr
    return emit(addr, ctor, size, ctor_args, vt, own, vft, nret)


def emit(addr, ctor, size, args, vt, own, vft, nparams):
    if vt:
        kind, n, targs = parse_vft(vft[vt])
        owner = targs[0]
    else:
        owner = 'Owner'
    for a in args:
        assert a[0] == 'arg', (addr, a)
    kinds = {1: 'const char*'}
    if own:
        kinds[own[1]] = owner + '*'
    for i in range(1, nparams + 1):
        kinds.setdefault(i, owner + '*' if (i == 2 and not own) else 'void (*)()')
    decl = []
    if vt:
        seen_t = set()
        for t in targs[1:]:
            b = re.sub(r'\bconst\b|\*|\bunsigned\b', '', t).strip()
            if b in ('void', 'int', 'float', 'bool', 'char', '') or b in seen_t: continue
            seen_t.add(b)
            if '::' in b:
                ns, c = b.rsplit('::', 1)
                decl.append('namespace %s { class %s { public: float x, y, z; }; }' % (ns, c))
            else:
                decl.append('class %s;' % b)
    o = ['// FUN_%s @ %s  (generated by tools/equiv_gen/reg_helper.py)' % (addr[2:], addr)] + decl + [
         'void* FUN_0008d690(unsigned int);',
         'inline void* operator new(unsigned int, void* p) throw() { return p; }',
         'class %s;' % owner]
    params = ', '.join('%s a%d' % (kinds[i], i) if '(*)' not in kinds[i] else 'void (*a%d)()' % i
                       for i in range(1, nparams + 1))
    sig_types = ', '.join(kinds[a[1]] for a in args)
    call = ', '.join('a%d' % a[1] for a in args)
    o.append('class Registry { public:')
    o.append('    void FUN_001d3b70(const char*, void*);')
    o.append('    void FUN_%s(%s);' % (addr[2:], params))
    o.append('};')
    if vt:
        tp = ''.join(', class A%d' % i for i in range(1, n + 1))
        o.append('template<class C, class R%s> class Closure%d;' % (tp, n))
        o.append('template<> class Closure%d<%s> { public: virtual void v(); char pad[0x1c]; %s* owner; '
                 'Closure%d(%s* o) { owner = o; } };' % (n, ', '.join(targs), owner, n, owner))
        o.append('class Raw { public: void %s(%s); };' % (ctor, sig_types))
        o.append('void Registry::FUN_%s(%s) {' % (addr[2:], params))
        o.append('    void* m = FUN_0008d690(0x%x);' % size)
        o.append('    void* x = 0;')
        o.append('    if (m) {')
        o.append('        ((Raw*)m)->%s(%s);' % (ctor, call))
        o.append('        x = new (m) Closure%d<%s>(a%d);' % (n, ', '.join(targs), own[1]))
        o.append('    }')
        o.append('    FUN_001d3b70(a1, x);')
        o.append('}')
    else:
        o.append('class Entry { public: void* %s(%s); };' % (ctor, sig_types))
        o.append('void Registry::FUN_%s(%s) {' % (addr[2:], params))
        o.append('    Entry* e = (Entry*)FUN_0008d690(0x%x);' % size)
        o.append('    void* x = 0;')
        o.append('    if (e)')
        o.append('        x = e->%s(%s);' % (ctor, call))
        o.append('    FUN_001d3b70(a1, x);')
        o.append('}')
    return '\n'.join(o) + '\n'


if __name__ == '__main__':
    args = sys.argv[1:]
    outd = os.path.join(ROOT, '../../build/farm/bench/claude-equiv/work')
    if '-o' in args:
        i = args.index('-o'); outd = args[i + 1]; del args[i:i + 2]
    for a in args:
        try:
            src = gen(a)
        except Exception as e:
            print(a, 'SKIP', repr(e)); continue
        open(os.path.join(outd, a + '.cpp'), 'w').write(src)
        print(a, 'ok')
