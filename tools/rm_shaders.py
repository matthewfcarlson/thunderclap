#!/usr/bin/env python3
"""The app runner's own bgfx shaders (src/platform/wasm/run/app/shaders; docs/lighting.md): compiled with bgfx's
shaderc into <gen>/rm_shaders.h, a table the runner's passes load from ({name, profile, data, size}).

  build/venv/bin/python tools/rm_shaders.py <gen dir> [--profiles metal,essl,spirv]

The faithful shaders (src/platform/sdl/pddi/shaders, tools/wine_gfx.py) are not touched: the runner's per-pixel
fragment shaders include shaders/vp/fs_vp_stage.sh, and each texture-stage combiner key of shaders/vp/combiners.txt
gets a per-pixel program fs_pxcmb_<hash> beside the faithful fs_cmb_<hash>. Outputs newer than their inputs are kept.
The binaries go to build/third_party/out/rm-shaders/<profile>/ (beside wine_gfx's out/shaders). Where there is no
shaderc (the queue's wasm hosts) the binaries there are embedded as they are: tools/wasm_build_job.py ships this
machine's out/rm-shaders/metal with the build's inputs, so compile them here first after a shader edit (`--shaders-ok`).
wasm_app.py's `build` runs this for the app (Metal); wasm_android.py asks for its profiles (spirv, essl)."""
import argparse
import os
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import wine_gfx  # noqa: E402

SRC = os.path.join(ROOT, "src/platform/wasm/run/app/shaders")
VP = os.path.join(wine_gfx.PDDI, "shaders", "vp")


def generate(gen_dir):
    """fs_pxcmb_<hash>.sc for every combiner key (the stages as constants, as wine_gfx's fs_cmb_<hash>)."""
    os.makedirs(gen_dir, exist_ok=True)
    names = []
    for key, h, example in wine_gfx.read_combiners():
        st = wine_gfx.parse_combiner(key)
        lines = ["$input v_pxbase, v_pxspec, v_fog, v_texcoord0, v_texcoord1, v_texcoord2, v_texcoord3, v_pxnormal, "
                 "v_pxpos", "",
                 "// generated by tools/rm_shaders.py: the combiner %s (first made by: %s), per-pixel lit" % (key, example),
                 "#define CMB_N %d" % len(st)]
        for i, (cop, ca1, ca2, aop, aa1, aa2, res) in enumerate(st):
            lines.append("#define CMB_K%d vec4(%d.0, %d.0, %d.0, %d.0)" % (i, cop, ca1, ca2, aop))
            lines.append("#define CMB_L%d vec4(%d.0, %d.0, %d.0, 0.0)" % (i, aa1, aa2, res))
        lines += ["#include <bgfx_shader.sh>", '#include "fs_px_stage.sh"', ""]
        text = "\n".join(lines)
        fn = "fs_pxcmb_%08x.sc" % h
        path = os.path.join(gen_dir, fn)
        if not os.path.exists(path) or open(path).read() != text:
            open(path, "w").write(text)
        names.append(fn)
    for fn in os.listdir(gen_dir):
        if fn.startswith("fs_pxcmb_") and fn.endswith(".sc") and fn not in names:
            os.unlink(os.path.join(gen_dir, fn))
    return names


OUT = os.path.join(wine_gfx.OUT, "rm-shaders")


def build(gen, profiles=("metal",)):
    sc = os.path.join(wine_gfx.TP, "tools/shaderc")
    if not os.path.exists(sc):
        return embed_prebuilt(gen, profiles)
    work = OUT
    srcgen = os.path.join(work, "src")
    units = [(SRC, fn) for fn in sorted(os.listdir(SRC)) if fn.endswith(".sc") and fn[:3] in ("vs_", "fs_")]
    units += [(srcgen, fn) for fn in generate(srcgen)]
    deps = [sc, os.path.join(SRC, "varying.def.sc")] + [os.path.join(d, f) for d in (SRC, VP) for f in os.listdir(d)
                                                        if f.endswith(".sh")]
    newest_dep = max(os.path.getmtime(f) for f in deps)
    jobs, outs = [], []
    for prof in profiles:
        plat, p = wine_gfx.SHADER_PROFILES[prof]
        od = os.path.join(work, prof)
        os.makedirs(od, exist_ok=True)
        for sd, fn in units:
            out = os.path.join(od, fn[:-3] + ".bin")
            outs.append((prof, fn[:-3], out))
            if os.path.exists(out) and os.path.getmtime(out) >= max(newest_dep, os.path.getmtime(os.path.join(sd, fn))):
                continue
            kind = {"vs": "vertex", "fs": "fragment"}[fn[:2]]
            jobs.append([sc, "-f", os.path.join(sd, fn), "-o", out, "--type", kind, "--platform", plat, "-p", p,
                         "-i", wine_gfx._bgfx("src"), "-i", SRC, "-i", VP, "--varyingdef",
                         os.path.join(SRC, "varying.def.sc")])

    def one(cmd):
        return cmd, subprocess.run(cmd, capture_output=True, text=True)

    failed = []
    with ThreadPoolExecutor(3) as ex:
        for cmd, r in ex.map(one, jobs):
            if r.returncode:
                if os.path.exists(cmd[4]):
                    os.unlink(cmd[4])
                failed.append("%s: %s" % (os.path.basename(cmd[2]), (r.stdout + r.stderr)[-1500:]))
    if failed:
        raise SystemExit("rm_shaders: %d failed\n%s" % (len(failed), "\n".join(failed[:3])))
    embed(gen, profiles, outs)
    print("rm_shaders: %d shaders x %s (%d compiled)" % (len(units), ",".join(profiles), len(jobs)))


def embed_prebuilt(gen, profiles):
    """No shaderc here: the binaries already in out/rm-shaders/<profile> (one per source and combiner key)."""
    names = [fn[:-3] for fn in sorted(os.listdir(SRC)) if fn.endswith(".sc") and fn[:3] in ("vs_", "fs_")]
    names += ["fs_pxcmb_%08x" % h for _k, h, _e in wine_gfx.read_combiners()]
    outs = []
    for prof in profiles:
        for n in names:
            path = os.path.join(OUT, prof, n + ".bin")
            if not os.path.exists(path):
                raise SystemExit("rm_shaders: no shaderc and no %s (compile the runner's shaders where shaderc is: "
                                 "tools/rm_shaders.py GEN --profiles %s)" % (path, ",".join(profiles)))
            outs.append((prof, n, path))
    embed(gen, profiles, outs)
    print("rm_shaders: %d shaders x %s (prebuilt: no shaderc here)" % (len(names), ",".join(profiles)))


def embed(gen, profiles, outs):
    lines = ["// generated by tools/rm_shaders.py from src/platform/wasm/run/app/shaders (%s)" % ", ".join(profiles)]
    table = []
    for prof, name, path in outs:
        data = open(path, "rb").read()
        sym = "g_rm_%s_%s" % (name, prof)
        table.append('    {"%s", "%s", %s, %d},' % (name, prof, sym, len(data)))
        lines.append("static const unsigned char %s[%d] = {" % (sym, len(data)))
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
    lines += ["struct RmEmbeddedShader { const char* name; const char* profile; const unsigned char* data; "
              "unsigned size; };", "static const RmEmbeddedShader g_rm_shaders[] = {"] + table + \
             ["    {0, 0, 0, 0},", "};"]
    text = "\n".join(lines) + "\n"
    hp = os.path.join(gen, "rm_shaders.h")
    os.makedirs(gen, exist_ok=True)
    if not os.path.exists(hp) or open(hp).read() != text:
        open(hp, "w").write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("gen")
    ap.add_argument("--profiles", default="metal")
    a = ap.parse_args(argv)
    build(a.gen, tuple(a.profiles.split(",")))


if __name__ == "__main__":
    main()
