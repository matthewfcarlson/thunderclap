#!/usr/bin/env python3
"""Make model-pack replacements (docs/model-replacement.md) from a dumped prim buffer, on the player's machine.

  mesh_remodel.py info   IN.obj
  mesh_remodel.py smooth IN.obj OUT.obj [--levels N]          # PN-triangle tessellation: same shape, rounder, more triangles
  mesh_remodel.py fit    IN.obj OUT.obj --shape cylinder|box [--segments N] [--ribs K] [--bevel F]
                                                              # each connected part -> a parametric solid in its bounds

IN.obj is a HULK_PACK_DUMP model (models/mdl-<key>.obj, the app's model space: docs/texture-packs.md "Models");
OUT.obj goes to <mods>/<pack>/models/ under the same name. The output keeps the original's texture: every new
triangle takes its UVs from the original triangle it lies over (nearest, facing the same way), so no new art is
needed. Normals are computed (smooth across edges under --smooth-angle degrees).

Everything this reads and writes is the player's own game data: keep it on their machine, never commit or share it.
The tool itself holds no game data. Needs numpy. Run with `python3 -I`.
"""
import argparse, math, sys

import numpy as np


# ------------------------------------------------------------------------------------------------ OBJ in / out
def read_obj(path):
    P, T, N, faces = [], [], [], []
    for line in open(path):
        s = line.split()
        if not s:
            continue
        if s[0] == "v":
            P.append([float(x) for x in s[1:4]])
        elif s[0] == "vt":
            T.append([float(x) for x in s[1:3]])
        elif s[0] == "vn":
            N.append([float(x) for x in s[1:4]])
        elif s[0] == "f":
            c = []
            for tok in s[1:]:
                r = (tok.split("/") + ["", ""])[:3]
                c.append(tuple(int(x) - 1 if x else -1 for x in r))
            for k in range(1, len(c) - 1):
                faces.append((c[0], c[k], c[k + 1]))
    return np.array(P, float), np.array(T, float).reshape(-1, 2), np.array(N, float).reshape(-1, 3), faces


def write_obj(path, P, UV, Nrm, tris, note):
    """P, UV, Nrm: per corner arrays (3 per triangle) -> an OBJ with welded v/vt/vn tables."""
    def weld(a, nd):
        keys = {}
        idx = []
        out = []
        for row in np.round(a, nd):
            k = tuple(row)
            if k not in keys:
                keys[k] = len(out)
                out.append(row)
            idx.append(keys[k])
        return np.array(out), idx
    vp, ip = weld(P, 6)
    vt, it = weld(UV, 6)
    vn, inn = weld(Nrm, 4)
    with open(path, "w") as f:
        f.write(f"# {note}\n# generated by tools/mesh_remodel.py from the player's own dump: local only, never share\n")
        for r in vp:
            f.write("v %.6g %.6g %.6g\n" % tuple(r))
        for r in vt:
            f.write("vt %.6g %.6g\n" % tuple(r))
        for r in vn:
            f.write("vn %.6g %.6g %.6g\n" % tuple(r))
        for t in range(tris):
            c = [3 * t + k for k in range(3)]
            f.write("f " + " ".join(f"{ip[i] + 1}/{it[i] + 1}/{inn[i] + 1}" for i in c) + "\n")
    return len(vp), tris


def corners(P, T, N, faces):
    """Per-corner positions, uvs, normals (missing uv/normal -> 0 / face normal)."""
    cp = np.array([[P[c[0]] for c in f] for f in faces])
    fn = np.cross(cp[:, 1] - cp[:, 0], cp[:, 2] - cp[:, 0])
    fn /= np.maximum(np.linalg.norm(fn, axis=1, keepdims=True), 1e-12)
    ct = np.array([[T[c[1]] if c[1] >= 0 and len(T) else (0.0, 0.0) for c in f] for f in faces])
    cn = np.array([[N[c[2]] if c[2] >= 0 and len(N) else fn[i] for c in f] for i, f in enumerate(faces)])
    return cp, ct, cn, fn


# ------------------------------------------------------------------------------------------------ UV transfer
class Projector:
    """UVs for new geometry from the original triangles: the nearest original triangle facing the same way
    (normal within 75 degrees, else any), extended linearly over its plane (barycentrics unclamped)."""

    def __init__(self, cp, ct, fn):
        self.a, self.b, self.c = cp[:, 0], cp[:, 1], cp[:, 2]
        self.t = ct
        self.fn = fn

    def nearest(self, q, n):
        # distance from q to each triangle (point projected to the plane, barycentrics clamped), facing penalty
        e0, e1 = self.b - self.a, self.c - self.a
        d = q - self.a
        d00, d01, d11 = (e0 * e0).sum(1), (e0 * e1).sum(1), (e1 * e1).sum(1)
        d20, d21 = (d * e0).sum(1), (d * e1).sum(1)
        den = np.where(np.abs(d00 * d11 - d01 * d01) < 1e-20, 1e-20, d00 * d11 - d01 * d01)
        v = np.clip((d11 * d20 - d01 * d21) / den, 0, 1)
        w = np.clip((d00 * d21 - d01 * d20) / den, 0, 1)
        s = v + w
        s = np.maximum(s, 1.0)
        v, w = v / s, w / s
        p = self.a + e0 * v[:, None] + e1 * w[:, None]
        dist = np.linalg.norm(q - p, axis=1)
        facing = (self.fn * n).sum(1)
        dist = dist + np.where(facing < 0.25, 1e3, 0.0)
        return int(np.argmin(dist))

    def uv(self, i, q):
        a, b, c = self.a[i], self.b[i], self.c[i]
        e0, e1, d = b - a, c - a, q - a
        d00, d01, d11, d20, d21 = e0 @ e0, e0 @ e1, e1 @ e1, d @ e0, d @ e1
        den = d00 * d11 - d01 * d01
        if abs(den) < 1e-20:
            return self.t[i, 0]
        v = (d11 * d20 - d01 * d21) / den
        w = (d00 * d21 - d01 * d20) / den
        return self.t[i, 0] * (1 - v - w) + self.t[i, 1] * v + self.t[i, 2] * w


def smooth_normals(cp, angle):
    """Per-corner normals: area-weighted face normals averaged over corners at the same position whose faces are
    within `angle` degrees (an auto-smooth)."""
    fnr = np.cross(cp[:, 1] - cp[:, 0], cp[:, 2] - cp[:, 0])
    fn = fnr / np.maximum(np.linalg.norm(fnr, axis=1, keepdims=True), 1e-12)
    groups = {}
    for t in range(len(cp)):
        for k in range(3):
            groups.setdefault(tuple(np.round(cp[t, k], 5)), []).append(t)
    cos = math.cos(math.radians(angle))
    out = np.zeros_like(cp)
    for t in range(len(cp)):
        for k in range(3):
            acc = np.zeros(3)
            for u in groups[tuple(np.round(cp[t, k], 5))]:
                if fn[u] @ fn[t] >= cos:
                    acc += fnr[u]
            out[t, k] = acc / max(np.linalg.norm(acc), 1e-12)
    return out


# ------------------------------------------------------------------------------------------------ smooth (PN triangles)
def pn_smooth(cp, ct, cn, levels):
    """Curved PN triangles (Vlachos et al. 2001) evaluated on a regular split of each triangle. A vertex whose
    duplicates (same position) disagree on the normal is a hard vertex: edges touching it stay straight, so
    neighbouring triangles never crack apart."""
    normals_at = {}
    for t in range(len(cp)):
        for k in range(3):
            normals_at.setdefault(tuple(np.round(cp[t, k], 5)), []).append(cn[t, k])
    hard = {key for key, ns in normals_at.items() if max(np.linalg.norm(n - ns[0]) for n in ns) > 1e-3}
    n = 2 ** levels
    P, UV, NN = [], [], []
    for t in range(len(cp)):
        p1, p2, p3 = cp[t]
        n1, n2, n3 = cn[t]
        hk = [tuple(np.round(cp[t, k], 5)) in hard for k in range(3)]

        def ctrl(pi, pj, ni, hi, hj):
            if hi or hj:
                return (2 * pi + pj) / 3
            w = (pj - pi) @ ni
            return (2 * pi + pj - w * ni) / 3
        b210, b120 = ctrl(p1, p2, n1, hk[0], hk[1]), ctrl(p2, p1, n2, hk[1], hk[0])
        b021, b012 = ctrl(p2, p3, n2, hk[1], hk[2]), ctrl(p3, p2, n3, hk[2], hk[1])
        b102, b201 = ctrl(p3, p1, n3, hk[2], hk[0]), ctrl(p1, p3, n1, hk[0], hk[2])
        E = (b210 + b120 + b021 + b012 + b102 + b201) / 6
        V = (p1 + p2 + p3) / 3
        b111 = E + (E - V) / 2

        def point(u, v):
            w = 1 - u - v
            pos = (p1 * w ** 3 + p2 * u ** 3 + p3 * v ** 3 + b210 * 3 * w * w * u + b120 * 3 * w * u * u
                   + b201 * 3 * w * w * v + b021 * 3 * u * u * v + b102 * 3 * w * v * v + b012 * 3 * u * v * v
                   + b111 * 6 * w * u * v)
            nrm = n1 * w + n2 * u + n3 * v
            return pos, ct[t, 0] * w + ct[t, 1] * u + ct[t, 2] * v, nrm / max(np.linalg.norm(nrm), 1e-12)
        grid = {(i, j): point(i / n, j / n) for i in range(n + 1) for j in range(n + 1 - i)}
        for i in range(n):
            for j in range(n - i):
                for tri in (((i, j), (i + 1, j), (i, j + 1)),) + ((((i + 1, j), (i + 1, j + 1), (i, j + 1)),)
                                                                if i + j + 1 < n else ()):
                    for key in tri:
                        pos, uv, nrm = grid[key]
                        P.append(pos), UV.append(uv), NN.append(nrm)
    return np.array(P), np.array(UV), np.array(NN)


# ------------------------------------------------------------------------------------------------ fit (parametric)
def components(cp):
    """Connected parts of the triangle soup (triangles sharing a position)."""
    parent = list(range(len(cp)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    seen = {}
    for t in range(len(cp)):
        for k in range(3):
            key = tuple(np.round(cp[t, k], 4))
            if key in seen:
                a, b = find(t), find(seen[key])
                if a != b:
                    parent[a] = b
            else:
                seen[key] = t
    out = {}
    for t in range(len(cp)):
        out.setdefault(find(t), []).append(t)
    return list(out.values())


def cylinder(lo, hi, segs, ribs):
    """A closed drum along y in the box lo..hi: side profile with `ribs` raised hoops (a steel drum), capped
    ends with a lip. Returns triangles as an (n, 3, 3) array (counter-clockwise seen from outside, right-handed)."""
    cx, cz = (lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2
    r = min(hi[0] - lo[0], hi[2] - lo[2]) / 2
    y0, y1 = lo[1], hi[1]
    h = y1 - y0
    # profile (radius, y) from bottom centre to top centre
    prof = [(0.0, y0 + 0.01 * h), (r * 0.94, y0 + 0.01 * h), (r * 0.97, y0), (r, y0 + 0.03 * h)]
    for k in range(1, ribs + 1):
        yc = y0 + h * k / (ribs + 1)
        prof += [(r, yc - 0.03 * h), (r * 1.025, yc - 0.012 * h), (r * 1.025, yc + 0.012 * h), (r, yc + 0.03 * h)]
    prof += [(r, y1 - 0.03 * h), (r * 0.97, y1), (r * 0.94, y1 - 0.01 * h), (0.0, y1 - 0.01 * h)]
    ring = [(math.cos(2 * math.pi * s / segs), math.sin(2 * math.pi * s / segs)) for s in range(segs)]
    tris = []
    for a in range(len(prof) - 1):
        (ra, ya), (rb, yb) = prof[a], prof[a + 1]
        for s in range(segs):
            c0, c1 = ring[s], ring[(s + 1) % segs]
            q = [np.array([cx + ra * c0[0], ya, cz + ra * c0[1]]), np.array([cx + ra * c1[0], ya, cz + ra * c1[1]]),
                 np.array([cx + rb * c1[0], yb, cz + rb * c1[1]]), np.array([cx + rb * c0[0], yb, cz + rb * c0[1]])]
            if ra > 0:
                tris.append((q[0], q[3], q[1]))
            if rb > 0:
                tris.append((q[1], q[3], q[2]))
    return np.array(tris)


def bevel_box(lo, hi, bevel):
    """A box with chamfered edges and corners (bevel = fraction of the smallest side): the convex hull of the six
    faces inset by the bevel."""
    c, half = (lo + hi) / 2, (hi - lo) / 2
    inner = np.maximum(half - bevel * float(np.min(hi - lo)), 1e-6)
    pts = []
    for ax in range(3):
        u, v = [k for k in range(3) if k != ax]
        for sgn in (-1, 1):
            for su in (-1, 1):
                for sv in (-1, 1):
                    p = c.copy()
                    p[ax] += sgn * half[ax]
                    p[u] += su * inner[u]
                    p[v] += sv * inner[v]
                    pts.append(p)
    return np.array([t for t in convex_hull(np.array(pts))])


def convex_hull(pts):
    """Brute-force hull of a few dozen points: every triangle with all points on its inner side."""
    import itertools
    c = pts.mean(0)
    out, seen = [], set()
    for i, j, k in itertools.combinations(range(len(pts)), 3):
        a, b, d = pts[i], pts[j], pts[k]
        n = np.cross(b - a, d - a)
        if np.linalg.norm(n) < 1e-9:
            continue
        side = (pts - a) @ n
        if (side <= 1e-7).all() or (side >= -1e-7).all():
            if (c - a) @ n > 0:
                a, b, d = a, d, b
                n = -n
            key = tuple(sorted((i, j, k)))
            plane = tuple(np.round(n / np.linalg.norm(n), 4)) + (round(float(n @ a / np.linalg.norm(n)), 4),)
            out.append((a, b, d, plane))
    # coplanar facets: keep a fan triangulation per plane (drop triangles covering others)
    by_plane = {}
    for a, b, d, plane in out:
        by_plane.setdefault(plane, []).append((a, b, d))
    res = []
    for plane, ts in by_plane.items():
        verts = np.unique(np.round(np.array([p for t in ts for p in t]), 7), axis=0)
        n = np.array(plane[:3])
        cen = verts.mean(0)
        ref = verts[0] - cen
        ref /= np.linalg.norm(ref)
        ang = [math.atan2(np.cross(ref, p - cen) @ n, ref @ (p - cen)) for p in verts]
        ring = verts[np.argsort(ang)]
        for k in range(1, len(ring) - 1):
            res.append((ring[0], ring[k], ring[k + 1]))
    return res


# ------------------------------------------------------------------------------------------------ commands
def cmd_info(a):
    P, T, N, faces = read_obj(a.inp)
    cp, ct, cn, fn = corners(P, T, N, faces)
    parts = components(cp)
    print(f"{len(P)} positions, {len(faces)} triangles, {len(parts)} parts, bounds {P.min(0)} .. {P.max(0)}")
    for k, part in enumerate(sorted(parts, key=len, reverse=True)[:20]):
        q = cp[part].reshape(-1, 3)
        print(f"  part {k}: {len(part)} triangles, bounds {np.round(q.min(0), 3)} .. {np.round(q.max(0), 3)}")


def cmd_smooth(a):
    P, T, N, faces = read_obj(a.inp)
    cp, ct, cn, fn = corners(P, T, N, faces)
    if not len(N):
        cn = smooth_normals(cp, a.smooth_angle)
    p, uv, nn = pn_smooth(cp, ct, cn, a.levels)
    v, t = write_obj(a.out, p, uv, nn, len(p) // 3, f"PN-smoothed ({a.levels} levels) {a.inp.split('/')[-1]}")
    print(f"{len(faces)} -> {t} triangles, {v} positions -> {a.out}")


def cmd_fit(a):
    P, T, N, faces = read_obj(a.inp)
    cp, ct, cn, fn = corners(P, T, N, faces)
    proj = Projector(cp, ct, fn)
    out = []
    for part in components(cp):
        q = cp[part].reshape(-1, 3)
        lo, hi = q.min(0), q.max(0)
        if len(part) < a.min_tris:
            out.append(cp[part])               # small details stay as they are
            continue
        out.append(cylinder(lo, hi, a.segments, a.ribs) if a.shape == "cylinder" else bevel_box(lo, hi, a.bevel))
    tris = np.concatenate(out)
    nn = smooth_normals(tris, a.smooth_angle)
    uv = np.zeros((len(tris), 3, 2))
    for t in range(len(tris)):
        fnrm = np.cross(tris[t, 1] - tris[t, 0], tris[t, 2] - tris[t, 0])
        fnrm /= max(np.linalg.norm(fnrm), 1e-12)
        i = proj.nearest(tris[t].mean(0), fnrm)
        for k in range(3):
            uv[t, k] = proj.uv(i, tris[t, k])
    v, n = write_obj(a.out, tris.reshape(-1, 3), uv.reshape(-1, 2), nn.reshape(-1, 3), len(tris),
                     f"{a.shape} fit of {a.inp.split('/')[-1]}")
    print(f"{len(faces)} -> {n} triangles, {v} positions -> {a.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("info")
    s.add_argument("inp")
    s = sub.add_parser("smooth")
    s.add_argument("inp"), s.add_argument("out")
    s.add_argument("--levels", type=int, default=2)
    s.add_argument("--smooth-angle", type=float, default=50)
    s = sub.add_parser("fit")
    s.add_argument("inp"), s.add_argument("out")
    s.add_argument("--shape", choices=("cylinder", "box"), required=True)
    s.add_argument("--segments", type=int, default=32)
    s.add_argument("--ribs", type=int, default=2)
    s.add_argument("--bevel", type=float, default=0.06)
    s.add_argument("--min-tris", type=int, default=8)
    s.add_argument("--smooth-angle", type=float, default=40)
    a = ap.parse_args()
    {"info": cmd_info, "smooth": cmd_smooth, "fit": cmd_fit}[a.cmd](a)


if __name__ == "__main__":
    main()
